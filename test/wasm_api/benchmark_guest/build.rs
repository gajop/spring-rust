use std::{env, fs, path::PathBuf};

fn interface_body(source: &str) -> &str {
    source
        .split_once("\n\n")
        .map(|(_, body)| body)
        .unwrap_or(source)
}

fn context_benchmark_source(source: &str, context: &str, generated_wit: &PathBuf) -> String {
    if context == "unsynced_gadget" {
        let (interfaces, _) = source
            .split_once("world rules-unsynced {")
            .expect("rules-unsynced world in parity WIT");
        return format!(
            "{interfaces}world rules-unsynced {{\n  import messages;\n  import profiling;\n  import units-info;\n  import units-query;\n  export callins-rules-unsynced;\n}}\n"
        );
    }

    if context == "ui" {
        let read_interface = |name: &str| {
            let path = generated_wit.join(name);
            interface_body(&fs::read_to_string(path).expect("read generated UI WIT")).to_owned()
        };
        let messages =
            read_interface("messages-rules-synced-rules-unsynced-gaia-synced-gaia-unsynced-ui.wit")
                .replace(
                    "interface messages-rules-synced-rules-unsynced-gaia-synced-gaia-unsynced-ui",
                    "interface messages",
                );
        let profiling = read_interface(
            "profiling-rules-synced-rules-unsynced-gaia-synced-gaia-unsynced-ui.wit",
        )
        .replace(
            "interface profiling-rules-synced-rules-unsynced-gaia-synced-gaia-unsynced-ui",
            "interface profiling",
        );
        // This guest deliberately implements only DrawWorld.  Component
        // callins are optional exports, so keeping the benchmark interface
        // minimal avoids a large no-op implementation while retaining the
        // canonical package/interface/callin path used by the engine.
        let callins = r#"interface callins-ui {
  record spring-error { code: s32 }

  record simple-callin-query {
    unused: u8,
  }

  draw-world: func(query: simple-callin-query) -> result<_, spring-error>;
}
"#;
        return format!(
            "package recoil:spring-api@1.0.0;\n\n{}\n{}\n{}\n{}\nworld ui {{\n  import gfx;\n  import messages;\n  import profiling;\n  export callins-ui;\n  export callback-1: func(user-data: u32);\n}}\n",
            callins,
            read_interface("gfx.wit"),
            messages,
            profiling,
        );
    }

    source.to_owned()
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let benchmark_context =
        env::var("SPRING_BENCHMARK_CONTEXT").unwrap_or_else(|_| "synced_gadget".to_owned());
    let scale = env::var("SPRING_BENCHMARK_SCALE").unwrap_or_else(|_| "1.0".to_owned());
    let benchmark_case = env::var("SPRING_BENCHMARK_CASE").unwrap_or_default();
    let benchmark_iterations =
        env::var("SPRING_BENCHMARK_ITERATIONS").unwrap_or_else(|_| "0".to_owned());
    let benchmark_repeats = env::var("SPRING_BENCHMARK_REPEATS").unwrap_or_else(|_| "5".to_owned());
    let benchmark_callin_variant =
        env::var("SPRING_BENCHMARK_CALLIN_VARIANT").unwrap_or_else(|_| "empty".to_owned());
    println!("cargo:rustc-check-cfg=cfg(benchmark_context_unsynced)");
    println!("cargo:rustc-check-cfg=cfg(benchmark_context_ui)");
    println!("cargo:rustc-check-cfg=cfg(benchmark_callin_unimplemented)");
    if benchmark_callin_variant == "unimplemented" {
        println!("cargo:rustc-cfg=benchmark_callin_unimplemented");
    }
    let parity_path = manifest.join("../parity_guest/wit/parity.wit");
    // Profiling is split by execution-environment applicability.  The timer
    // is the one profiling callout intentionally present in both synced and
    // unsynced worlds, so use the generated mixed-world interface rather than
    // reintroducing a hand-maintained aggregate interface.
    let profiling_path = manifest.join(
        "../../../rts/wasm/generated/wit/profiling-rules-synced-rules-unsynced-gaia-synced-gaia-unsynced-ui.wit",
    );
    let generated_wit = manifest.join("../../../rts/wasm/generated/wit");
    let base_source = fs::read_to_string(&parity_path).expect("read parity WIT");
    if benchmark_context == "unsynced_gadget" || benchmark_context == "ui" {
        // The unsynced and UI benchmark rows use the context-specific parity
        // WIT generated by generate_probe.py.  It already contains the
        // profiling, unit-query, and callin surfaces needed by the bounded
        // memory/rendering profiles.  Keep the context world intact so the
        // component advertises the same environment as the host adapter.
        fs::create_dir_all(manifest.join("wit")).expect("create benchmark WIT directory");
        let context_source =
            context_benchmark_source(&base_source, &benchmark_context, &generated_wit);
        fs::write(manifest.join("wit/benchmark.wit"), context_source)
            .expect("write context benchmark WIT");
        match benchmark_context.as_str() {
            "unsynced_gadget" => println!("cargo:rustc-cfg=benchmark_context_unsynced"),
            "ui" => println!("cargo:rustc-cfg=benchmark_context_ui"),
            _ => unreachable!(),
        }
    }
    let mut base = interface_body(&base_source).to_string();
    let profiling_source = fs::read_to_string(&profiling_path).expect("read profiling WIT");
    let profiling = interface_body(&profiling_source).replace(
        "interface profiling-rules-synced-rules-unsynced-gaia-synced-gaia-unsynced-ui",
        "interface profiling",
    );
    let rules_params = r#"interface rules-params {
  record spring-error { code: s32 }

  record rules-param-value {
    %type: rules-param-type,
  }

  enum rules-param-type {
    rulesparam-type-bool,
    rulesparam-type-float,
    rulesparam-type-string,
  }

  record get-unit-rules-param-value {
    value: rules-param-value,
    los: s32,
    exists: bool,
  }

  /// read-only
  get-unit-rules-param: func(unit-id: s32, param-name: string) -> result<get-unit-rules-param-value, spring-error>;

  /// mutating
  set-unit-rules-param: func(unit-id: s32, param-name: string, value: rules-param-value, los: s32) -> result<bool, spring-error>;
}
"#;
    let terrain = r#"interface terrain-control {
  record spring-error { code: s32 }

  set-terrain-type-data: func(type-index: s32, tank-speed: f32, kbot-speed: f32, hover-speed: f32, ship-speed: f32, hardness: f32, receive-tracks: bool, name: string) -> result<bool, spring-error>;
  set-tidal: func(tidal: f32) -> result<bool, spring-error>;
  set-wind: func(min-wind: f32, max-wind: f32) -> result<bool, spring-error>;
  set-height-map: func(x: f32, z: f32, height: f32, terraform: f32) -> result<bool, spring-error>;
  set-height-map-func: func(callback: u32, user-data: u32) -> result<bool, spring-error>;
  level-height-map: func(x1: f32, z1: f32, x2: f32, z2: f32, height: f32) -> result<bool, spring-error>;
}
"#;
    let old_terrain = "interface terrain-control {\n  record spring-error { code: s32 }\n\n  set-terrain-type-data: func(type-index: s32, tank-speed: f32, kbot-speed: f32, hover-speed: f32, ship-speed: f32, hardness: f32, receive-tracks: bool, name: string) -> result<bool, spring-error>;\n  set-tidal: func(tidal: f32) -> result<bool, spring-error>;\n  set-wind: func(min-wind: f32, max-wind: f32) -> result<bool, spring-error>;\n}\n";
    base = base.replace(old_terrain, terrain);
    base = base.replace(
        "interface unit-control {\n  record spring-error { code: s32 }\n",
        "interface unit-control {\n  record spring-error { code: s32 }\n\n  /// mutating\n  give-order-to-unit: func(unit-id: s32, cmd-id: s32, params: list<f32>, options: u32, timeout: s32) -> result<bool, spring-error>;\n",
    );
    base = base.replace(
        "interface units-info {\n  record spring-error { code: s32 }\n",
        "interface units-info {\n  record spring-error { code: s32 }\n\n  record unit-health {\n    health: f32,\n    max-health: f32,\n    paralyze-damage: f32,\n    capture-progress: f32,\n    build-progress: f32,\n  }\n",
    );
    base = base.replace(
        "  get-unit-height: func(unit-id: s32) -> result<f32, spring-error>;\n",
        "  get-unit-health: func(unit-id: s32) -> result<unit-health, spring-error>;\n  get-unit-height: func(unit-id: s32) -> result<f32, spring-error>;\n",
    );
    base = base.replace("world rules-synced {", "world benchmark-rules-synced {");
    base = base.replace(
        "  import messages;\n",
        "  import messages;\n  import profiling;\n  import rules-params;\n",
    );
	let callin_exports = if benchmark_callin_variant == "unimplemented" {
		"  export callback-1: func(user-data: u32);\n}"
	} else {
		"  export callins-rules-synced;\n  export callback-1: func(user-data: u32);\n}"
	};
	base = base.replace(
		"  export callins-rules-synced;\n}",
		callin_exports,
	);
    let output = format!("package recoil:spring-api@1.0.0;\n\n{profiling}\n{rules_params}\n{base}");
    let wit_dir = manifest.join("wit");
    fs::create_dir_all(&wit_dir).expect("create benchmark WIT directory");
    if benchmark_context != "unsynced_gadget" && benchmark_context != "ui" {
        fs::write(wit_dir.join("benchmark.wit"), output).expect("write benchmark WIT");
    }
    println!("cargo:rerun-if-changed={}", parity_path.display());
    println!("cargo:rerun-if-changed={}", profiling_path.display());
    println!("cargo:rerun-if-env-changed=SPRING_BENCHMARK_SCALE");
    println!("cargo:rerun-if-env-changed=SPRING_BENCHMARK_CASE");
    println!("cargo:rerun-if-env-changed=SPRING_BENCHMARK_ITERATIONS");
    println!("cargo:rerun-if-env-changed=SPRING_BENCHMARK_REPEATS");
    println!("cargo:rerun-if-env-changed=SPRING_BENCHMARK_CALLIN_VARIANT");
    println!("cargo:rerun-if-env-changed=SPRING_BENCHMARK_CONTEXT");
    println!("cargo:rustc-env=SPRING_BENCHMARK_SCALE={scale}");
    println!("cargo:rustc-env=SPRING_BENCHMARK_CASE={benchmark_case}");
    println!("cargo:rustc-env=SPRING_BENCHMARK_ITERATIONS={benchmark_iterations}");
    println!("cargo:rustc-env=SPRING_BENCHMARK_REPEATS={benchmark_repeats}");
    println!("cargo:rustc-env=SPRING_BENCHMARK_CALLIN_VARIANT={benchmark_callin_variant}");
}
