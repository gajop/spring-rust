"""Generate private native API table copies and zero/no-op mutants from the model."""
import argparse
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[2]

def render(root):
 model=json.loads((root/'rts/wasm/generated/model.json').read_text())
 manifest=(root/'rust/crates/spring-native-codegen/src/manifest.rs').read_text()
 definitions={m:(h,a) for m,h,a in re.findall(r'module: "([^"]+)",\s*header: "([^"]+)",\s*api_struct: "([^"]*)"',manifest) if a}
 source=(root/'rts/NativeInterface/NativeInterface.h').read_text()+'\n'+'\n'.join(p.read_text() for p in (root/'rts/NativeInterface/api').glob('*.h'))
 structs={name:body for name,body in re.findall(r'struct ((?:\w+Api|NativeInterface))\s*\{(.*?)\};',source,re.S)}
 paths={};parents={}
 def visit(type_,path,parent=None,field=None):
  for child,member in re.findall(r'const\s+(\w+Api)\s*\*\s*(\w+)\s*;',structs[type_]):
   child_path=path+('->' if path else '')+member
   paths[child]=(child_path,'table'+str(len(paths)));parents[child]=(parent,member)
   visit(child,child_path,paths[child][1],member)
 visit('NativeInterface','')
 lines=['/* This file is part of the Spring engine (GPL v2 or later), see LICENSE.html */',
  '// Generated by generate_mutants.py. Do not edit.','#pragma once','#include "NativeInterface/NativeInterface.h"','#include <string_view>',
  'struct NativeApiMutants {','\tNativeInterface api{};']
 for type_,(path,var) in paths.items():lines.append(f'\t{type_} {var}{{}};')
 lines+=['\texplicit NativeApiMutants(const NativeInterface& source) { Reset(source); }','\tvoid Reset(const NativeInterface& source) {','\t\tapi=source;']
 for type_,(path,var) in paths.items():lines.append(f'\t\t{var}=*source.{path};')
 for type_,(path,var) in paths.items():
  parent,member=parents[type_];lines.append(f'\t\t{parent or "api"}.{member}=&{var};')
 lines+=['\t}','\ttemplate<typename Q,typename R> static void Zero(const Q*,R* result) { *result={}; }',
  '\ttemplate<typename Q,typename R> static void Noop(const Q*,R* result) { *result={}; if constexpr (requires { result->success; }) result->success=true; }',
  '\tbool Select(std::string_view module,std::string_view function,bool noop=false) {']
 count=0
 for module in model['modules']:
  if not module['functions']:continue
  _,type_=definitions[module['name']]
  if type_ not in paths:raise ValueError(f'unreachable API table {type_}')
  var=paths[type_][1]
  for f in module['functions']:
   q,r=f['query'],f['result'];name=f['name']
   lines.append(f'\t\tif (module=="{module["name"]}" && function=="{name}") {{ {var}.{name}=noop ? Noop<{q},{r}> : Zero<{q},{r}>; return true; }}')
   count+=1
 lines+=['\t\treturn false;','\t}',f'\tstatic constexpr unsigned FunctionCount={count};','};','']
 return '\n'.join(lines)

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,default=ROOT);p.add_argument('--output',type=Path,default=ROOT/'test/native_api_parity/generated/NativeApiMutants.h');p.add_argument('--check',action='store_true');a=p.parse_args()
 text=render(a.root)
 if a.check:
  if not a.output.exists() or a.output.read_text()!=text:raise SystemExit('native API mutants are stale')
 else:a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(text)
 print('Native API mutant inventory:',text.count('function=='),'functions')
if __name__=='__main__':main()
