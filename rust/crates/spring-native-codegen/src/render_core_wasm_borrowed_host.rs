//! Allocation-free Core-Wasm lowering for synchronous variable-input callouts.
//!
//! The NativeInterface query contract makes ordinary input pointers call-scoped.
//! This renderer therefore borrows validated guest memory directly for strings,
//! bytes and scalar/enum lists. Complex element records and list<string> remain
//! outside this renderer because their native layout requires adaptation.

