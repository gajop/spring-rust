//! Scoped, target-independent SDK. Public signatures come from the semantic
//! facade; native bodies call the real NativeInterface tables directly.

use crate::model::{ApiModel, ApiModule, FieldModel, SemanticType};
use crate::{ApiSpec, CType, CodeGenerator, FieldDef, StructDef};
use anyhow::{Context, Result, anyhow, bail};
