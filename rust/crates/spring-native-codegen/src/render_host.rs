fn unique_records<'a>(model: &'a ApiModel) -> BTreeMap<String, &'a RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records.entry(record.name.clone()).or_insert(record);
        }
    }
    records
}

fn unique_enums<'a>(model: &'a ApiModel) -> BTreeMap<String, &'a crate::model::EnumModel> {
    let mut enums = BTreeMap::new();
    for module in &model.modules {
        for enum_model in &module.enums {
            enums.entry(enum_model.name.clone()).or_insert(enum_model);
        }
    }
    enums
}

fn record_owners(model: &ApiModel) -> BTreeMap<String, String> {
    let mut owners = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            owners
                .entry(record.name.clone())
                .or_insert_with(|| module.name.clone());
        }
    }
    owners
}

fn simple_type(
    ty: &SemanticType,
    records: &BTreeMap<String, &RecordModel>,
    seen: &mut Vec<String>,
) -> bool {
    match ty {
        SemanticType::Scalar { .. }
        | SemanticType::Enum { .. }
        | SemanticType::String
        | SemanticType::Bytes => true,
        SemanticType::Record { name } => {
            if seen.iter().any(|value| value == name) {
                return false;
            }
            let Some(record) = records.get(name) else {
                return false;
            };
            if matches!(
                record.status,
                LoweringStatus::Manual | LoweringStatus::Unsupported
            ) {
                return false;
            }
            seen.push(name.clone());
            let result = record
                .fields
                .iter()
                .all(|field| simple_type(&field.ty, records, seen));
            seen.pop();
            result
        }
        SemanticType::List { element }
        | SemanticType::FixedArray { element, .. }
        | SemanticType::Option { inner: element } => simple_type(element, records, seen),
        SemanticType::Result { .. }
        | SemanticType::Handle { .. }
        | SemanticType::Callback { .. }
        | SemanticType::Pointer { .. }
        | SemanticType::Unknown { .. } => false,
    }
}

fn simple_record(
    record: &RecordModel,
    records: &BTreeMap<String, &RecordModel>,
    seen: &mut Vec<String>,
) -> bool {
    if matches!(
        record.status,
        LoweringStatus::Manual | LoweringStatus::Unsupported
    ) {
        return false;
    }
    seen.push(record.name.clone());
    let result = record
        .fields
        .iter()
        .all(|field| simple_type(&field.ty, records, seen));
    seen.pop();
    result
}

fn function_is_simple(
    function: &crate::model::FunctionModel,
    records: &BTreeMap<String, &RecordModel>,
) -> bool {
    function
        .inputs
        .iter()
        .chain(&function.outputs)
        .all(|field| simple_type(&field.ty, records, &mut Vec::new()))
}

fn function_identifier(module: &str, function: &str) -> String {
    format!("Dispatch_{}_{}", sanitize(module), sanitize(function))
}

fn sanitize(value: &str) -> String {
    value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character
            } else {
                '_'
            }
        })
        .collect()
}

fn render_record_reader(
    output: &mut String,
    record: &RecordModel,
    _records: &BTreeMap<String, &RecordModel>,
) {
    if record.name == "RulesParamValue" {
        render_rules_param_value_reader(output);
        return;
    }

    output.push_str(&format!(
        "bool Read_{}(const WasmValue& input, {}& output, NativeCallStorage& storage, std::string& error)\n{{\n",
        sanitize(&record.name),
        record.name
    ));
    output.push_str("\tconst auto* record = std::get_if<WasmValueRecord>(&input.storage);\n\tif (record == nullptr) { error = \"Wasm argument is not a record\"; return false; }\n");
    for field in &record.fields {
        let stem = sanitize(&field.name);
        let wit_name = render_wit::wit_runtime_identifier(&field.name);
        output.push_str(&format!(
            "\tconst auto* value_{} = FindRecordField(*record, \"{}\", error);\n\tif (value_{} == nullptr) return false;\n",
            stem, wit_name, stem
        ));
        output.push_str(&render_read_value(
            field,
            &format!("*value_{}", stem),
            &format!("output.{}", field.name),
            "output",
            "storage",
            "return false;",
        ));
    }
    output.push_str("\treturn true;\n}\n\n");
}

fn render_enum_helpers(enum_model: &crate::model::EnumModel) -> String {
    let name = sanitize(&enum_model.name);
    let mut output = format!(
		"inline bool ReadEnum_{name}(const WasmValue& input, {cpp_name}& output, std::string& error)\n{{\n",
		name = name,
		cpp_name = enum_model.name,
	);
    output.push_str(
		"\tconst auto* enum_name = std::get_if<std::string>(&input.storage);\n\tif (enum_name == nullptr) { error = \"Wasm argument is not an enum name\"; return false; }\n",
	);
    for (variant, value) in &enum_model.variants {
        output.push_str(&format!(
            "\tif (*enum_name == \"{}\") {{ output = static_cast<{}>({}); return true; }}\n",
            render_wit::wit_runtime_identifier(variant),
            enum_model.name,
            value,
        ));
    }
    output
        .push_str("\terror = \"unknown Wasm enum value: \" + *enum_name;\n\treturn false;\n}\n\n");

    output.push_str(&format!(
        "inline WasmValue WriteEnum_{name}(const {cpp_name}& value)\n{{\n",
        name = name,
        cpp_name = enum_model.name,
    ));
    for (variant, value) in &enum_model.variants {
        output.push_str(&format!(
            "\tif (value == static_cast<{}>({})) return WasmValue::String(\"{}\");\n",
            enum_model.name,
            value,
            render_wit::wit_runtime_identifier(variant),
        ));
    }
    output.push_str("\treturn WasmValue::String(\"unknown\");\n}\n\n");
    output
}

fn render_record_writer(
    output: &mut String,
    record: &RecordModel,
    _records: &BTreeMap<String, &RecordModel>,
) {
    if record.name == "RulesParamValue" {
        render_rules_param_value_writer(output);
        return;
    }

    output.push_str(&format!(
        "WasmValue Write_{}(const {}& value)\n{{\n\tWasmValueRecord fields;\n",
        sanitize(&record.name),
        record.name
    ));
    for field in &record.fields {
        let wit_name = render_wit::wit_runtime_identifier(&field.name);
        output.push_str(&format!(
            "\tfields.emplace(\"{}\", {});\n",
            wit_name,
            write_field_expression(field, "value")
        ));
    }
    output.push_str("\treturn WasmValue::Record(std::move(fields));\n}\n\n");
}

fn render_rules_param_value_reader(output: &mut String) {
    output.push_str(
		"bool Read_RulesParamValue(const WasmValue& input, RulesParamValue& output, NativeCallStorage& storage, std::string& error)\n"
	);
    output.push_str("{\n\tconst auto* record = std::get_if<WasmValueRecord>(&input.storage);\n");
    output.push_str(
        "\tif (record == nullptr) { error = \"Wasm argument is not a record\"; return false; }\n",
    );
    output.push_str("\tconst auto* value_type = FindRecordField(*record, \"type\", error);\n");
    output.push_str(
		"\tif (value_type == nullptr || !ReadEnum_RulesParamType(*value_type, output.type, error)) return false;\n"
	);
    output.push_str("\tswitch (output.type) {\n");
    output.push_str(
		"\t\tcase RULESPARAM_TYPE_BOOL: {\n\t\t\tconst auto* value_bool = FindRecordField(*record, \"bool-value\", error);\n\t\t\treturn value_bool != nullptr && ReadScalar(*value_bool, output.boolValue, error);\n\t\t}\n"
	);
    output.push_str(
		"\t\tcase RULESPARAM_TYPE_FLOAT: {\n\t\t\tconst auto* value_float = FindRecordField(*record, \"float-value\", error);\n\t\t\treturn value_float != nullptr && ReadScalar(*value_float, output.floatValue, error);\n\t\t}\n"
	);
    output.push_str(
		"\t\tcase RULESPARAM_TYPE_STRING: {\n\t\t\tconst auto* value_string = FindRecordField(*record, \"string-value\", error);\n\t\t\tif (value_string == nullptr) return false;\n\t\t\tauto& stored_string = storage.Make<std::string>();\n\t\t\tif (!ReadString(*value_string, stored_string, error)) return false;\n\t\t\toutput.stringValue = stored_string.c_str();\n\t\t\treturn true;\n\t\t}\n"
	);
    output.push_str(
        "\t\tdefault: error = \"unknown RulesParamValue type\"; return false;\n\t}\n}\n\n",
    );
}

fn render_rules_param_value_writer(output: &mut String) {
    output.push_str(
		"WasmValue Write_RulesParamValue(const RulesParamValue& value)\n{\n\tWasmValueRecord fields;\n"
	);
    output.push_str("\tfields.emplace(\"type\", WriteEnum_RulesParamType(value.type));\n");
    output.push_str(
		"\tfields.emplace(\"bool-value\", value.type == RULESPARAM_TYPE_BOOL ? WriteScalar(value.boolValue) : WasmValue::Bool(false));\n"
	);
    output.push_str(
		"\tfields.emplace(\"float-value\", value.type == RULESPARAM_TYPE_FLOAT ? WriteScalar(value.floatValue) : WasmValue::F64(0.0));\n"
	);
    output.push_str(
		"\tfields.emplace(\"string-value\", value.type == RULESPARAM_TYPE_STRING && value.stringValue != nullptr ? WasmValue::String(std::string(value.stringValue)) : WasmValue::String(std::string{}));\n"
	);
    output.push_str("\treturn WasmValue::Record(std::move(fields));\n}\n\n");
}

fn render_read_value(
    field: &FieldModel,
    value_expression: &str,
    target_expression: &str,
    owner_expression: &str,
    storage_expression: &str,
    failure: &str,
) -> String {
    match &field.ty {
        SemanticType::Scalar { .. }
        | SemanticType::Enum { .. }
        | SemanticType::Record { .. }
        | SemanticType::String => render_read_type(
            &field.ty,
            value_expression,
            target_expression,
            storage_expression,
            failure,
        ),
        SemanticType::Bytes | SemanticType::List { .. } => render_read_list(
            &field.ty,
            field,
            value_expression,
            target_expression,
            owner_expression,
            storage_expression,
            failure,
        ),
        SemanticType::FixedArray { element, length } => render_read_fixed_array(
            element,
            *length,
            &sanitize(&field.name),
            value_expression,
            target_expression,
            storage_expression,
            failure,
        ),
        SemanticType::Option { inner } => {
            let Some(presence) = presence_field(field) else {
                unreachable!("supported option is missing a presence field")
            };
            let reset = if matches!(inner.as_ref(), SemanticType::FixedArray { .. }) {
                format!("ResetNativeArray({});", target_expression)
            } else {
                format!("{} = {{}};", target_expression)
            };
            let mut output = format!(
                "\tif (std::holds_alternative<std::monostate>(({}).storage)) {{\n\t\t{}\n\t\t{}.{} = false;\n\t}} else {{\n\t\t{}.{} = true;\n",
                value_expression,
                reset,
                owner_expression,
                presence,
                owner_expression,
                presence
            );
            for line in render_read_type(
                inner,
                value_expression,
                target_expression,
                storage_expression,
                failure,
            )
            .lines()
            {
                output.push_str("\t");
                output.push_str(line);
                output.push('\n');
            }
            output.push_str("\t}\n");
            output
        }
        _ => unreachable!("unsupported field reached generated Wasm adapter"),
    }
}

fn render_read_type(
    ty: &SemanticType,
    value_expression: &str,
    target_expression: &str,
    storage_expression: &str,
    failure: &str,
) -> String {
    let call = match ty {
        SemanticType::Scalar { .. } => {
            format!(
                "ReadScalar({}, {}, error)",
                value_expression, target_expression
            )
        }
        SemanticType::Enum { name } => format!(
            "ReadEnum_{}({}, {}, error)",
            sanitize(name),
            value_expression,
            target_expression
        ),
        SemanticType::Record { name } => format!(
            "Read_{}({}, {}, {}, error)",
            sanitize(name),
            value_expression,
            target_expression,
            storage_expression
        ),
        SemanticType::String => {
            let storage_name = format!("stored_string_{}", sanitize(target_expression));
            return format!(
                "\tauto& {} = {}.Make<std::string>();\n\tif (!ReadString({}, {}, error)) {{ {} }}\n\t{} = {}.c_str();\n",
                storage_name,
                storage_expression,
                value_expression,
                storage_name,
                failure,
                target_expression,
                storage_name
            );
        }
        SemanticType::FixedArray { element, length } => {
            return render_read_fixed_array(
                element,
                *length,
                &format!("array_{}", sanitize(target_expression)),
                value_expression,
                target_expression,
                storage_expression,
                failure,
            );
        }
        _ => unreachable!("render_read_type called for a compound field"),
    };
    format!("\tif (!{}) {{ {} }}\n", call, failure)
}

fn render_read_list(
    ty: &SemanticType,
    field: &FieldModel,
    value_expression: &str,
    target_expression: &str,
    owner_expression: &str,
    storage_expression: &str,
    failure: &str,
) -> String {
    if is_byte_list(ty) {
        let stem = sanitize(&field.name);
        let count = count_field(field).expect("supported list is missing its count field");
        return format!(
            "\tauto& native_{} = {}.Make<std::vector<std::uint8_t>>();\n\tif (!ReadByteList({}, native_{}, error)) {{ {} }}\n\t{} = reinterpret_cast<decltype({})>(native_{}.data());\n\tif (!AssignCount(native_{}.size(), {}.{}, error)) {{ {} }}\n",
            stem,
            storage_expression,
            value_expression,
            stem,
            failure,
            target_expression,
            target_expression,
            stem,
            stem,
            owner_expression,
            count,
            failure,
        );
    }
    let element = match ty {
        SemanticType::Bytes => SemanticType::Scalar {
            name: "u8".to_string(),
        },
        SemanticType::List { element } => (**element).clone(),
        _ => unreachable!("render_read_list called for a non-list"),
    };
    let stem = sanitize(&field.name);
    let element_cpp = cpp_type(&element);
    let storage_cpp = cpp_storage_type(&element);
    let count = count_field(field).expect("supported list is missing its count field");
    let mut output = format!(
        "\tconst auto* list_{} = std::get_if<WasmValueList>(&({}).storage);\n\tif (list_{} == nullptr) {{ error = \"Wasm argument is not a list\"; {} }}\n\tauto& native_{} = {}.Make<std::vector<{}>>();\n\tnative_{}.reserve(list_{}->size());\n",
        stem,
        value_expression,
        stem,
        failure,
        stem,
        storage_expression,
        storage_cpp,
        stem,
        stem
    );
    output.push_str(&format!(
        "\tfor (const auto& item : *list_{}) {{\n\t\t{} item_value{{}};\n",
        stem, element_cpp
    ));
    output.push_str(&indent_lines(
        &render_read_type(&element, "item", "item_value", storage_expression, failure),
        1,
    ));
    let push_expression = if matches!(&element, SemanticType::Scalar { name } if name == "bool") {
        "item_value ? 1u : 0u".to_string()
    } else {
        "std::move(item_value)".to_string()
    };
    output.push_str(&format!(
        "\t\tnative_{}.push_back({});\n\t}}\n",
        stem, push_expression
    ));
    if matches!(element, SemanticType::String) {
        output.push_str(&format!(
            "\tauto& pointers_{} = {}.Make<std::vector<const char*>>();\n\tpointers_{}.reserve(native_{}.size());\n\tfor (const auto& item : native_{}) pointers_{}.push_back(item.c_str());\n\t{} = pointers_{}.data();\n",
            stem,
            storage_expression,
            stem,
            stem,
            stem,
            stem,
            target_expression,
            stem
        ));
    } else if matches!(ty, SemanticType::Bytes)
        || matches!(&element, SemanticType::Scalar { name } if name == "bool")
    {
        output.push_str(&format!(
            "\t{} = reinterpret_cast<decltype({})>(native_{}.data());\n",
            target_expression, target_expression, stem
        ));
    } else {
        output.push_str(&format!(
            "\t{} = native_{}.data();\n",
            target_expression, stem
        ));
    }
    output.push_str(&format!(
        "\tif (!AssignCount(list_{}->size(), {}.{}, error)) {{ {} }}\n",
        stem, owner_expression, count, failure
    ));
    output
}

fn is_byte_list(ty: &SemanticType) -> bool {
    matches!(ty, SemanticType::Bytes)
        || matches!(ty, SemanticType::List { element } if matches!(element.as_ref(), SemanticType::Scalar { name } if name == "u8"))
}

fn render_read_fixed_array(
    element: &SemanticType,
    length: u64,
    stem: &str,
    value_expression: &str,
    target_expression: &str,
    storage_expression: &str,
    failure: &str,
) -> String {
    let mut output = format!(
        "\tconst auto* array_values_{} = std::get_if<WasmValueList>(&({}).storage);\n\tif (array_values_{} == nullptr || array_values_{}->size() != {}u) {{ error = \"Wasm fixed array has the wrong length\"; {} }}\n\tfor (std::size_t index = 0; index < {}u; ++index) {{\n",
        stem, value_expression, stem, stem, length, failure, length
    );
    output.push_str(&indent_lines(
        &render_read_type(
            element,
            &format!("(*array_values_{})[index]", stem),
            &format!("{}[index]", target_expression),
            storage_expression,
            failure,
        ),
        1,
    ));
    output.push_str("\t}\n");
    output
}

fn indent_lines(value: &str, additional: usize) -> String {
    let prefix = "\t".repeat(additional);
    value
        .lines()
        .map(|line| format!("{}{}\n", prefix, line))
        .collect()
}

fn count_field(field: &FieldModel) -> Option<String> {
    field.metadata.iter().find_map(|metadata| {
        metadata
            .strip_prefix("count-field:")
            .map(ToString::to_string)
    })
}

fn presence_field(field: &FieldModel) -> Option<String> {
    field.metadata.iter().find_map(|metadata| {
        metadata
            .strip_prefix("presence-field:")
            .map(ToString::to_string)
    })
}

fn cpp_type(ty: &SemanticType) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i8" => "std::int8_t".to_string(),
            "i16" => "std::int16_t".to_string(),
            "i32" => "std::int32_t".to_string(),
            "u8" | "char" => "std::uint8_t".to_string(),
            "u16" => "std::uint16_t".to_string(),
            "u32" => "std::uint32_t".to_string(),
            "u64" => "std::uint64_t".to_string(),
            "bool" => "bool".to_string(),
            "f32" => "float".to_string(),
            _ => "std::int64_t".to_string(),
        },
        SemanticType::Enum { name } | SemanticType::Record { name } => name.clone(),
        SemanticType::String => "std::string".to_string(),
        SemanticType::Bytes => "std::uint8_t".to_string(),
        _ => unreachable!("compound type cannot be used as a native list element"),
    }
}

fn cpp_storage_type(ty: &SemanticType) -> String {
    if matches!(ty, SemanticType::Scalar { name } if name == "bool") {
        "std::uint8_t".to_string()
    } else {
        cpp_type(ty)
    }
}

fn write_field_expression(field: &FieldModel, owner_expression: &str) -> String {
    let target = format!("{}.{}", owner_expression, field.name);
    match &field.ty {
        SemanticType::Scalar { .. }
        | SemanticType::Enum { .. }
        | SemanticType::Record { .. }
        | SemanticType::String => write_expression(&field.ty, &target),
        SemanticType::Bytes | SemanticType::List { .. } => {
            let count = count_field(field).expect("supported list is missing its count field");
            let element = match &field.ty {
                SemanticType::Bytes => SemanticType::Scalar {
                    name: "u8".to_string(),
                },
                SemanticType::List { element } => (**element).clone(),
                _ => unreachable!(),
            };
            format!(
                "WriteNativeList({}, {}.{}, {})",
                target,
                owner_expression,
                count,
                write_lambda(&element, matches!(&field.ty, SemanticType::Bytes))
            )
        }
        SemanticType::FixedArray { element, .. } => format!(
            "WriteNativeArray({}, {})",
            target,
            write_lambda(element, false)
        ),
        SemanticType::Option { inner } => {
            let presence = presence_field(field).expect("supported option is missing presence");
            format!(
                "{}.{} ? {} : WasmValue::Unit()",
                owner_expression,
                presence,
                write_expression(inner, &target)
            )
        }
        _ => unreachable!("unsupported field reached generated Wasm writer"),
    }
}

fn write_lambda(ty: &SemanticType, bytes: bool) -> String {
    if bytes {
        return "[](const auto& value) { return WriteScalar(static_cast<std::uint8_t>(value)); }"
            .to_string();
    }
    let expression = match ty {
        SemanticType::Scalar { .. } => "WriteScalar(value)".to_string(),
        SemanticType::Enum { name } => format!("WriteEnum_{}(value)", sanitize(name)),
        SemanticType::Record { name } => format!("Write_{}(value)", sanitize(name)),
        SemanticType::String => {
            "WasmValue::String(value == nullptr ? std::string{} : std::string(value))".to_string()
        }
        _ => unreachable!("unsupported list/array element writer"),
    };
    format!("[](const auto& value) {{ return {}; }}", expression)
}

fn render_native_function(
    output: &mut String,
    module: &ApiModule,
    function: &crate::model::FunctionModel,
    path: &str,
    api_type: &str,
    function_id: &str,
    _records: &BTreeMap<String, &RecordModel>,
) {
    output.push_str(&format!("NativeCalloutDispatch {}(NativeInterface* nativeInterface, const std::vector<WasmValue>& arguments, WasmValue& result, std::string& error)\n{{\n", function_id));
    let guard = native_api_guard(path, &function.name);
    output.push_str(&format!("\tif ({}) {{ error = \"NativeInterface API is unavailable: {}.{}\"; return NativeCalloutDispatch::handled; }}\n", guard, module.name, function.name));
    output.push_str(&format!(
        "\tNativeCallStorage storage;\n\t{} query{{}};\n\t{} nativeResult{{}};\n",
        function.query, function.result
    ));

    let logical_inputs: Vec<&FieldModel> = function
        .inputs
        .iter()
        .filter(|field| field.name != "_unused")
        .collect();
    let logical_count = logical_inputs.len();
    let raw_count = function.inputs.len();
    for (raw_index, field) in function.inputs.iter().enumerate() {
        let logical_index = logical_inputs
            .iter()
            .position(|item| item.name == field.name)
            .unwrap_or(0);
        let target = format!("query.{}", field.name);
        let wit_name = render_wit::wit_runtime_identifier(&field.name);
        match &field.ty {
			SemanticType::Scalar { .. } => output.push_str(&format!("\tif (!ReadArgument(arguments, {}u, {}u, {}u, {}u, \"{}\", {}, error)) return NativeCalloutDispatch::handled;\n", logical_index, raw_index, logical_count, raw_count, wit_name, target)),
			SemanticType::Enum { name } => {
				let value_name = format!("value_{}", sanitize(&field.name));
				output.push_str(&format!("\tconst WasmValue* {} = FindArgument(arguments, {}u, {}u, {}u, {}u, \"{}\", error);\n\tif ({} == nullptr) return NativeCalloutDispatch::handled;\n", value_name, logical_index, raw_index, logical_count, raw_count, wit_name, value_name));
				output.push_str(&format!("\tif (!ReadEnum_{}(*{}, {}, error)) return NativeCalloutDispatch::handled;\n", sanitize(name), value_name, target));
			},
			SemanticType::Record { name } => output.push_str(&format!("\tif (!ReadRecordArgument(arguments, {}u, {}u, {}u, {}u, \"{}\", Read_{}, {}, storage, error)) return NativeCalloutDispatch::handled;\n", logical_index, raw_index, logical_count, raw_count, wit_name, sanitize(name), target)),
			_ => {
				let value_name = format!("value_{}", sanitize(&field.name));
				output.push_str(&format!("\tconst WasmValue* {} = FindArgument(arguments, {}u, {}u, {}u, {}u, \"{}\", error);\n\tif ({} == nullptr) return NativeCalloutDispatch::handled;\n", value_name, logical_index, raw_index, logical_count, raw_count, wit_name, value_name));
				output.push_str(&render_read_value(field, &format!("*{}", value_name), &target, "query", "storage", "return NativeCalloutDispatch::handled;"));
			}
		}
    }
    output.push_str(
        &format!(
            "\t{}->{}->{}(&query, &nativeResult);\n",
            path, "", function.name
        )
        .replace("->->", "->"),
    );
    output.push_str(
        "\tif (!CheckNativeError(nativeResult, error)) return NativeCalloutDispatch::handled;\n",
    );
    match function.outputs.as_slice() {
        [] => output.push_str("\tresult = WasmValue::Unit();\n"),
        [field] => output.push_str(&format!(
            "\tresult = {};\n",
            write_field_expression(field, "nativeResult")
        )),
        fields => {
            output.push_str("\tWasmValueRecord outputFields;\n");
            for field in fields {
                let wit_name = render_wit::wit_runtime_identifier(&field.name);
                output.push_str(&format!(
                    "\toutputFields.emplace(\"{}\", {});\n",
                    wit_name,
                    write_field_expression(field, "nativeResult")
                ));
            }
            output.push_str("\tresult = WasmValue::Record(std::move(outputFields));\n");
        }
    }
    output.push_str("\treturn NativeCalloutDispatch::handled;\n}\n\n");
    let _ = api_type;
}

fn native_api_guard(path: &str, function: &str) -> String {
    let components: Vec<&str> = path.split("->").collect();
    let mut current = components[0].to_string();
    let mut checks = vec![format!("{} == nullptr", current)];
    for component in components.iter().skip(1) {
        current.push_str("->");
        current.push_str(component);
        checks.push(format!("{} == nullptr", current));
    }
    checks.push(format!("{}->{} == nullptr", current, function));
    checks.join(" || ")
}

fn write_expression(ty: &SemanticType, expression: &str) -> String {
    match ty {
        SemanticType::Scalar { .. } => {
            format!("WriteScalar({})", expression)
        }
        SemanticType::Enum { name } => {
            format!("WriteEnum_{}({})", sanitize(name), expression)
        }
        SemanticType::Record { name } => format!("Write_{}({})", sanitize(name), expression),
        SemanticType::String => format!(
            "WasmValue::String(({} == nullptr) ? std::string{{}} : std::string({}))",
            expression, expression
        ),
        SemanticType::FixedArray { element, .. } => {
            format!(
                "WriteNativeArray({}, {})",
                expression,
                write_lambda(element, false)
            )
        }
        _ => unreachable!("write_expression called for a compound output"),
    }
}

