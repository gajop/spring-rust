//! Generated owned Rust façade used by Wasm guests.
//!
//! The façade deliberately performs the semantic conversion at its boundary:
//! module code sees strings, vectors, options and records, while the selected
//! backend only sees [`spring_wasm::Value`] values.  This keeps the generated
//! API useful for both a native mock backend and the eventual Component Model
//! backend.

use heck::ToSnakeCase;
use std::collections::BTreeMap;

use crate::model::{ApiModel, EnumModel, FieldModel, RecordModel, SemanticType};

pub fn render(model: &ApiModel) -> String {
    let mut output = String::from("// @generated by spring-api-codegen; do not edit.\n\n");
    // The artifact is included at the root of the spring-wasm façade, so its
    // public transport names are already in scope.  Use fully qualified
    // standard-library names where needed to keep the artifact include-safe.
    output.push('\n');
    output.push_str(
        "fn generated_missing_field(name: &str) -> ApiError {\n    ApiError::with_detail(101, crate::ErrorCategory::Internal, format!(\"missing generated field {name}\"))\n}\n\n",
    );

    let records = unique_records(model);
    for record in records.values() {
        render_record(&mut output, record);
    }
    let output_records = unique_output_records(model);
    for (name, fields) in output_records {
        if !records.contains_key(&name) {
            render_record_fields(&mut output, &name, &fields);
        }
    }
    let enums = unique_enums(model);
    for enum_model in enums.values() {
        render_enum(&mut output, enum_model);
    }

    for module in &model.modules {
        output.push_str(&format!(
            "#[allow(dead_code, non_camel_case_types)]\npub struct {}<'a, B: CalloutBackend> {{\n    backend: &'a mut B,\n}}\n\n",
            module_ident(&module.name)
        ));
        output.push_str(&format!(
            "impl<'a, B: CalloutBackend> {}<'a, B> {{\n",
            module_ident(&module.name)
        ));
        output.push_str(
            "    pub fn new(backend: &'a mut B) -> Self {\n        Self { backend }\n    }\n\n",
        );
        for function in &module.functions {
            render_function(&mut output, &module.name, function);
        }
        output.push_str("}\n\n");
    }
    // Keep generated artifacts free of a blank line at EOF. This matters for
    // reproducible source checks and avoids whitespace errors in new files.
    if output.ends_with("\n\n") {
        output.pop();
    }
    output
}

fn unique_records<'a>(model: &'a ApiModel) -> BTreeMap<String, &'a RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records.entry(record.name.clone()).or_insert(record);
        }
    }
    records
}

fn unique_enums<'a>(model: &'a ApiModel) -> BTreeMap<String, &'a EnumModel> {
    let mut enums = BTreeMap::new();
    for module in &model.modules {
        for enum_model in &module.enums {
            enums.entry(enum_model.name.clone()).or_insert(enum_model);
        }
    }
    enums
}

fn unique_output_records(model: &ApiModel) -> BTreeMap<String, Vec<FieldModel>> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for function in &module.functions {
            if function.outputs.len() > 1 {
                records
                    .entry(format!("{}Value", type_ident(&function.name)))
                    .or_insert_with(|| function.outputs.clone());
            }
        }
    }
    records
}

fn render_record(output: &mut String, record: &RecordModel) {
    render_record_fields(output, &record.name, &record.fields);
}

fn render_record_fields(output: &mut String, name: &str, fields: &[FieldModel]) {
    output.push_str(
        "#[allow(dead_code, non_camel_case_types)]\n#[derive(Debug, Clone, PartialEq)]\n",
    );
    output.push_str(&format!("pub struct {} {{\n", type_ident(name)));
    for field in fields {
        output.push_str(&format!(
            "    pub {}: {},\n",
            rust_ident(&field.name),
            rust_type(&field.ty)
        ));
    }
    output.push_str("}\n\n");

    let binding = if fields.is_empty() {
        "fields"
    } else {
        "mut fields"
    };
    output.push_str(&format!(
        "impl IntoValue for {} {{\n    fn into_value(self) -> Value {{\n        let {binding} = std::collections::BTreeMap::new();\n",
        type_ident(name)
    ));
    for field in fields {
        output.push_str(&format!(
            "        fields.insert({:?}.to_string(), self.{}.into_value());\n",
            field.name,
            rust_ident(&field.name)
        ));
    }
    output.push_str("        Value::Record(fields)\n    }\n}\n\n");

    let binding = if fields.is_empty() {
        "fields"
    } else {
        "mut fields"
    };
    output.push_str(&format!(
        "#[allow(unused_variables)]\nimpl FromValue for {} {{\n    fn from_value(value: Value) -> Result<Self, ApiError> {{\n        let Value::Record({binding}) = value else {{ return Err(ApiError::with_detail(102, crate::ErrorCategory::Internal, \"expected record\")); }};\n        Ok(Self {{\n",
        type_ident(name)
    ));
    for field in fields {
        output.push_str(&format!(
            "            {}: FromValue::from_value(fields.remove({:?}).ok_or_else(|| generated_missing_field({:?}))?)?,\n",
            rust_ident(&field.name),
            field.name,
            field.name
        ));
    }
    output.push_str("        })\n    }\n}\n\n");
}

fn render_enum(output: &mut String, enum_model: &EnumModel) {
    output.push_str(
        "#[allow(dead_code, non_camel_case_types)]\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n",
    );
    output.push_str(&format!(
        "pub struct {}(pub i64);\n\n",
        type_ident(&enum_model.name)
    ));
    output.push_str(&format!(
        "#[allow(non_upper_case_globals)]\nimpl {} {{\n",
        type_ident(&enum_model.name)
    ));
    for (variant, value) in &enum_model.variants {
        output.push_str(&format!(
            "    pub const {}: Self = Self({});\n",
            rust_ident(variant),
            value
        ));
    }
    output.push_str("}\n\n");
    output.push_str(&format!(
        "impl IntoValue for {} {{\n    fn into_value(self) -> Value {{ Value::I64(self.0) }}\n}}\n\n",
        type_ident(&enum_model.name)
    ));
    output.push_str(&format!(
        "#[allow(unreachable_patterns)]\nimpl FromValue for {} {{\n    fn from_value(value: Value) -> Result<Self, ApiError> {{\n        let value = i64::from_value(value)?;\n        match value {{\n",
        type_ident(&enum_model.name)
    ));
    for (variant, value) in &enum_model.variants {
        output.push_str(&format!(
            "            {} => Ok(Self::{}),\n",
            value,
            rust_ident(variant)
        ));
    }
    output.push_str(
        "            _ => Err(ApiError::with_detail(103, crate::ErrorCategory::InvalidArgument, \"unknown enum value\")),\n        }\n    }\n}\n\n",
    );
}

fn render_function(output: &mut String, module_name: &str, function: &crate::model::FunctionModel) {
    let params = function
        .inputs
        .iter()
        .map(|field| format!("{}: {}", rust_ident(&field.name), rust_type(&field.ty)))
        .collect::<Vec<_>>();
    let return_type = return_type(function);
    let arguments = function
        .inputs
        .iter()
        .map(|field| format!("{}.into_value()", rust_ident(&field.name)))
        .collect::<Vec<_>>()
        .join(", ");
    let method = rust_ident(&function.name);
    output.push_str(&format!(
        "    pub fn {method}(&mut self{})-> Result<{return_type}, ApiError> {{\n        let arguments = vec![{arguments}];\n        let value = self.backend.call({:?}, &arguments)?;\n        FromValue::from_value(value)\n    }}\n\n",
        if params.is_empty() {
            String::new()
        } else {
            format!(", {}", params.join(", "))
        },
        format!("{}.{}", module_name, function.name)
    ));
}

fn return_type(function: &crate::model::FunctionModel) -> String {
    match function.outputs.as_slice() {
        [] => "()".to_string(),
        [field] => rust_type(&field.ty),
        _ => format!("{}Value", type_ident(&function.name)),
    }
}

fn rust_type(ty: &SemanticType) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "char" => "u8".to_string(),
            "void" => "()".to_string(),
            other => other.to_string(),
        },
        SemanticType::Enum { name } | SemanticType::Record { name } => {
            format!("crate::{}", type_ident(name))
        }
        SemanticType::String => "String".to_string(),
        SemanticType::Bytes => "Vec<u8>".to_string(),
        SemanticType::List { element } => format!("Vec<{}>", rust_type(element)),
        SemanticType::FixedArray { element, length } => {
            format!("[{}; {}]", rust_type(element), length)
        }
        SemanticType::Option { inner } => format!("Option<{}>", rust_type(inner)),
        SemanticType::Result { ok, .. } => ok
            .as_deref()
            .map(rust_type)
            .unwrap_or_else(|| "()".to_string()),
        SemanticType::Handle { .. } => "u64".to_string(),
        SemanticType::Callback { .. } => "u32".to_string(),
        // These statuses are retained in the generated registry for manual
        // adapters.  The temporary public type is an opaque integer so the
        // generated artifact remains inspectable and type-checkable.
        SemanticType::Pointer { .. } | SemanticType::Unknown { .. } => "u32".to_string(),
    }
}

fn module_ident(name: &str) -> String {
    rust_ident(name)
}

fn type_ident(name: &str) -> String {
    name.to_string()
}

fn rust_ident(name: &str) -> String {
    let ident = name.to_snake_case();
    if is_rust_keyword(&ident) {
        format!("r#{ident}")
    } else {
        ident
    }
}

fn is_rust_keyword(value: &str) -> bool {
    matches!(
        value,
        "as" | "async"
            | "await"
            | "box"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "do"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "final"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "macro"
            | "mod"
            | "move"
            | "mut"
            | "override"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "Self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "try"
            | "type"
            | "unsafe"
            | "unsized"
            | "use"
            | "where"
            | "while"
            | "union"
            | "typeof"
            | "virtual"
            | "yield"
    )
}
