fn render_fixed_forward(
    output: &mut String,
    function: &FunctionModel,
    records: &BTreeMap<String, &RecordModel>,
    enums: &BTreeMap<String, &EnumModel>,
    module_ident: &str,
) {
    let params = function
        .inputs
        .iter()
        .map(|field| {
            format!(
                "{}: {}",
                rust_ident(&field.name),
                rust_param_type(&field.ty, records, enums)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let args = function
        .inputs
        .iter()
        .map(|field| {
            convert_to_core(
                &field.ty,
                &rust_ident(&field.name),
                records,
                enums,
                module_ident,
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let core_path = format!(
        "crate::generated::{module_ident}::{}",
        rust_ident(&function.name)
    );
    let body = match function.outputs.as_slice() {
        [] => format!("{core_path}({args})?;\n            Ok(())"),
        [field] => format!(
            "let value = {core_path}({args})?;\n            Ok({})",
            convert_from_core(&field.ty, "value", records, enums),
        ),
        fields => {
            let values = fields
                .iter()
                .enumerate()
                .map(|(index, field)| {
                    let value = format!("value.{index}");
                    format!(
                        "{}: {}",
                        rust_ident(&field.name),
                        convert_from_core(&field.ty, &value, records, enums)
                    )
                })
                .collect::<Vec<_>>()
                .join(",\n                ");
            format!(
                "let value = {core_path}({args})?;\n            Ok({}Value {{\n                {values}\n            }})",
                function.name
            )
        }
    };
    let return_type = match function.outputs.as_slice() {
        [] => "()".to_owned(),
        [field] => rust_type(&field.ty, records, enums),
        _ => format!("{}Value", function.name),
    };
    let arity_lint = too_many_arguments_attribute(function.inputs.len(), 8);
    output.push_str(&format!(
        "        #[inline]\n        {arity_lint}pub fn {}({params}) -> Result<{return_type}> {{\n            {body}\n        }}\n\n",
        rust_ident(&function.name),
        arity_lint = arity_lint,
    ));
}

fn convert_to_core(
    ty: &SemanticType,
    expression: &str,
    records: &BTreeMap<String, &RecordModel>,
    enums: &BTreeMap<String, &EnumModel>,
    module_ident: &str,
) -> String {
    match ty {
        SemanticType::Enum { name } => {
            let enum_model = enums[name];
            let arms = enum_model
                .variants
                .iter()
                .map(|(variant, value)| {
                    format!(
                        "{}::{variant_ident} => {value}i32",
                        name,
                        variant_ident = enum_variant_ident(name, variant)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("match {expression} {{ {arms} }}")
        }
        SemanticType::Record { name } => {
            let record = records[name];
            let fields = record
                .fields
                .iter()
                .map(|field| {
                    let field_name = rust_ident(&field.name);
                    format!(
                        "{field_name}: {}",
                        convert_to_core(
                            &field.ty,
                            &format!("{expression}.{field_name}"),
                            records,
                            enums,
                            module_ident
                        )
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("crate::generated::{module_ident}::{name} {{ {fields} }}")
        }
        SemanticType::FixedArray { .. } => format!(
            "{expression}.to_vec().try_into().map_err(|_| crate::ApiError::new(crate::ErrorCode::InvalidArgument as i32))?"
        ),
        _ => expression.to_owned(),
    }
}

fn convert_from_core(
    ty: &SemanticType,
    expression: &str,
    records: &BTreeMap<String, &RecordModel>,
    enums: &BTreeMap<String, &EnumModel>,
) -> String {
    match ty {
        SemanticType::Enum { name } => {
            let enum_model = enums[name];
            let arms = enum_model
                .variants
                .iter()
                .map(|(variant, value)| {
                    format!(
                        "{value} => Ok({name}::{variant_ident})",
                        name = name,
                        variant_ident = enum_variant_ident(name, variant)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "match {expression} {{ {arms}, _ => Err(crate::ApiError::new(crate::ErrorCode::Internal as i32)) }}?"
            )
        }
        SemanticType::Record { name } => {
            let record = records[name];
            let fields = record
                .fields
                .iter()
                .map(|field| {
                    let field_name = rust_ident(&field.name);
                    format!(
                        "{field_name}: {}",
                        convert_from_core(
                            &field.ty,
                            &format!("{expression}.{field_name}"),
                            records,
                            enums
                        )
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("{name} {{ {fields} }}")
        }
        SemanticType::FixedArray { element, .. } => {
            let converted = convert_from_core(element, "value", records, enums);
            if converted == "value" {
                format!("{expression}.into_iter().collect::<Vec<_>>()")
            } else {
                format!(
                    "{expression}.into_iter().map(|value| Ok({converted})).collect::<crate::Result<Vec<_>>>()?"
                )
            }
        }
        _ => expression.to_owned(),
    }
}

fn rust_type(
    ty: &SemanticType,
    records: &BTreeMap<String, &RecordModel>,
    enums: &BTreeMap<String, &EnumModel>,
) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "char" => "u8".to_owned(),
            "void" => "()".to_owned(),
            other => other.to_owned(),
        },
        SemanticType::Enum { name } => {
            if enums.contains_key(name) {
                name.to_owned()
            } else {
                "i32".to_owned()
            }
        }
        SemanticType::Record { name } => {
            if records.contains_key(name) {
                name.to_owned()
            } else {
                "u32".to_owned()
            }
        }
        SemanticType::String => "String".to_owned(),
        SemanticType::Bytes => "Vec<u8>".to_owned(),
        SemanticType::List { element } => {
            format!("Vec<{}>", rust_type(element, records, enums))
        }
        // The semantic Core façade follows the WIT surface.  Native fixed
        // arrays are lowered to `list<T>` there, while the raw transport
        // keeps the fixed width for validation and packing.
        SemanticType::FixedArray { element, .. } => {
            format!("Vec<{}>", rust_type(element, records, enums))
        }
        SemanticType::Option { inner } => {
            format!("Option<{}>", rust_type(inner, records, enums))
        }
        SemanticType::Handle { .. } => "u64".to_owned(),
        SemanticType::Callback { .. }
        | SemanticType::Pointer { .. }
        | SemanticType::Unknown { .. } => "u32".to_owned(),
        SemanticType::Result { ok, .. } => ok
            .as_deref()
            .map(|inner| rust_type(inner, records, enums))
            .unwrap_or_else(|| "()".to_owned()),
    }
}

fn needs_borrow(ty: &SemanticType, records: &BTreeMap<String, &RecordModel>) -> bool {
    match ty {
        SemanticType::String
        | SemanticType::Bytes
        | SemanticType::List { .. }
        | SemanticType::FixedArray { .. } => true,
        SemanticType::Option { inner } => matches!(inner.as_ref(), SemanticType::String),
        SemanticType::Record { name } => records.get(name).is_some_and(|record| {
            record
                .fields
                .iter()
                .any(|field| needs_borrow(&field.ty, records))
        }),
        _ => false,
    }
}

fn rust_param_type(
    ty: &SemanticType,
    records: &BTreeMap<String, &RecordModel>,
    enums: &BTreeMap<String, &EnumModel>,
) -> String {
    match ty {
        SemanticType::String => "&str".to_owned(),
        SemanticType::Bytes => "&[u8]".to_owned(),
        SemanticType::List { element } | SemanticType::FixedArray { element, .. } => {
            format!("&[{}]", rust_type(element, records, enums))
        }
        SemanticType::Option { inner } if matches!(inner.as_ref(), SemanticType::String) => {
            "Option<&str>".to_owned()
        }
        other if needs_borrow(other, records) => {
            format!("&{}", rust_type(other, records, enums))
        }
        other => rust_type(other, records, enums),
    }
}

fn enum_variant_ident(_enum_name: &str, variant: &str) -> String {
    let value = variant.to_lowercase();
    value
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().collect::<String>() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn too_many_arguments_attribute(count: usize, indent: usize) -> String {
    let _ = (count, indent);
    String::new()
}

