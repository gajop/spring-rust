//! Generate Core-Wasm host callbacks for fixed-layout option fields. Options
//! are encoded as a canonical u32 presence flag followed by the aligned fixed
//! payload; raw NativeInterface presence fields come from semantic metadata.

use heck::ToSnakeCase;
use std::collections::BTreeMap;

use crate::model::{ApiModel, FieldModel, RecordModel, SemanticType};
use crate::render_core_wasm::{self, CoreType, FunctionPlan, InputStrategy, ResultStrategy};

pub fn render_header() -> String {
    r#"/* @generated by spring-api-codegen; do not edit. */
#pragma once

#include <string>

#include "WasmInterface/core/bindings/WasmCoreBindings.h"

namespace recoil::wasm::core::generated {

bool RegisterGeneratedOptionImports(wasmtime_linker_t* linker, HostState* state,
    std::string& error);

} // namespace recoil::wasm::core::generated
"#
    .to_owned()
}

pub fn render_cpp(model: &ApiModel) -> String {
    let records = record_index(model);
    let plans = render_core_wasm::plan(model)
        .functions
        .into_iter()
        .map(|plan| ((plan.module.clone(), plan.function.clone()), plan))
        .collect::<BTreeMap<_, _>>();
    let mut callbacks = String::new();
    let mut registrations = String::new();
    let mut generated_count = 0usize;

    for module in &model.modules {
        for function in &module.functions {
            let Some(plan) = plans.get(&(module.name.clone(), function.name.clone())) else {
                continue;
            };
            if !eligible(plan, &function.inputs, &function.outputs, &records) {
                continue;
            }
            generated_count += 1;
            callbacks.push_str(&render_callback(&module.name, function, plan, &records));
            callbacks.push('\n');
            registrations.push_str(&render_registration(
                plan,
                &callback_name(&module.name, &function.name),
            ));
        }
    }

    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */

#include "wasm/generated/WasmCoreGeneratedOptionBindings.h"

#include <array>
#include <bit>
#include <cstdint>
#include <span>
#include <string_view>
#include <type_traits>

#include "NativeInterface/NativeInterface.h"
#include "WasmInterface/core/host/WasmCoreAbi.h"
#include "WasmInterface/core/host/WasmCoreGeneratedSupport.h"
#include "WasmInterface/core/host/WasmCoreWire.h"

namespace recoil::wasm::core::generated {{
namespace {{

bool DefineGeneratedOption(wasmtime_linker_t* linker, const char* moduleName,
    const char* functionName, wasm_functype_t* type,
    wasmtime_func_unchecked_callback_t callback, HostState* state, std::string& error)
{{
    wasmtime_error_t* defineError = wasmtime_linker_define_func_unchecked(
        linker,
        moduleName, std::char_traits<char>::length(moduleName),
        functionName, std::char_traits<char>::length(functionName),
        type, callback, state, nullptr);
    wasm_functype_delete(type);
    if (defineError == nullptr)
        return true;
    error = ErrorMessage(defineError);
    return false;
}}

{callbacks}
}} // namespace

bool RegisterGeneratedOptionImports(wasmtime_linker_t* linker, HostState* state,
    std::string& error)
{{
    if (linker == nullptr || state == nullptr || state->native == nullptr) {{
        error = "cannot register generated option Core imports without linker/host/native API";
        return false;
    }}
{registrations}
    return true;
}}

static_assert({generated_count} >= 0, "generated option Core callback count");

}} // namespace recoil::wasm::core::generated
"#,
        callbacks = callbacks,
        registrations = registrations,
        generated_count = generated_count,
    )
}

pub(crate) fn eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    // A reviewed handwritten transport already owns this import.
    if crate::render_core_wasm_registry::handwritten_reviewed(&plan.module, &plan.function) {
        return false;
    }
    if matches!(plan.source_status.as_str(), "manual" | "unsupported")
        || !matches!(
            plan.input_strategy,
            InputStrategy::Direct | InputStrategy::FixedInputBuffer
        )
        || matches!(
            plan.result_strategy,
            ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported
        )
    {
        return false;
    }
    if !inputs.iter().all(|field| field_supported(field, records))
        || !outputs.iter().all(|field| field_supported(field, records))
    {
        return false;
    }
    if matches!(plan.result_strategy, ResultStrategy::Packed32)
        && (outputs.len() != 1
            || !matches!(
                outputs[0].ty,
                SemanticType::Scalar { .. } | SemanticType::Enum { .. }
            ))
    {
        return false;
    }
    inputs.iter().any(|field| field_has_option(field, records))
        || outputs.iter().any(|field| field_has_option(field, records))
}

fn direct_type(ty: &SemanticType) -> bool {
    matches!(
        ty,
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. }
    )
}

fn field_supported(field: &FieldModel, records: &BTreeMap<String, RecordModel>) -> bool {
    match &field.ty {
        SemanticType::Option { inner } => {
            presence_field(field).is_some() && type_supported(inner, records)
        }
        SemanticType::Record { name } => records.get(name).is_some_and(|record| {
            record
                .fields
                .iter()
                .all(|field| field_supported(field, records))
        }),
        other => type_supported(other, records),
    }
}

fn type_supported(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. } => {
            true
        }
        SemanticType::FixedArray { element, length } => {
            *length <= 64 && type_supported(element, records)
        }
        SemanticType::Record { name } => records.get(name).is_some_and(|record| {
            record
                .fields
                .iter()
                .all(|field| field_supported(field, records))
        }),
        SemanticType::Option { .. } => false,
        _ => false,
    }
}

fn field_has_option(field: &FieldModel, records: &BTreeMap<String, RecordModel>) -> bool {
    match &field.ty {
        SemanticType::Option { .. } => true,
        SemanticType::Record { name } => records.get(name).is_some_and(|record| {
            record
                .fields
                .iter()
                .any(|field| field_has_option(field, records))
        }),
        _ => false,
    }
}

fn fixed_layout(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> Option<(u32, u32)> {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i64" | "u64" | "isize" | "usize" | "f64" => Some((8, 8)),
            _ => Some((4, 4)),
        },
        SemanticType::Enum { .. } => Some((4, 4)),
        SemanticType::Handle { .. } => Some((8, 8)),
        SemanticType::FixedArray { element, length } => {
            let (bytes, alignment) = fixed_layout(element, records)?;
            Some((bytes.checked_mul(u32::try_from(*length).ok()?)?, alignment))
        }
        SemanticType::Record { name } => layout_fields(&records.get(name)?.fields, records),
        SemanticType::Option { inner } => {
            let (payload_bytes, payload_alignment) = fixed_layout(inner, records)?;
            let alignment = payload_alignment.max(4);
            let payload_offset = align_up(4, payload_alignment);
            Some((
                align_up(payload_offset.checked_add(payload_bytes)?, alignment),
                alignment,
            ))
        }
        _ => None,
    }
}

fn layout_fields(
    fields: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    let mut bytes = 0u32;
    let mut alignment = 1u32;
    for field in fields {
        let (field_bytes, field_alignment) = fixed_layout(&field.ty, records)?;
        bytes = align_up(bytes, field_alignment).checked_add(field_bytes)?;
        alignment = alignment.max(field_alignment);
    }
    Some((align_up(bytes, alignment), alignment))
}

fn aggregate_input_layout(
    fields: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    let fixed = fields
        .iter()
        .filter(|field| !direct_type(&field.ty))
        .cloned()
        .collect::<Vec<_>>();
    if fixed.is_empty() {
        None
    } else {
        layout_fields(&fixed, records)
    }
}

fn align_up(value: u32, alignment: u32) -> u32 {
    (value + alignment - 1) & !(alignment - 1)
}

fn render_callback(
    module_name: &str,
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
) -> String {
    let callback = callback_name(module_name, &function.name);
    let api_member = native_member(module_name);
    let api_guard = native_guard(module_name);
    let slot_count = plan.direct_params.len().max(plan.direct_results.len());
    let fixed_input = matches!(plan.input_strategy, InputStrategy::FixedInputBuffer);
    let fixed_output = matches!(
        plan.result_strategy,
        ResultStrategy::FixedOutputBuffer { .. }
    );
    let direct_input_count = function
        .inputs
        .iter()
        .filter(|field| direct_type(&field.ty))
        .count();
    let mut body = format!(
        "wasm_trap_t* {callback}(void* environment, wasmtime_caller_t* caller,\n    wasmtime_val_raw_t* slots, std::size_t slotCount)\n{{\n    auto* state = static_cast<HostState*>(environment);\n    if (state == nullptr || state->native == nullptr || {api_guard} ||\n        state->native->{api_member}->{function_name} == nullptr)\n        return Trap(\"{function_name} generated Core binding is unavailable\");\n    if ({slot_count} != 0 && (slots == nullptr || slotCount != {slot_count}))\n        return Trap(\"{function_name} generated Core ABI signature mismatch\");\n    if ({slot_count} == 0 && slotCount != 0)\n        return Trap(\"{function_name} generated Core ABI signature mismatch\");\n\n    std::string budgetError;\n    ImportGuard guard(state, {work}u, budgetError);\n    if (!guard.Ok())\n        return Trap(budgetError);\n",
        callback = callback,
        api_member = api_member,
        api_guard = api_guard,
        function_name = function.name,
        slot_count = slot_count,
        work = 1 + plan.direct_params.len(),
    );
    if fixed_input || fixed_output {
        body.push_str("\n    std::string memoryError;\n    if (!EnsureMemory(state, caller, memoryError))\n        return Trap(memoryError);\n");
    }
    if fixed_input {
        let (bytes, _) = aggregate_input_layout(&function.inputs, records)
            .expect("eligible option input layout");
        body.push_str(&format!(
            "    const std::uint32_t input = static_cast<std::uint32_t>(slots[{index}].i32);\n    std::span<const std::uint8_t> inputWire;\n    if (!state->memory.View(input, {bytes}u, inputWire)) {{\n{error}    }}\n    WireReader reader(inputWire);\n",
            index = direct_input_count,
            bytes = bytes,
            error = error_return(plan, "Status::OutOfBounds", 2),
        ));
    }
    if let ResultStrategy::FixedOutputBuffer { bytes, .. } = plan.result_strategy {
        let index = plan.direct_params.len() - 1;
        body.push_str(&format!(
            "    const std::uint32_t output = static_cast<std::uint32_t>(slots[{index}].i32);\n    if (!state->memory.Contains(output, {bytes}u)) {{\n{error}    }}\n",
            index = index,
            bytes = bytes,
            error = error_return(plan, "Status::OutOfBounds", 2),
        ));
    }
    body.push_str(&format!("\n    {} query{{}};\n", function.query));
    let mut direct_slot = 0usize;
    for field in &function.inputs {
        if direct_type(&field.ty) {
            body.push_str(&format!(
                "    query.{name} = {expr};\n",
                name = field.name,
                expr = query_expr(&field.ty, direct_slot, &format!("query.{}", field.name)),
            ));
            direct_slot += 1;
        } else {
            body.push_str(&render_read_field(
                field,
                &format!("query.{}", field.name),
                "query",
                records,
                1,
            ));
        }
    }
    if fixed_input {
        let (_, alignment) = aggregate_input_layout(&function.inputs, records)
            .expect("eligible option input layout");
        body.push_str(&format!(
            "    if (!reader.Finish({alignment}u)) {{\n{error}    }}\n",
            alignment = alignment,
            error = error_return(plan, "Status::InvalidArgument", 2),
        ));
    }
    body.push_str(&format!(
        "    {} result{{}};\n    state->native->{api_member}->{function_name}(&query, &result);\n    const std::int32_t errorCode = NativeErrorCode(result.error);\n",
        function.result,
        api_member = api_member,
        function_name = function.name,
    ));
    match plan.result_strategy {
        ResultStrategy::Status => {
            body.push_str("    slots[0].i32 = errorCode;\n    return nullptr;\n")
        }
        ResultStrategy::Packed32 => {
            let field = &function.outputs[0];
            body.push_str(&format!(
                "    slots[0].i64 = static_cast<std::int64_t>(PackU32({value}, errorCode));\n    return nullptr;\n",
                value = packed32_expr(&field.ty, &format!("result.{}", field.name)),
            ));
        }
        ResultStrategy::FixedOutputBuffer { bytes, alignment } => {
            body.push_str(
                "    if (errorCode != 0) { slots[0].i32 = errorCode; return nullptr; }\n",
            );
            body.push_str(&format!(
                "    std::array<std::uint8_t, {bytes}> wire{{}};\n    WireWriter writer(wire);\n"
            ));
            for field in &function.outputs {
                body.push_str(&render_write_field(
                    field,
                    &format!("result.{}", field.name),
                    "result",
                    records,
                    1,
                ));
            }
            body.push_str(&format!(
                "    if (!writer.Finish({alignment}u)) return Trap(\"generated option output layout mismatch\");\n    if (!state->memory.Write(output, wire.data(), wire.size())) return Trap(\"generated option output range changed unexpectedly\");\n    slots[0].i32 = 0;\n    return nullptr;\n"
            ));
        }
        _ => unreachable!(),
    }
    body.push_str("}\n");
    body
}

fn render_read_field(
    field: &FieldModel,
    destination: &str,
    owner: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match &field.ty {
        SemanticType::Option { inner } => {
            let presence = presence_field(field).expect("eligible option has presence metadata");
            let mut output = format!(
                // Scope the presence temporary: a record with several option
                // fields reads more than one of these into the same function.
                "{pad}{{\n{pad}    bool corePresent = false;\n{pad}    if (!reader.Bool(corePresent)) return Trap(\"generated option presence underflow\");\n{pad}    {owner}.{presence} = corePresent;\n{pad}}}\n"
            );
            output.push_str(&render_read_type(inner, destination, records, indent));
            output
        }
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|nested| {
                    render_read_field(
                        nested,
                        &format!("{destination}.{}", nested.name),
                        destination,
                        records,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) = fixed_layout(&field.ty, records)
                .expect("eligible option record must have a fixed layout");
            output.push_str(&format!(
                "{pad}if (!reader.Align({alignment}u)) return Trap(\"generated option record alignment overflow\");\n"
            ));
            output
        }
        other => render_read_type(other, destination, records, indent),
    }
}

fn render_read_type(
    ty: &SemanticType,
    destination: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!(
                "{pad}if (!reader.Bool({destination})) return Trap(\"generated Core wire underflow\");\n"
            ),
            "f32" => format!(
                "{pad}if (!reader.F32({destination})) return Trap(\"generated Core wire underflow\");\n"
            ),
            "f64" => format!(
                "{pad}if (!reader.F64({destination})) return Trap(\"generated Core wire underflow\");\n"
            ),
            "i64" | "isize" => scalar_read("I64", "std::int64_t", destination, &pad),
            "u64" | "usize" => scalar_read("U64", "std::uint64_t", destination, &pad),
            "i8" | "i16" | "i32" => scalar_read("I32", "std::int32_t", destination, &pad),
            _ => scalar_read("U32", "std::uint32_t", destination, &pad),
        },
        SemanticType::Enum { .. } => scalar_read("I32", "std::int32_t", destination, &pad),
        SemanticType::Handle { .. } => scalar_read("U64", "std::uint64_t", destination, &pad),
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|field| {
                    render_read_field(
                        field,
                        &format!("{destination}.{}", field.name),
                        destination,
                        records,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) =
                fixed_layout(ty, records).expect("eligible option record must have a fixed layout");
            output.push_str(&format!(
                "{pad}if (!reader.Align({alignment}u)) return Trap(\"generated option record alignment overflow\");\n"
            ));
            output
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreReadIndex{indent}");
            let nested = render_read_type(
                element,
                &format!("{destination}[{index}]"),
                records,
                indent + 1,
            );
            format!(
                "{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n"
            )
        }
        _ => unreachable!(),
    }
}

fn render_write_field(
    field: &FieldModel,
    value: &str,
    owner: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match &field.ty {
        SemanticType::Option { inner } => {
            let presence = presence_field(field).expect("eligible option has presence metadata");
            let native_ty = format!("std::remove_cv_t<std::remove_reference_t<decltype({value})>>");
            let mut output = format!(
                "{pad}if (!writer.Bool({owner}.{presence})) return Trap(\"generated option output overflow\");\n"
            );
            output.push_str(&format!("{pad}if ({owner}.{presence}) {{\n"));
            output.push_str(&render_write_type(inner, value, records, indent + 1));
            output.push_str(&format!(
                "{pad}}} else {{\n{pad}    {native_ty} coreDefault{{}};\n"
            ));
            output.push_str(&render_write_type(
                inner,
                "coreDefault",
                records,
                indent + 1,
            ));
            output.push_str(&format!("{pad}}}\n"));
            output
        }
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|nested| {
                    render_write_field(
                        nested,
                        &format!("{value}.{}", nested.name),
                        value,
                        records,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) = fixed_layout(&field.ty, records)
                .expect("eligible option record must have a fixed layout");
            output.push_str(&format!(
                "{pad}if (!writer.Align({alignment}u)) return Trap(\"generated option record alignment overflow\");\n"
            ));
            output
        }
        other => render_write_type(other, value, records, indent),
    }
}

fn render_write_type(
    ty: &SemanticType,
    value: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => {
            let method = match name.as_str() {
                "bool" => "Bool",
                "f32" => "F32",
                "f64" => "F64",
                "i64" | "isize" => "I64",
                "u64" | "usize" => "U64",
                "i8" | "i16" | "i32" => "I32",
                _ => "U32",
            };
            format!(
                "{pad}if (!writer.{method}({value})) return Trap(\"generated Core wire overflow\");\n"
            )
        }
        SemanticType::Enum { .. } => format!(
            "{pad}if (!writer.I32(static_cast<std::int32_t>({value}))) return Trap(\"generated Core wire overflow\");\n"
        ),
        SemanticType::Handle { .. } => format!(
            "{pad}if (!writer.U64(static_cast<std::uint64_t>({value}))) return Trap(\"generated Core wire overflow\");\n"
        ),
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|field| {
                    render_write_field(
                        field,
                        &format!("{value}.{}", field.name),
                        value,
                        records,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) =
                fixed_layout(ty, records).expect("eligible option record must have a fixed layout");
            output.push_str(&format!(
                "{pad}if (!writer.Align({alignment}u)) return Trap(\"generated option record alignment overflow\");\n"
            ));
            output
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreWriteIndex{indent}");
            let nested =
                render_write_type(element, &format!("{value}[{index}]"), records, indent + 1);
            format!(
                "{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n"
            )
        }
        _ => unreachable!(),
    }
}

fn scalar_read(method: &str, raw: &str, destination: &str, pad: &str) -> String {
    format!(
        "{pad}{{ {raw} coreRaw = 0; if (!reader.{method}(coreRaw)) return Trap(\"generated Core wire underflow\"); {destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>(coreRaw); }}\n"
    )
}

fn query_expr(ty: &SemanticType, slot: usize, destination: &str) -> String {
    let cast = |value: String| {
        format!(
            "static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>({value})"
        )
    };
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!("slots[{slot}].i32 != 0"),
            "f32" => format!("slots[{slot}].f32"),
            "f64" => format!("slots[{slot}].f64"),
            "i64" | "u64" | "isize" | "usize" => cast(format!("slots[{slot}].i64")),
            _ => cast(format!("slots[{slot}].i32")),
        },
        SemanticType::Enum { .. } => cast(format!("slots[{slot}].i32")),
        SemanticType::Handle { .. } => cast(format!("slots[{slot}].i64")),
        _ => unreachable!(),
    }
}

fn packed32_expr(ty: &SemanticType, value: &str) -> String {
    match ty {
        SemanticType::Scalar { name } if name == "f32" => {
            format!("std::bit_cast<std::uint32_t>({value})")
        }
        SemanticType::Scalar { name } if name == "bool" => {
            format!("static_cast<std::uint32_t>({value} ? 1u : 0u)")
        }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => {
            format!("static_cast<std::uint32_t>({value})")
        }
        _ => unreachable!(),
    }
}

fn error_return(plan: &FunctionPlan, status: &str, indent: usize) -> String {
    let pad = "    ".repeat(indent);
    if matches!(plan.result_strategy, ResultStrategy::Packed32) {
        format!(
            "{pad}slots[0].i64 = static_cast<std::int64_t>(PackU32(0, static_cast<std::int32_t>({status})));\n{pad}return nullptr;\n"
        )
    } else {
        format!("{pad}slots[0].i32 = static_cast<std::int32_t>({status});\n{pad}return nullptr;\n")
    }
}

fn presence_field(field: &FieldModel) -> Option<String> {
    field.metadata.iter().find_map(|metadata| {
        metadata
            .strip_prefix("presence-field:")
            .map(ToString::to_string)
    })
}

fn render_registration(plan: &FunctionPlan, callback: &str) -> String {
    let params = kind_array("params", &plan.direct_params);
    let results = kind_array("results", &plan.direct_results);
    format!(
        "    {{\n{params}{results}        if (!DefineGeneratedOption(linker, \"{module}\", \"{name}\",\n                MakeFuncType(params, {pc}, results, {rc}), {callback}, state, error))\n            return false;\n    }}\n",
        params = params,
        results = results,
        module = plan.import_module,
        name = plan.import_name,
        pc = plan.direct_params.len(),
        rc = plan.direct_results.len(),
        callback = callback
    )
}

fn kind_array(name: &str, kinds: &[CoreType]) -> String {
    if kinds.is_empty() {
        return format!("        const wasm_valkind_t* {name} = nullptr;\n");
    }
    format!(
        "        const wasm_valkind_t {name}[] = {{{}}};\n",
        kinds
            .iter()
            .map(|kind| match kind {
                CoreType::I32 => "WASM_I32",
                CoreType::I64 => "WASM_I64",
                CoreType::F32 => "WASM_F32",
                CoreType::F64 => "WASM_F64",
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

