pub(super) fn render_header(model: &ApiModel) -> String {
    let slots = expanded(model).len() + 1;
    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */
#pragma once

#include <array>
#include <cstdint>
#include <string>

#include "WasmInterface/core/host/WasmCoreAbi.h"

class WasmExecutionBudget;

namespace recoil::wasm::core::generated {{

inline constexpr std::size_t kGeneratedScratchCallinSlotCount = {slots}u;

class GeneratedScratchCallinBindings {{
public:
    bool Bind(wasmtime_context_t* context, const wasmtime_instance_t& instance,
        Memory& memory, std::string& error);
    bool Has(std::uint16_t ordinal) const;
    bool Invoke(std::uint16_t ordinal, wasmtime_context_t* context,
        WasmExecutionBudget& budget, Memory& memory, const void* query,
        void* result, std::string& error) const;
    bool AnyPresent() const {{ return anyPresent; }}

private:
    std::array<RawExport, kGeneratedScratchCallinSlotCount> exports{{}};
    RawExport scratchInfo;
    std::uint32_t scratchOffset = 0;
    std::uint32_t scratchCapacity = 0;
    bool anyPresent = false;
}};

}} // namespace recoil::wasm::core::generated
"#,
        slots = slots,
    )
}

pub(super) fn render_cpp(model: &ApiModel) -> String {
    let records = record_index(model);
    let callins = executable(model, &records);
    let mut binds = String::new();
    let mut cases = String::new();
    for callin in &callins {
        binds.push_str(&render_bind(callin, &records));
        cases.push_str(&render_case(callin, &records));
    }

    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */

#include "wasm/generated/WasmCoreGeneratedScratchCallinBindings.h"

#include <bit>
#include <cstdint>
#include <limits>
#include <span>
#include <string_view>
#include <type_traits>

#include "NativeInterface/api/Callins.h"
#include "WasmInterface/core/bindings/WasmCoreVariableCallins.h"
#include "WasmInterface/core/host/WasmCoreWire.h"
#include "WasmInterface/runtime/WasmResources.h"

namespace recoil::wasm::core::generated {{
namespace {{

struct ScratchScope {{
    explicit ScratchScope(bool& active) : active(active) {{ active = true; }}
    ~ScratchScope() {{ active = false; }}
    bool& active;
}};

bool ResolveOptional(RawExport& target, wasmtime_context_t* context,
    const wasmtime_instance_t& instance, const char* name,
    std::span<const wasm_valkind_t> params, std::span<const wasm_valkind_t> results,
    std::string& error)
{{
    return target.Resolve(context, instance, name,
        std::char_traits<char>::length(name), params, results, true, error);
}}

bool WriteString(WireWriter& writer, const char* value)
{{
    const std::string_view text = value == nullptr ? std::string_view{{}} : std::string_view(value);
    if (text.size() > std::numeric_limits<std::uint32_t>::max())
        return false;
    return writer.U32(static_cast<std::uint32_t>(text.size())) &&
        writer.Bytes(std::span(reinterpret_cast<const std::uint8_t*>(text.data()), text.size()));
}}

template<typename T>
bool WriteNumericList(WireWriter& writer, const T* values, std::uint32_t count)
{{
    static_assert(std::is_trivially_copyable_v<T>);
    if (count != 0 && values == nullptr)
        return false;
    if (!writer.U32(count))
        return false;
    if constexpr (std::endian::native == std::endian::little)
        return writer.Bytes(
            std::span(reinterpret_cast<const std::uint8_t*>(values), count * sizeof(T)),
            alignof(T));
    return count == 0; // no element representation crosses the boundary
}}

}} // namespace

bool GeneratedScratchCallinBindings::Bind(wasmtime_context_t* context,
    const wasmtime_instance_t& instance, Memory& memory, std::string& error)
{{
    if (context == nullptr) {{
        error = "cannot bind generated scratch Core callins without Wasmtime context";
        return false;
    }}
{binds}
    if (!anyPresent)
        return true;

    const wasm_valkind_t i64Result[] = {{WASM_I64}};
    if (!scratchInfo.Resolve(context, instance, "spring:callin/scratch-info",
            std::char_traits<char>::length("spring:callin/scratch-info"),
            std::span<const wasm_valkind_t>{{}}, i64Result, false, error))
        return false;

    wasmtime_val_raw_t slot{{}};
    if (!scratchInfo.Call(context, &slot, 1, error))
        return false;
    const std::uint64_t packed = static_cast<std::uint64_t>(slot.i64);
    scratchOffset = static_cast<std::uint32_t>(packed);
    scratchCapacity = static_cast<std::uint32_t>(packed >> 32);
    if (scratchCapacity == 0 || !memory.Contains(scratchOffset, scratchCapacity)) {{
        error = "generated Core callin scratch range is invalid";
        return false;
    }}
    return true;
}}

bool GeneratedScratchCallinBindings::Has(std::uint16_t ordinal) const
{{
    return ordinal < exports.size() && exports[ordinal].Present();
}}

bool GeneratedScratchCallinBindings::Invoke(std::uint16_t ordinal,
    wasmtime_context_t* context, WasmExecutionBudget& budget, Memory& memory,
    const void* query, void* result, std::string& error) const
{{
    if (!Has(ordinal))
        return true;
    bool& scratchInUse = VariableCallinScratchInUse();
    if (scratchInUse) {{
        error = "nested generated Core variable callin would overwrite guest scratch";
        return false;
    }}
    ScratchScope scratchScope(scratchInUse);
    std::span<std::uint8_t> scratch;
    if (!memory.MutableView(scratchOffset, scratchCapacity, scratch)) {{
        error = "generated Core callin scratch range became invalid";
        return false;
    }}
    WireWriter writer(scratch);

    switch (ordinal) {{
{cases}        default:
            error = "generated Core scratch callin has no serializer";
            return false;
    }}
}}

static_assert(kGeneratedScratchCallinSlotCount == {slots}u,
    "generated scratch Core callin slot count drifted");
static_assert({count}u <= kGeneratedScratchCallinSlotCount,
    "generated scratch Core callin coverage count");

}} // namespace recoil::wasm::core::generated
"#,
        binds = binds,
        cases = cases,
        slots = expanded(model).len() + 1,
        count = callins.len(),
    )
}

fn render_bind(callin: &ScratchCallin<'_>, records: &BTreeMap<String, RecordModel>) -> String {
    let shape = result::classify(callin.result, records).expect("executable scratch result");
    let (results, result_count) = match shape {
        result::ResultShape::Empty => (
            "        const wasm_valkind_t* results = nullptr;\n".to_owned(),
            0usize,
        ),
        result::ResultShape::Direct(field) => (
            format!(
                "        const wasm_valkind_t results[] = {{{}}};\n",
                wasm_kind(&field.ty)
            ),
            1usize,
        ),
        result::ResultShape::PackedFixed(_) => (
            "        const wasm_valkind_t results[] = {WASM_I64};\n".to_owned(),
            1usize,
        ),
    };
    let export_name = format!("spring:callin/{}", callin.entry.name.to_kebab_case());
    format!(
        "    {{\n        const wasm_valkind_t params[] = {{WASM_I32}};\n{results}        if (!ResolveOptional(exports[{ordinal}], context, instance, \"{name}\", params, std::span<const wasm_valkind_t>(results, {result_count}), error))\n            return false;\n        anyPresent = anyPresent || exports[{ordinal}].Present();\n    }}\n",
        results = results,
        ordinal = callin.entry.ordinal,
        name = export_name,
        result_count = result_count,
    )
}

fn render_case(callin: &ScratchCallin<'_>, records: &BTreeMap<String, RecordModel>) -> String {
    let mut body = format!(
        "        case {ordinal}u: {{\n            const auto* typedQuery = static_cast<const {query}*>(query);\n            if (typedQuery == nullptr) {{ error = \"generated Core {name} query is null\"; return false; }}\n",
        ordinal = callin.entry.ordinal,
        query = callin.entry.callin.query,
        name = callin.entry.name,
    );
    body.push_str(&render_cpp_fields(
        &callin.query.fields,
        "typedQuery->",
        records,
        3,
    ));
    body.push_str(
        "            const std::size_t used = writer.Offset();\n            if (used > std::numeric_limits<std::uint32_t>::max()) { error = \"generated Core callin scratch payload exceeds u32\"; return false; }\n            if (!budget.ChargeHost(static_cast<std::uint64_t>(used))) { error = \"generated Core callin scratch host-work budget exhausted\"; return false; }\n            wasmtime_val_raw_t slot{};\n            slot.i32 = static_cast<std::int32_t>(used);\n",
    );
    body.push_str(&format!(
        "            if (!exports[{ordinal}].Call(context, &slot, 1, error)) return false;\n",
        ordinal = callin.entry.ordinal,
    ));

    match result::classify(callin.result, records).expect("executable scratch result") {
        result::ResultShape::Empty => {}
        result::ResultShape::Direct(field) => {
            body.push_str(&format!(
                "            if (result != nullptr) {{\n                auto* typedResult = static_cast<{result_type}*>(result);\n                typedResult->error = nullptr;\n                {assign}\n            }}\n",
                result_type = callin.entry.callin.result,
                assign = cpp_result_assign(&field.ty, &format!("typedResult->{}", field.name)),
            ));
        }
        result::ResultShape::PackedFixed(leaves) => {
            body.push_str(&format!(
                "            if (result != nullptr) {{\n                auto* typedResult = static_cast<{result_type}*>(result);\n                typedResult->error = nullptr;\n                const std::uint64_t packed = static_cast<std::uint64_t>(slot.i64);\n",
                result_type = callin.entry.callin.result,
            ));
            for (index, leaf) in leaves.iter().enumerate() {
                body.push_str(&format!(
                    "                const std::uint32_t raw{index} = static_cast<std::uint32_t>(packed >> {shift}u);\n                {assign}\n",
                    index = index,
                    shift = index * 32,
                    assign = cpp_unpack_packed32(
                        &leaf.ty,
                        &format!("typedResult->{}", leaf.cpp_path),
                        &format!("raw{index}"),
                    ),
                ));
            }
            body.push_str("            }\n");
        }
    }

    body.push_str("            return true;\n        }\n");
    body
}

fn render_cpp_fields(
    fields: &[FieldModel],
    prefix: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let implicit = implicit_count_fields(fields);
    fields
        .iter()
        .filter(|field| !implicit.contains(&field.name))
        .map(|field| {
            render_cpp_type(
                &field.ty,
                field,
                &format!("{prefix}{}", field.name),
                prefix,
                records,
                indent,
            )
        })
        .collect()
}

fn render_cpp_type(
    ty: &SemanticType,
    field: &FieldModel,
    expr: &str,
    sibling_prefix: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => {
            let method = writer_method(name);
            format!("{pad}if (!writer.{method}({expr})) {{ error = \"generated Core scratch overflow\"; return false; }}\n")
        }
        SemanticType::Enum { .. } => format!(
            "{pad}if (!writer.I32(static_cast<std::int32_t>({expr}))) {{ error = \"generated Core scratch overflow\"; return false; }}\n"
        ),
        SemanticType::Handle { .. } => format!(
            "{pad}if (!writer.U64(static_cast<std::uint64_t>({expr}))) {{ error = \"generated Core scratch overflow\"; return false; }}\n"
        ),
        SemanticType::String => format!(
            "{pad}if (!WriteString(writer, {expr})) {{ error = \"generated Core string exceeds scratch capacity\"; return false; }}\n"
        ),
        SemanticType::Bytes => {
            let count = count_field(field).expect("eligible bytes count");
            let count_expr = format!("{sibling_prefix}{count}");
            format!(
                "{pad}if ({count_expr} != 0 && {expr} == nullptr) {{ error = \"generated Core byte input is null\"; return false; }}\n{pad}if (!writer.U32(static_cast<std::uint32_t>({count_expr})) || !writer.Bytes(std::span<const std::uint8_t>(reinterpret_cast<const std::uint8_t*>({expr}), static_cast<std::size_t>({count_expr})))) {{ error = \"generated Core byte payload exceeds scratch capacity\"; return false; }}\n"
            )
        }
        SemanticType::List { element } => {
            let count = count_field(field).expect("eligible list count");
            let count_expr = format!("{sibling_prefix}{count}");
            match element.as_ref() {
                SemanticType::Record { name } => {
                    let record = &records[name];
                    let index = format!("coreScratchRecordIndex{indent}");
                    let total_offset = format!("coreScratchRecordTotalOffset{indent}");
                    let frames_start = format!("coreScratchRecordFramesStart{indent}");
                    let frames_bytes = format!("coreScratchRecordFramesBytes{indent}");
                    let length_offset = format!("coreScratchRecordLengthOffset{indent}");
                    let payload_start = format!("coreScratchRecordPayloadStart{indent}");
                    let payload_bytes = format!("coreScratchRecordPayloadBytes{indent}");
                    let item_expr = format!("{expr}[{index}]");
                    let item_prefix = format!("{item_expr}.");
                    let nested = render_cpp_fields(&record.fields, &item_prefix, records, indent + 1);
                    format!(
                        "{pad}if ({count_expr} != 0 && {expr} == nullptr) {{ error = \"generated Core record-list input is null\"; return false; }}\n{pad}if (!writer.U32(static_cast<std::uint32_t>({count_expr}))) {{ error = \"generated Core record-list header exceeds scratch capacity\"; return false; }}\n{pad}const std::size_t {total_offset} = writer.Offset();\n{pad}if (!writer.U32(0) || !writer.Align(8)) {{ error = \"generated Core record-list header exceeds scratch capacity\"; return false; }}\n{pad}const std::size_t {frames_start} = writer.Offset();\n{pad}for (std::size_t {index} = 0; {index} < static_cast<std::size_t>({count_expr}); ++{index}) {{\n{pad}    const std::size_t {length_offset} = writer.Offset();\n{pad}    if (!writer.U32(0) || !writer.Align(8)) {{ error = \"generated Core record-list frame exceeds scratch capacity\"; return false; }}\n{pad}    const std::size_t {payload_start} = writer.Offset();\n{nested}{pad}    const std::size_t {payload_bytes} = writer.Offset() - {payload_start};\n{pad}    if ({payload_bytes} > std::numeric_limits<std::uint32_t>::max() || !writer.PatchU32({length_offset}, static_cast<std::uint32_t>({payload_bytes}))) {{ error = \"generated Core record-list frame exceeds u32\"; return false; }}\n{pad}}}\n{pad}const std::size_t {frames_bytes} = writer.Offset() - {frames_start};\n{pad}if ({frames_bytes} > std::numeric_limits<std::uint32_t>::max() || !writer.PatchU32({total_offset}, static_cast<std::uint32_t>({frames_bytes}))) {{ error = \"generated Core record-list payload exceeds u32\"; return false; }}\n"
                    )
                }
                _ => {
                    let cpp = cpp_list_type(element);
                    format!(
                        "{pad}static_assert(sizeof({cpp}) == {bytes}u, \"generated Core list element width mismatch\");\n{pad}if (!WriteNumericList(writer, reinterpret_cast<const {cpp}*>({expr}), static_cast<std::uint32_t>({count_expr}))) {{ error = \"generated Core numeric list exceeds scratch capacity or native endian is unsupported\"; return false; }}\n",
                        bytes = scalar_bytes(element),
                    )
                }
            }
        }
        SemanticType::Record { name } => {
            let record = &records[name];
            let nested_prefix = format!("{expr}.");
            render_cpp_fields(&record.fields, &nested_prefix, records, indent)
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreScratchIndex{indent}");
            let nested = render_cpp_type(
                element,
                field,
                &format!("{expr}[{index}]"),
                sibling_prefix,
                records,
                indent + 1,
            );
            format!("{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n")
        }
        _ => unreachable!(),
    }
}

fn writer_method(name: &str) -> &'static str {
    match name {
        "bool" => "Bool",
        "f32" => "F32",
        "f64" => "F64",
        "i64" | "isize" => "I64",
        "u64" | "usize" => "U64",
        "i8" | "i16" | "i32" => "I32",
        "u8" | "char" | "u16" | "u32" => "U32",
        _ => "I32",
    }
}

fn wasm_kind(ty: &SemanticType) -> &'static str {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "f32" => "WASM_F32",
            "f64" => "WASM_F64",
            "i64" | "u64" | "isize" | "usize" => "WASM_I64",
            _ => "WASM_I32",
        },
        SemanticType::Enum { .. } => "WASM_I32",
        SemanticType::Handle { .. } => "WASM_I64",
        _ => unreachable!(),
    }
}

fn cpp_result_assign(ty: &SemanticType, destination: &str) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!("{destination} = slot.i32 != 0;"),
            "f32" => format!("{destination} = slot.f32;"),
            "f64" => format!("{destination} = slot.f64;"),
            "i64" | "u64" | "isize" | "usize" => format!(
                "{destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>(slot.i64);"
            ),
            _ => format!(
                "{destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>(slot.i32);"
            ),
        },
        SemanticType::Enum { .. } => format!(
            "{destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>(slot.i32);"
        ),
        SemanticType::Handle { .. } => format!(
            "{destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>(slot.i64);"
        ),
        _ => unreachable!(),
    }
}

fn cpp_unpack_packed32(ty: &SemanticType, destination: &str, raw: &str) -> String {
    match ty {
        SemanticType::Scalar { name } if name == "bool" =>
            format!("{destination} = {raw} != 0u;"),
        SemanticType::Scalar { name } if name == "f32" =>
            format!("{destination} = std::bit_cast<float>({raw});"),
        SemanticType::Scalar { name } if matches!(name.as_str(), "i8" | "i16" | "i32") => {
            let signed = match name.as_str() {
                "i8" => "std::int8_t",
                "i16" => "std::int16_t",
                _ => "std::int32_t",
            };
            format!(
                "{destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>(static_cast<{signed}>({raw}));"
            )
        }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => format!(
            "{destination} = static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>({raw});"
        ),
        _ => unreachable!(),
    }
}

fn cpp_list_type(ty: &SemanticType) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i8" => "std::int8_t",
            "i16" => "std::int16_t",
            "i32" => "std::int32_t",
            "i64" => "std::int64_t",
            "u8" | "char" => "std::uint8_t",
            "u16" => "std::uint16_t",
            "u32" => "std::uint32_t",
            "u64" => "std::uint64_t",
            "f32" => "float",
            "f64" => "double",
            other => panic!("unsupported scratch list scalar {other}"),
        }
        .to_owned(),
        SemanticType::Enum { name } => name.clone(),
        _ => unreachable!(),
    }
}

fn scalar_bytes(ty: &SemanticType) -> u32 {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i8" | "u8" | "char" => 1,
            "i16" | "u16" => 2,
            "i32" | "u32" | "f32" => 4,
            "i64" | "u64" | "f64" => 8,
            _ => unreachable!(),
        },
        SemanticType::Enum { .. } => 4,
        _ => unreachable!(),
    }
}
