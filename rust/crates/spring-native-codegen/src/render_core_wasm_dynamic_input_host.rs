//! Generate Core-Wasm host callbacks for nested dynamic input records/lists.
//!
//! This is a fallback behind the flat borrowed/adapted renderers. It handles
//! semantic records that own strings/lists (CommandFFI, NativeCommand,
//! command descriptions, DefRef, etc.) by decoding one schema-driven guest
//! blob per non-direct top-level input into host-owned native record shells.

use heck::{ToLowerCamelCase, ToSnakeCase};
use std::collections::{BTreeMap, BTreeSet};

use crate::model::{ApiModel, FieldModel, FunctionModel, RecordModel, SemanticType};
use crate::render_core_wasm::{self, CoreType, FunctionPlan, InputStrategy, ResultStrategy};
use crate::render_core_wasm_owned_guest;

pub fn render_header() -> String {
    r#"/* @generated by spring-api-codegen; do not edit. */
#pragma once

#include <string>

#include "WasmInterface/core/bindings/WasmCoreBindings.h"

namespace recoil::wasm::core::generated {

bool RegisterGeneratedDynamicInputImports(wasmtime_linker_t* linker, HostState* state,
    std::string& error);

} // namespace recoil::wasm::core::generated
"#
    .to_owned()
}

pub fn render_cpp(model: &ApiModel) -> String {
    let records = record_index(model);
    let plans = plan_index(model);
    let mut used_records = BTreeSet::new();
    let mut callbacks = String::new();
    let mut registrations = String::new();
    let mut generated_count = 0usize;

    for module in &model.modules {
        for function in &module.functions {
            let Some(plan) = plans.get(&(module.name.clone(), function.name.clone())) else {
                continue;
            };
            if !eligible(plan, &function.inputs, &function.outputs, &records) {
                continue;
            }
            for field in &function.inputs {
                if record_pointer(field)
                    && let SemanticType::Record { name } = &field.ty
                {
                    used_records.insert(name.clone());
                }
                collect_dynamic_records(&field.ty, &records, &mut used_records);
            }
            generated_count += 1;
            callbacks.push_str(&render_callback(&module.name, function, plan, &records));
            callbacks.push('\n');
            // Only register when the borrowed renderer does not also cover
            // this import.  Borrowed is tried first by the owned SDK and
            // registers on the same linker slot; if both register, the
            // last-registered handler wins and a wire-format mismatch
            // results for whichever path the owned SDK did not pick.
            // Only register when the owned SDK does not route this
            // function to borrowed.  The owned SDK's routing is the
            // single source of truth for which wire format is used.
            if !render_core_wasm_owned_guest::routes_to_borrowed(
                plan,
                &function.inputs,
                &function.outputs,
                &records,
            ) {
                registrations.push_str(&render_registration(
                    plan,
                    &callback_name(&module.name, &function.name),
                ));
            }
        }
    }

    let owned_records = used_records
        .iter()
        .filter_map(|name| records.get(name))
        .map(|record| render_owned_record(record, &records))
        .collect::<String>();

    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */

#include "wasm/generated/WasmCoreGeneratedDynamicInputBindings.h"

#include <array>
#include <bit>
#include <cstdint>
#include <limits>
#include <span>
#include <string>
#include <string_view>
#include <type_traits>
#include <vector>

#include "NativeInterface/NativeInterface.h"
#include "WasmInterface/core/host/WasmCoreAbi.h"
#include "WasmInterface/core/host/WasmCoreGeneratedSupport.h"
#include "WasmInterface/core/host/WasmCoreWire.h"

namespace recoil::wasm::core::generated {{
namespace {{

template<typename T>
bool AssignDynamicCount(std::uint32_t value, T& output)
{{
    using Native = std::remove_cv_t<std::remove_reference_t<T>>;
    if constexpr (std::numeric_limits<Native>::is_signed) {{
        if (static_cast<std::uint64_t>(value) >
            static_cast<std::uint64_t>(std::numeric_limits<Native>::max()))
            return false;
    }} else if (static_cast<std::uint64_t>(value) >
               static_cast<std::uint64_t>(std::numeric_limits<Native>::max())) {{
        return false;
    }}
    output = static_cast<Native>(value);
    return true;
}}

bool WriteDynamicU32(std::span<std::uint8_t> bytes, std::size_t offset,
    std::uint32_t value)
{{
    if (offset > bytes.size() || bytes.size() - offset < 4u)
        return false;
    bytes[offset + 0] = static_cast<std::uint8_t>(value);
    bytes[offset + 1] = static_cast<std::uint8_t>(value >> 8);
    bytes[offset + 2] = static_cast<std::uint8_t>(value >> 16);
    bytes[offset + 3] = static_cast<std::uint8_t>(value >> 24);
    return true;
}}

{owned_records}

bool DefineGeneratedDynamicInput(wasmtime_linker_t* linker, const char* moduleName,
    const char* functionName, wasm_functype_t* type,
    wasmtime_func_unchecked_callback_t callback, HostState* state, std::string& error)
{{
    wasmtime_error_t* defineError = wasmtime_linker_define_func_unchecked(
        linker,
        moduleName, std::char_traits<char>::length(moduleName),
        functionName, std::char_traits<char>::length(functionName),
        type, callback, state, nullptr);
    wasm_functype_delete(type);
    if (defineError == nullptr)
        return true;
    error = ErrorMessage(defineError);
    return false;
}}

{callbacks}
}} // namespace

bool RegisterGeneratedDynamicInputImports(wasmtime_linker_t* linker, HostState* state,
    std::string& error)
{{
    if (linker == nullptr || state == nullptr || state->native == nullptr) {{
        error = "cannot register dynamic-input Core imports without linker/host/native API";
        return false;
    }}
{registrations}
    return true;
}}

static_assert({generated_count}u >= 0u, "generated dynamic-input Core callback count");

}} // namespace recoil::wasm::core::generated
"#,
        owned_records = owned_records,
        callbacks = callbacks,
        registrations = registrations,
        generated_count = generated_count,
    )
}

pub(crate) fn eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    // A reviewed handwritten transport already owns this import.
    if crate::render_core_wasm_registry::handwritten_reviewed(&plan.module, &plan.function) {
        return false;
    }
    if plan.source_status == "unsupported"
        || !matches!(plan.input_strategy, InputStrategy::VariableInputBuffer)
        || !inputs
            .iter()
            .all(|field| input_field_supported(field, records))
        || !inputs
            .iter()
            .any(|field| nested_dynamic_input(field, records))
    {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status => outputs.is_empty(),
        ResultStrategy::Packed32 => {
            outputs.len() == 1
                && matches!(
                    outputs[0].ty,
                    SemanticType::Scalar { .. } | SemanticType::Enum { .. }
                )
        }
        ResultStrategy::FixedOutputBuffer { .. } => outputs
            .iter()
            .all(|field| fixed_wire_type(&field.ty, records)),
        ResultStrategy::VariableOutputBuffer => variable_result_supported(outputs, records),
        ResultStrategy::Unsupported => false,
    }
}

fn nested_dynamic_input(field: &FieldModel, records: &BTreeMap<String, RecordModel>) -> bool {
    if record_pointer(field) {
        return true;
    }
    match &field.ty {
        SemanticType::String | SemanticType::Bytes | SemanticType::List { .. } => true,
        SemanticType::Record { name } => record_dynamic(name, records),
        _ => false,
    }
}

fn input_field_supported(field: &FieldModel, records: &BTreeMap<String, RecordModel>) -> bool {
    match &field.ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. } => {
            true
        }
        SemanticType::String => true,
        SemanticType::Bytes => count_field(field).is_some(),
        SemanticType::List { element } => {
            count_field(field).is_some() && list_element_supported(element, records)
        }
        SemanticType::Record { name } => record_supported(name, records),
        SemanticType::FixedArray { element, length } => {
            *length <= 64 && fixed_wire_type(element, records)
        }
        _ => false,
    }
}

fn list_element_supported(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::String => true,
        SemanticType::Scalar { name } if !matches!(name.as_str(), "bool" | "isize" | "usize") => {
            true
        }
        SemanticType::Enum { .. } => true,
        SemanticType::Record { name } => record_supported(name, records),
        _ => false,
    }
}

fn record_supported(name: &str, records: &BTreeMap<String, RecordModel>) -> bool {
    let Some(record) = records.get(name) else {
        return false;
    };
    let implicit = implicit_count_fields(&record.fields);
    record
        .fields
        .iter()
        .filter(|field| !implicit.contains(&field.name))
        .all(|field| match &field.ty {
            SemanticType::String => true,
            SemanticType::Bytes => count_field(field).is_some(),
            SemanticType::List { element } => {
                count_field(field).is_some()
                    && (matches!(element.as_ref(), SemanticType::String)
                        || fixed_wire_type(element, records))
            }
            other => fixed_wire_type(other, records),
        })
}

fn record_dynamic(name: &str, records: &BTreeMap<String, RecordModel>) -> bool {
    records.get(name).is_some_and(|record| {
        record.fields.iter().any(|field| {
            matches!(
                field.ty,
                SemanticType::String | SemanticType::Bytes | SemanticType::List { .. }
            )
        })
    })
}

fn collect_dynamic_records(
    ty: &SemanticType,
    records: &BTreeMap<String, RecordModel>,
    output: &mut BTreeSet<String>,
) {
    match ty {
        SemanticType::Record { name } if record_dynamic(name, records) => {
            output.insert(name.clone());
        }
        SemanticType::List { element } => collect_dynamic_records(element, records, output),
        _ => {}
    }
}

fn direct_type(ty: &SemanticType) -> bool {
    matches!(
        ty,
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. }
    )
}

fn fixed_wire_type(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. } => {
            true
        }
        SemanticType::FixedArray { element, length } => {
            *length <= 64 && fixed_wire_type(element, records)
        }
        SemanticType::Record { name } => records.get(name).is_some_and(|record| {
            record
                .fields
                .iter()
                .all(|field| fixed_wire_type(&field.ty, records))
        }),
        _ => false,
    }
}

fn fixed_wire_layout(
    ty: &SemanticType,
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i64" | "u64" | "isize" | "usize" | "f64" => Some((8, 8)),
            _ => Some((4, 4)),
        },
        SemanticType::Enum { .. } => Some((4, 4)),
        SemanticType::Handle { .. } => Some((8, 8)),
        SemanticType::FixedArray { element, length } => {
            let (bytes, alignment) = fixed_wire_layout(element, records)?;
            Some((bytes.checked_mul(u32::try_from(*length).ok()?)?, alignment))
        }
        SemanticType::Record { name } => layout_fields(&records.get(name)?.fields, records),
        _ => None,
    }
}

fn layout_fields(
    fields: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    let mut bytes = 0u32;
    let mut alignment = 1u32;
    for field in fields {
        let (field_bytes, field_alignment) = fixed_wire_layout(&field.ty, records)?;
        bytes = align_up(bytes, field_alignment).checked_add(field_bytes)?;
        alignment = alignment.max(field_alignment);
    }
    Some((align_up(bytes, alignment), alignment))
}

fn align_up(value: u32, alignment: u32) -> u32 {
    (value + alignment - 1) & !(alignment - 1)
}

fn descriptor_bytes(inputs: &[FieldModel]) -> Option<u32> {
    let count = inputs
        .iter()
        .filter(|field| !direct_type(&field.ty))
        .count();
    u32::try_from(count).ok()?.checked_mul(8)
}

fn render_owned_record(record: &RecordModel, records: &BTreeMap<String, RecordModel>) -> String {
    let name = &record.name;
    let mut members = String::new();
    let mut decode = String::new();
    let implicit = implicit_count_fields(&record.fields);

    for field in record
        .fields
        .iter()
        .filter(|field| !implicit.contains(&field.name))
    {
        let stem = sanitize(&field.name);
        match &field.ty {
            SemanticType::String => {
                members.push_str(&format!("    std::string {stem}Storage;\n"));
                decode.push_str(&format!(
                    "        {{ std::uint32_t coreLength = 0; if (!reader.U32(coreLength) || !CheckResultNodes(state, coreLength)) return false; std::span<const std::uint8_t> coreBytes; if (!reader.Bytes(coreLength, coreBytes)) return false; {stem}Storage.assign(reinterpret_cast<const char*>(coreBytes.data()), coreBytes.size()); value.{field_name} = {stem}Storage.data(); }}\n",
                    field_name = field.name,
                ));
            }
            SemanticType::Bytes => {
                let count = count_field(field).expect("supported bytes count");
                members.push_str(&format!("    std::vector<std::uint8_t> {stem}Storage;\n"));
                decode.push_str(&format!(
                    "        {{ std::uint32_t coreCount = 0; if (!reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) return false; std::span<const std::uint8_t> coreBytes; if (!reader.Bytes(coreCount, coreBytes)) return false; {stem}Storage.assign(coreBytes.begin(), coreBytes.end()); value.{field_name} = {stem}Storage.empty() ? nullptr : reinterpret_cast<std::remove_reference_t<decltype(value.{field_name})>>({stem}Storage.data()); if (!AssignDynamicCount(coreCount, value.{count})) return false; }}\n",
                    field_name = field.name,
                ));
            }
            SemanticType::List { element } if matches!(element.as_ref(), SemanticType::String) => {
                let count = count_field(field).expect("supported string-list count");
                members.push_str(&format!("    std::vector<std::string> {stem}Strings;\n    std::vector<const char*> {stem}Pointers;\n"));
                decode.push_str(&format!(
                    "        {{ std::uint32_t coreCount = 0; if (!reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) return false; {stem}Strings.clear(); {stem}Pointers.clear(); {stem}Strings.reserve(coreCount); for (std::uint32_t coreIndex = 0; coreIndex < coreCount; ++coreIndex) {{ std::uint32_t coreLength = 0; if (!reader.U32(coreLength)) return false; std::span<const std::uint8_t> coreBytes; if (!reader.Bytes(coreLength, coreBytes)) return false; {stem}Strings.emplace_back(reinterpret_cast<const char*>(coreBytes.data()), coreBytes.size()); }} {stem}Pointers.reserve({stem}Strings.size()); for (const auto& item : {stem}Strings) {stem}Pointers.push_back(item.c_str()); value.{field_name} = {stem}Pointers.empty() ? nullptr : {stem}Pointers.data(); if (!AssignDynamicCount(coreCount, value.{count})) return false; }}\n",
                    field_name = field.name,
                ));
            }
            SemanticType::List { element } => {
                let count = count_field(field).expect("supported list count");
                let cpp = native_cpp_type(element);
                members.push_str(&format!("    std::vector<{cpp}> {stem}Storage;\n"));
                let item_read = render_fixed_read(element, "item", records, "reader", 3);
                decode.push_str(&format!(
                    "        {{ std::uint32_t coreCount = 0; if (!reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) return false; {stem}Storage.clear(); {stem}Storage.reserve(coreCount); for (std::uint32_t coreIndex = 0; coreIndex < coreCount; ++coreIndex) {{ {cpp} item{{}};\n{item_read}            {stem}Storage.push_back(item); }} value.{field_name} = {stem}Storage.empty() ? nullptr : {stem}Storage.data(); if (!AssignDynamicCount(coreCount, value.{count})) return false; }}\n",
                    field_name = field.name,
                ));
            }
            other => {
                decode.push_str(&render_fixed_read(
                    other,
                    &format!("value.{}", field.name),
                    records,
                    "reader",
                    2,
                ));
            }
        }
    }

    format!(
        "struct CoreOwned_{name} {{\n    {name} value{{}};\n{members}\n    bool Decode(HostState* state, WireReader& reader)\n    {{\n{decode}        return true;\n    }}\n}};\n\n"
    )
}

fn render_callback(
    module_name: &str,
    function: &FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
) -> String {
    let callback = callback_name(module_name, &function.name);
    let api_member = native_member(module_name);
    let api_guard = native_guard(module_name);
    let slot_count = plan.direct_params.len().max(plan.direct_results.len());
    let input_descriptor_index = function
        .inputs
        .iter()
        .filter(|field| direct_type(&field.ty))
        .count();
    let input_descriptor_bytes =
        descriptor_bytes(&function.inputs).expect("dynamic input descriptor bytes");
    let mut body = format!(
        "wasm_trap_t* {callback}(void* environment, wasmtime_caller_t* caller,\n    wasmtime_val_raw_t* slots, std::size_t slotCount)\n{{\n    auto* state = static_cast<HostState*>(environment);\n    if (state == nullptr || state->native == nullptr || {api_guard} ||\n        state->native->{api_member}->{function_name} == nullptr)\n        return Trap(\"{function_name} dynamic-input Core binding is unavailable\");\n    if (slots == nullptr || slotCount != {slot_count}u)\n        return Trap(\"{function_name} dynamic-input Core ABI signature mismatch\");\n\n    std::string budgetError;\n    ImportGuard guard(state, {work}u, budgetError);\n    if (!guard.Ok()) return Trap(budgetError);\n    std::string memoryError;\n    if (!EnsureMemory(state, caller, memoryError)) return Trap(memoryError);\n\n    const std::uint32_t inputDescriptor = static_cast<std::uint32_t>(slots[{input_descriptor_index}].i32);\n    std::span<const std::uint8_t> inputDescriptorWire;\n    if (!state->memory.View(inputDescriptor, {input_descriptor_bytes}u, inputDescriptorWire)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds); return nullptr; }}\n    WireReader inputControl(inputDescriptorWire);\n\n    {query_type} query{{}};\n",
        callback = callback,
        api_guard = api_guard,
        api_member = api_member,
        function_name = function.name,
        slot_count = slot_count,
        work = 1 + plan.direct_params.len(),
        input_descriptor_index = input_descriptor_index,
        input_descriptor_bytes = input_descriptor_bytes,
        query_type = function.query,
    );

    let mut direct_slot = 0usize;
    for field in &function.inputs {
        if direct_type(&field.ty) {
            body.push_str(&format!(
                "    query.{name} = {expr};\n",
                name = field.name,
                expr = query_expr(&field.ty, direct_slot, &format!("query.{}", field.name)),
            ));
            direct_slot += 1;
            continue;
        }
        let stem = sanitize(&field.name);
        body.push_str(&format!(
            "    std::uint32_t {stem}Pointer = 0, {stem}Bytes = 0;\n    if (!inputControl.U32({stem}Pointer) || !inputControl.U32({stem}Bytes)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }}\n    if (!guard.Charge({stem}Bytes)) return Trap(budgetError);\n    std::span<const std::uint8_t> {stem}Wire;\n    if (!state->memory.View({stem}Pointer, {stem}Bytes, {stem}Wire)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds); return nullptr; }}\n    WireReader {stem}Reader({stem}Wire);\n",
        ));
        body.push_str(&render_top_input(field, records, &stem));
        body.push_str(&format!(
            "    if (!{stem}Reader.Finish(1)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }}\n"
        ));
    }
    body.push_str("    if (!inputControl.Finish(4)) { slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }\n");

    if matches!(
        plan.result_strategy,
        ResultStrategy::FixedOutputBuffer { .. } | ResultStrategy::VariableOutputBuffer
    ) {
        body.push_str(&render_output_setup(function, plan, records));
    }

    body.push_str(&format!(
        "\n    {result_type} result{{}};\n    state->native->{api_member}->{function_name}(&query, &result);\n    const std::int32_t errorCode = NativeErrorCode(result.error);\n",
        result_type = function.result,
        api_member = api_member,
        function_name = function.name,
    ));
    body.push_str(&render_result(function, plan, records));
    body.push_str("}\n");
    body
}

fn render_top_input(
    field: &FieldModel,
    records: &BTreeMap<String, RecordModel>,
    stem: &str,
) -> String {
    match &field.ty {
        SemanticType::String => format!(
            "    std::string {stem}Storage;\n    {{ std::uint32_t coreLength = 0; if (!{stem}Reader.U32(coreLength) || !CheckResultNodes(state, coreLength)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} std::span<const std::uint8_t> coreBytes; if (!{stem}Reader.Bytes(coreLength, coreBytes)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Storage.assign(reinterpret_cast<const char*>(coreBytes.data()), coreBytes.size()); query.{field_name} = {stem}Storage.data(); }}\n",
            field_name = field.name,
        ),
        SemanticType::Bytes => {
            let count = count_field(field).expect("supported bytes count");
            format!(
                "    std::vector<std::uint8_t> {stem}Storage;\n    {{ std::uint32_t coreCount = 0; if (!{stem}Reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} std::span<const std::uint8_t> coreBytes; if (!{stem}Reader.Bytes(coreCount, coreBytes)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Storage.assign(coreBytes.begin(), coreBytes.end()); query.{field_name} = {stem}Storage.empty() ? nullptr : reinterpret_cast<std::remove_reference_t<decltype(query.{field_name})>>({stem}Storage.data()); if (!AssignDynamicCount(coreCount, query.{count})) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} }}\n",
                field_name = field.name,
            )
        }
        SemanticType::List { element } => {
            let count = count_field(field).expect("supported list count");
            if matches!(element.as_ref(), SemanticType::String) {
                return format!(
                    "    std::vector<std::string> {stem}Strings;\n    std::vector<const char*> {stem}Pointers;\n    {{ std::uint32_t coreCount = 0; if (!{stem}Reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Strings.reserve(coreCount); for (std::uint32_t coreIndex = 0; coreIndex < coreCount; ++coreIndex) {{ std::uint32_t coreLength = 0; if (!{stem}Reader.U32(coreLength)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} std::span<const std::uint8_t> coreBytes; if (!{stem}Reader.Bytes(coreLength, coreBytes)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Strings.emplace_back(reinterpret_cast<const char*>(coreBytes.data()), coreBytes.size()); }} {stem}Pointers.reserve({stem}Strings.size()); for (const auto& item : {stem}Strings) {stem}Pointers.push_back(item.c_str()); query.{field_name} = {stem}Pointers.empty() ? nullptr : {stem}Pointers.data(); if (!AssignDynamicCount(coreCount, query.{count})) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} }}\n",
                    field_name = field.name,
                );
            }
            if let SemanticType::Record { name } = element.as_ref()
                && record_dynamic(name, records)
            {
                return format!(
                    "    std::vector<CoreOwned_{name}> {stem}Owners;\n    std::vector<{name}> {stem}Values;\n    {{ std::uint32_t coreCount = 0; if (!{stem}Reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Owners.resize(coreCount); {stem}Values.resize(coreCount); for (std::uint32_t coreIndex = 0; coreIndex < coreCount; ++coreIndex) {{ if (!{stem}Owners[coreIndex].Decode(state, {stem}Reader)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Values[coreIndex] = {stem}Owners[coreIndex].value; }} query.{field_name} = {stem}Values.empty() ? nullptr : {stem}Values.data(); if (!AssignDynamicCount(coreCount, query.{count})) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} }}\n",
                    field_name = field.name,
                );
            }
            let cpp = native_cpp_type(element);
            let item_read =
                render_fixed_read(element, "item", records, &format!("{stem}Reader"), 4);
            format!(
                "    std::vector<{cpp}> {stem}Storage;\n    {{ std::uint32_t coreCount = 0; if (!{stem}Reader.U32(coreCount) || !CheckResultNodes(state, coreCount)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Storage.reserve(coreCount); for (std::uint32_t coreIndex = 0; coreIndex < coreCount; ++coreIndex) {{ {cpp} item{{}}; bool coreItemOk = [&]() -> bool {{\n{item_read}                return true;\n            }}(); if (!coreItemOk) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} {stem}Storage.push_back(item); }} query.{field_name} = {stem}Storage.empty() ? nullptr : {stem}Storage.data(); if (!AssignDynamicCount(coreCount, query.{count})) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }} }}\n",
                field_name = field.name,
            )
        }
        SemanticType::Record { name } if record_dynamic(name, records) || record_pointer(field) => {
            let assign = if record_pointer(field) {
                format!("query.{} = &{stem}Owner.value;", field.name)
            } else {
                format!("query.{} = {stem}Owner.value;", field.name)
            };
            format!(
                "    CoreOwned_{name} {stem}Owner;\n    if (!{stem}Owner.Decode(state, {stem}Reader)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }}\n    {assign}\n"
            )
        }
        other => {
            let read = render_fixed_read(
                other,
                &format!("query.{}", field.name),
                records,
                &format!("{stem}Reader"),
                2,
            );
            format!(
                "    const bool {stem}Ok = [&]() -> bool {{\n{read}        return true;\n    }}();\n    if (!{stem}Ok) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }}\n"
            )
        }
    }
}

fn variable_result_supported(
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    if outputs.len() != 1 {
        return false;
    }
    let field = &outputs[0];
    match &field.ty {
        SemanticType::List { element } => {
            count_field(field).is_some() && fixed_wire_type(element, records)
        }
        _ => false,
    }
}

fn render_output_setup(
    function: &FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
) -> String {
    let index = plan.direct_params.len() - 1;
    match plan.result_strategy {
        ResultStrategy::FixedOutputBuffer { bytes, .. } => format!(
            "    const std::uint32_t output = static_cast<std::uint32_t>(slots[{index}].i32);\n    if (!state->memory.Contains(output, {bytes}u)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds); return nullptr; }}\n"
        ),
        ResultStrategy::VariableOutputBuffer => {
            let field = &function.outputs[0];
            let SemanticType::List { element } = &field.ty else {
                unreachable!()
            };
            let (element_bytes, _) =
                fixed_wire_layout(element, records).expect("variable result element layout");
            format!(
                "    const std::uint32_t outputDescriptor = static_cast<std::uint32_t>(slots[{index}].i32);\n    std::span<std::uint8_t> outputControlWire;\n    if (!state->memory.MutableView(outputDescriptor, 12u, outputControlWire)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds); return nullptr; }}\n    WireReader outputControl(std::span<const std::uint8_t>(outputControlWire.data(), outputControlWire.size()));\n    std::uint32_t outputPointer = 0, outputCapacity = 0, outputIgnoredLength = 0;\n    if (!outputControl.U32(outputPointer) || !outputControl.U32(outputCapacity) || !outputControl.U32(outputIgnoredLength) || !outputControl.Finish(4)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument); return nullptr; }}\n    const std::uint64_t outputCapacityBytes = static_cast<std::uint64_t>(outputCapacity) * {element_bytes}u;\n    if (outputCapacityBytes > std::numeric_limits<std::size_t>::max() || !state->memory.Contains(outputPointer, static_cast<std::size_t>(outputCapacityBytes))) {{ slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds); return nullptr; }}\n"
            )
        }
        _ => String::new(),
    }
}

fn render_result(
    function: &FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
) -> String {
    match plan.result_strategy {
        ResultStrategy::Status => "    slots[0].i32 = errorCode;\n    return nullptr;\n".to_owned(),
        ResultStrategy::Packed32 => {
            let field = &function.outputs[0];
            format!(
                "    slots[0].i64 = static_cast<std::int64_t>(PackU32({value}, errorCode));\n    return nullptr;\n",
                value = packed32_expr(&field.ty, &format!("result.{}", field.name)),
            )
        }
        ResultStrategy::FixedOutputBuffer { bytes, alignment } => {
            let mut output =
                "    if (errorCode != 0) { slots[0].i32 = errorCode; return nullptr; }\n"
                    .to_owned();
            output.push_str(&format!(
                "    std::array<std::uint8_t, {bytes}> wire{{}};\n    WireWriter writer(wire);\n"
            ));
            for field in &function.outputs {
                output.push_str(&render_fixed_write(
                    &field.ty,
                    &format!("result.{}", field.name),
                    records,
                    "writer",
                    1,
                ));
            }
            output.push_str(&format!(
                "    if (!writer.Finish({alignment}u)) return Trap(\"dynamic-input Core fixed output layout mismatch\");\n    if (!state->memory.Write(output, wire.data(), wire.size())) return Trap(\"dynamic-input Core output range changed unexpectedly\");\n    slots[0].i32 = 0;\n    return nullptr;\n"
            ));
            output
        }
        ResultStrategy::VariableOutputBuffer => {
            let field = &function.outputs[0];
            let count = count_field(field).expect("variable output count");
            let SemanticType::List { element } = &field.ty else {
                unreachable!()
            };
            let (element_bytes, _) =
                fixed_wire_layout(element, records).expect("variable result element layout");
            let item_write = render_fixed_write(
                element,
                &format!("result.{}[coreIndex]", field.name),
                records,
                "writer",
                2,
            );
            format!(
                "    if (errorCode != 0) {{ slots[0].i32 = errorCode; return nullptr; }}\n    std::uint32_t required = 0;\n    if (!AssignDynamicCount(result.{count}, required) || (required != 0 && result.{field_name} == nullptr)) {{ slots[0].i32 = static_cast<std::int32_t>(Status::OperationFailed); return nullptr; }}\n    if (!WriteDynamicU32(outputControlWire, 8u, required)) return Trap(\"dynamic-input output descriptor changed unexpectedly\");\n    if (outputCapacity < required) {{ slots[0].i32 = static_cast<std::int32_t>(Status::BufferOverflow); return nullptr; }}\n    const std::uint64_t requiredBytes64 = static_cast<std::uint64_t>(required) * {element_bytes}u;\n    if (requiredBytes64 > std::numeric_limits<std::size_t>::max() || !CheckResultBytes(state, static_cast<std::size_t>(requiredBytes64))) {{ slots[0].i32 = static_cast<std::int32_t>(Status::BufferOverflow); return nullptr; }}\n    if (!guard.Charge(requiredBytes64)) return Trap(budgetError);\n    std::span<std::uint8_t> outputWire;\n    if (!state->memory.MutableView(outputPointer, static_cast<std::size_t>(requiredBytes64), outputWire)) return Trap(\"dynamic-input output range changed unexpectedly\");\n    WireWriter writer(outputWire);\n    for (std::uint32_t coreIndex = 0; coreIndex < required; ++coreIndex) {{\n{item_write}    }}\n    if (!writer.Finish(1)) return Trap(\"dynamic-input variable output layout mismatch\");\n    slots[0].i32 = 0;\n    return nullptr;\n",
                field_name = field.name,
            )
        }
        ResultStrategy::Unsupported => unreachable!(),
    }
}

fn render_fixed_read(
    ty: &SemanticType,
    destination: &str,
    records: &BTreeMap<String, RecordModel>,
    reader: &str,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!("{pad}if (!{reader}.Bool({destination})) return false;\n"),
            "f32" => format!("{pad}if (!{reader}.F32({destination})) return false;\n"),
            "f64" => format!("{pad}if (!{reader}.F64({destination})) return false;\n"),
            "i64" | "isize" => scalar_read(reader, "I64", "std::int64_t", destination, &pad),
            "u64" | "usize" => scalar_read(reader, "U64", "std::uint64_t", destination, &pad),
            "i8" | "i16" | "i32" => scalar_read(reader, "I32", "std::int32_t", destination, &pad),
            _ => scalar_read(reader, "U32", "std::uint32_t", destination, &pad),
        },
        SemanticType::Enum { .. } => scalar_read(reader, "I32", "std::int32_t", destination, &pad),
        SemanticType::Handle { .. } => {
            scalar_read(reader, "U64", "std::uint64_t", destination, &pad)
        }
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|field| {
                    render_fixed_read(
                        &field.ty,
                        &format!("{destination}.{}", field.name),
                        records,
                        reader,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) = fixed_wire_layout(ty, records).expect("fixed record layout");
            output.push_str(&format!(
                "{pad}if (!{reader}.Align({alignment}u)) return false;\n"
            ));
            output
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreReadIndex{indent}");
            let nested = render_fixed_read(
                element,
                &format!("{destination}[{index}]"),
                records,
                reader,
                indent + 1,
            );
            format!(
                "{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n"
            )
        }
        _ => unreachable!("unsupported fixed dynamic-input field"),
    }
}

fn scalar_read(reader: &str, method: &str, raw: &str, destination: &str, pad: &str) -> String {
    format!(
        "{pad}{{ {raw} coreRaw = 0; if (!{reader}.{method}(coreRaw)) return false; {destination} = {cast}; }}\n",
        cast = native_cast(destination, "coreRaw")
    )
}

fn render_fixed_write(
    ty: &SemanticType,
    value: &str,
    records: &BTreeMap<String, RecordModel>,
    writer: &str,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => {
            let method = match name.as_str() {
                "bool" => "Bool",
                "f32" => "F32",
                "f64" => "F64",
                "i64" | "isize" => "I64",
                "u64" | "usize" => "U64",
                "i8" | "i16" | "i32" => "I32",
                _ => "U32",
            };
            format!(
                "{pad}if (!{writer}.{method}({value})) return Trap(\"dynamic-input Core wire overflow\");\n"
            )
        }
        SemanticType::Enum { .. } => format!(
            "{pad}if (!{writer}.I32(static_cast<std::int32_t>({value}))) return Trap(\"dynamic-input Core wire overflow\");\n"
        ),
        SemanticType::Handle { .. } => format!(
            "{pad}if (!{writer}.U64(static_cast<std::uint64_t>({value}))) return Trap(\"dynamic-input Core wire overflow\");\n"
        ),
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|field| {
                    render_fixed_write(
                        &field.ty,
                        &format!("{value}.{}", field.name),
                        records,
                        writer,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) = fixed_wire_layout(ty, records).expect("fixed record layout");
            output.push_str(&format!("{pad}if (!{writer}.Align({alignment}u)) return Trap(\"dynamic-input Core record alignment overflow\");\n"));
            output
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreWriteIndex{indent}");
            let nested = render_fixed_write(
                element,
                &format!("{value}[{index}]"),
                records,
                writer,
                indent + 1,
            );
            format!(
                "{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n"
            )
        }
        _ => unreachable!(),
    }
}

fn query_expr(ty: &SemanticType, slot: usize, destination: &str) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!("slots[{slot}].i32 != 0"),
            "f32" => format!("slots[{slot}].f32"),
            "f64" => format!("slots[{slot}].f64"),
            "i64" | "u64" | "isize" | "usize" => {
                native_cast(destination, &format!("slots[{slot}].i64"))
            }
            _ => native_cast(destination, &format!("slots[{slot}].i32")),
        },
        SemanticType::Enum { .. } => native_cast(destination, &format!("slots[{slot}].i32")),
        SemanticType::Handle { .. } => native_cast(destination, &format!("slots[{slot}].i64")),
        _ => unreachable!(),
    }
}

fn packed32_expr(ty: &SemanticType, value: &str) -> String {
    match ty {
        SemanticType::Scalar { name } if name == "f32" => {
            format!("std::bit_cast<std::uint32_t>({value})")
        }
        SemanticType::Scalar { name } if name == "bool" => {
            format!("static_cast<std::uint32_t>({value} ? 1u : 0u)")
        }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => {
            format!("static_cast<std::uint32_t>({value})")
        }
        _ => unreachable!(),
    }
}

fn native_cast(destination: &str, value: &str) -> String {
    format!(
        "static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>({value})"
    )
}

fn native_cpp_type(ty: &SemanticType) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i8" => "std::int8_t".to_owned(),
            "u8" | "char" => "std::uint8_t".to_owned(),
            "i16" => "std::int16_t".to_owned(),
            "u16" => "std::uint16_t".to_owned(),
            "i32" => "std::int32_t".to_owned(),
            "u32" => "std::uint32_t".to_owned(),
            "i64" | "isize" => "std::int64_t".to_owned(),
            "u64" | "usize" => "std::uint64_t".to_owned(),
            "f32" => "float".to_owned(),
            "f64" => "double".to_owned(),
            other => other.to_owned(),
        },
        SemanticType::Enum { name } | SemanticType::Record { name } => name.clone(),
        SemanticType::Handle { .. } => "std::uint64_t".to_owned(),
        _ => unreachable!(),
    }
}

fn record_pointer(field: &FieldModel) -> bool {
    field
        .metadata
        .iter()
        .any(|metadata| metadata.starts_with("spring.wasm.record:"))
}

fn count_field(field: &FieldModel) -> Option<String> {
    field.metadata.iter().find_map(|metadata| {
        metadata
            .strip_prefix("count-field:")
            .map(ToString::to_string)
    })
}

fn implicit_count_fields(fields: &[FieldModel]) -> BTreeSet<String> {
    fields.iter().filter_map(count_field).collect()
}

fn render_registration(plan: &FunctionPlan, callback: &str) -> String {
    let params = kind_array("params", &plan.direct_params);
    let results = kind_array("results", &plan.direct_results);
    format!(
        "    {{\n{params}{results}        if (!DefineGeneratedDynamicInput(linker, \"{module}\", \"{name}\",\n                MakeFuncType(params, {pc}, results, {rc}), {callback}, state, error))\n            return false;\n    }}\n",
        params = params,
        results = results,
        module = plan.import_module,
        name = plan.import_name,
        pc = plan.direct_params.len(),
        rc = plan.direct_results.len(),
        callback = callback,
    )
}

fn kind_array(name: &str, kinds: &[CoreType]) -> String {
    if kinds.is_empty() {
        return format!("        const wasm_valkind_t* {name} = nullptr;\n");
    }
    format!(
        "        const wasm_valkind_t {name}[] = {{{}}};\n",
        kinds
            .iter()
            .map(|kind| match kind {
                CoreType::I32 => "WASM_I32",
                CoreType::I64 => "WASM_I64",
                CoreType::F32 => "WASM_F32",
                CoreType::F64 => "WASM_F64",
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn callback_name(module: &str, function: &str) -> String {
    format!(
        "CoreDynamicInput_{}_{}",
        module.to_snake_case(),
        function.to_snake_case()
    )
}

fn native_member(module: &str) -> String {
    spring_native_codegen::render_core_native::core_native_member(module)
        .unwrap_or_else(|| panic!("no NativeInterface member mapped for module {module}"))
}

fn native_guard(module: &str) -> String {
    spring_native_codegen::render_core_native::core_native_guard(module)
        .unwrap_or_else(|| panic!("no NativeInterface member mapped for module {module}"))
}

fn sanitize(value: &str) -> String {
    value
        .to_lower_camel_case()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

fn plan_index(model: &ApiModel) -> BTreeMap<(String, String), FunctionPlan> {
    render_core_wasm::plan(model)
        .functions
        .into_iter()
        .map(|plan| ((plan.module.clone(), plan.function.clone()), plan))
        .collect()
}

fn record_index(model: &ApiModel) -> BTreeMap<String, RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records
                .entry(record.name.clone())
                .or_insert_with(|| record.clone());
        }
    }
    records
}
