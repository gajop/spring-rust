//! Core-Wasm fallback for recursively variable callout results.
//!
//! Optimized fixed/caller-owned variable-output renderers handle flat shapes.
//! This renderer is deliberately last: it covers results such as
//! `list<CommandFFI>` where each record itself owns a variable list, and records
//! such as `FactoryQueueInfo` that contain multiple owned lists.
//!
//! The guest supplies one 12-byte output descriptor `{ptr, capacity, required}`.
//! The payload is a schema-driven canonical stream: little-endian scalar values,
//! u32-length-prefixed strings/bytes/lists, records in semantic field order and
//! fixed arrays in element order. Native count fields represented by semantic
//! list metadata are not emitted separately.

use heck::ToSnakeCase;
use std::collections::{BTreeMap, BTreeSet};

use crate::model::{ApiModel, FieldModel, RecordModel, SemanticType};
use crate::render_core_wasm::{self, CoreType, FunctionPlan, InputStrategy, ResultStrategy};
use crate::render_core_wasm_variable_io_host;
use crate::render_core_wasm_variable_output_host;

pub fn render_header() -> String {
    r#"/* @generated by spring-api-codegen; do not edit. */
#pragma once

#include <string>

#include "WasmInterface/WasmCoreBindings.h"

namespace recoil::wasm::core::generated {

bool RegisterGeneratedDynamicOutputImports(wasmtime_linker_t* linker, HostState* state,
    std::string& error);

} // namespace recoil::wasm::core::generated
"#
    .to_owned()
}

pub fn render_cpp(model: &ApiModel) -> String {
    let records = record_index(model);
    let plans = render_core_wasm::plan(model)
        .functions
        .into_iter()
        .map(|plan| ((plan.module.clone(), plan.function.clone()), plan))
        .collect::<BTreeMap<_, _>>();
    let mut callbacks = String::new();
    let mut registrations = String::new();
    let mut generated_count = 0usize;

    for module in &model.modules {
        for function in &module.functions {
            let Some(plan) = plans.get(&(module.name.clone(), function.name.clone())) else {
                continue;
            };
            if !eligible(plan, &function.inputs, &function.outputs, &records) {
                continue;
            }
            generated_count += 1;
            callbacks.push_str(&render_callback(&module.name, function, plan, &records));
            callbacks.push('\n');
            registrations.push_str(&render_registration(
                plan,
                &callback_name(&module.name, &function.name),
            ));
        }
    }

    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */

#include "wasm/generated/WasmCoreGeneratedDynamicOutputBindings.h"

#include <bit>
#include <cstdint>
#include <limits>
#include <span>
#include <string>
#include <string_view>
#include <type_traits>
#include <vector>

#include "NativeInterface/NativeInterface.h"
#include "WasmInterface/WasmCoreAbi.h"
#include "WasmInterface/WasmCoreGeneratedSupport.h"
#include "WasmInterface/WasmCoreWire.h"

namespace recoil::wasm::core::generated {{
namespace {{

class DynamicSizeWriter {{
public:
    bool Bool(bool) {{ return U32(0); }}
    bool I32(std::int32_t) {{ return U32(0); }}
    bool U32(std::uint32_t) {{ return Add(4u, 4u); }}
    bool I64(std::int64_t) {{ return U64(0); }}
    bool U64(std::uint64_t) {{ return Add(8u, 8u); }}
    bool F32(float) {{ return U32(0); }}
    bool F64(double) {{ return U64(0); }}

    bool Bytes(std::span<const std::uint8_t> value, std::size_t alignment = 1)
    {{
        return Add(value.size(), alignment);
    }}

    bool Align(std::size_t alignment)
    {{
        if (alignment == 0 || (alignment & (alignment - 1u)) != 0)
            return false;
        if (cursor > std::numeric_limits<std::size_t>::max() - (alignment - 1u))
            return false;
        cursor = (cursor + alignment - 1u) & ~(alignment - 1u);
        return true;
    }}

    std::size_t Offset() const {{ return cursor; }}

private:
    bool Add(std::size_t bytes, std::size_t alignment)
    {{
        if (!Align(alignment) || bytes > std::numeric_limits<std::size_t>::max() - cursor)
            return false;
        cursor += bytes;
        return true;
    }}

    std::size_t cursor = 0;
}};

// Shared with the variable-input lowering this renderer reuses: a guest-supplied
// u32 count only reaches the native query when it fits the native field.
template<typename T>
bool AssignCoreCount(std::uint32_t value, T& output)
{{
    using Native = std::remove_cv_t<std::remove_reference_t<T>>;
    static_assert(std::is_integral_v<Native>);
    if (static_cast<std::uint64_t>(value) >
        static_cast<std::uint64_t>(std::numeric_limits<Native>::max()))
        return false;
    output = static_cast<Native>(value);
    return true;
}}

template<typename T>
bool NormalizeDynamicCount(T value, std::uint32_t& output)
{{
    using Native = std::remove_cv_t<std::remove_reference_t<T>>;
    static_assert(std::is_integral_v<Native>);
    if constexpr (std::numeric_limits<Native>::is_signed) {{
        if (value < 0)
            return false;
    }}
    const std::uint64_t wide = static_cast<std::uint64_t>(value);
    if (wide > std::numeric_limits<std::uint32_t>::max())
        return false;
    output = static_cast<std::uint32_t>(wide);
    return true;
}}

bool WriteDynamicRequired(std::span<std::uint8_t> descriptor, std::uint32_t required)
{{
    if (descriptor.size() < 12u)
        return false;
    descriptor[8] = static_cast<std::uint8_t>(required);
    descriptor[9] = static_cast<std::uint8_t>(required >> 8);
    descriptor[10] = static_cast<std::uint8_t>(required >> 16);
    descriptor[11] = static_cast<std::uint8_t>(required >> 24);
    return true;
}}

bool DefineGeneratedDynamicOutput(wasmtime_linker_t* linker, const char* moduleName,
    const char* functionName, wasm_functype_t* type,
    wasmtime_func_unchecked_callback_t callback, HostState* state, std::string& error)
{{
    wasmtime_error_t* defineError = wasmtime_linker_define_func_unchecked(
        linker,
        moduleName, std::char_traits<char>::length(moduleName),
        functionName, std::char_traits<char>::length(functionName),
        type, callback, state, nullptr);
    wasm_functype_delete(type);
    if (defineError == nullptr)
        return true;
    error = ErrorMessage(defineError);
    return false;
}}

{callbacks}
}} // namespace

bool RegisterGeneratedDynamicOutputImports(wasmtime_linker_t* linker, HostState* state,
    std::string& error)
{{
    if (linker == nullptr || state == nullptr || state->native == nullptr) {{
        error = "cannot register dynamic-output Core imports without linker/host/native API";
        return false;
    }}
{registrations}
    return true;
}}

static_assert({generated_count}u >= 0u, "generated dynamic-output Core callback count");

}} // namespace recoil::wasm::core::generated
"#,
        callbacks = callbacks,
        registrations = registrations,
        generated_count = generated_count,
    )
}

/// Last-resort production result transport. It pairs with either all-direct
/// inputs or the shared borrowed variable-input descriptor; the flat
/// caller-owned renderers still claim every result they can encode, so this one
/// only sees results that are recursively variable.
pub(crate) fn eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    // A reviewed handwritten transport already owns this import.
    if crate::render_core_wasm_registry::handwritten_reviewed(&plan.module, &plan.function) {
        return false;
    }
    if matches!(plan.source_status.as_str(), "manual" | "unsupported")
        || !matches!(plan.result_strategy, ResultStrategy::VariableOutputBuffer)
        || outputs.is_empty()
        || !fields_supported(outputs, records)
    {
        return false;
    }
    // Deliberately last: whenever a flat caller-owned renderer can encode this
    // result, it keeps it. Claiming those here would both slow them down and
    // define the same import twice.
    if render_core_wasm_variable_output_host::eligible(plan, inputs, outputs, records)
        || render_core_wasm_variable_io_host::eligible(plan, inputs, outputs, records)
    {
        return false;
    }
    match plan.input_strategy {
        InputStrategy::Direct => inputs.iter().all(|field| direct_type(&field.ty)),
        // A fixed input buffer is the same descriptor read with no variable
        // fields in it, so both go through the shared lowering.
        InputStrategy::VariableInputBuffer | InputStrategy::FixedInputBuffer => {
            descriptor_inputs_supported(inputs, records)
        }
        _ => false,
    }
}

/// True when this call reads its inputs through the shared input descriptor
/// rather than plain slots.
pub(crate) fn variable_input(plan: &FunctionPlan) -> bool {
    matches!(
        plan.input_strategy,
        InputStrategy::VariableInputBuffer | InputStrategy::FixedInputBuffer
    )
}

fn descriptor_inputs_supported(
    inputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    render_core_wasm_variable_io_host::input_descriptor_layout(inputs, records).is_some()
        && inputs
            .iter()
            .all(|field| render_core_wasm_variable_io_host::input_field_supported(field, records))
}

fn fields_supported(fields: &[FieldModel], records: &BTreeMap<String, RecordModel>) -> bool {
    let implicit = implicit_count_fields(fields);
    fields
        .iter()
        .filter(|field| !implicit.contains(&field.name))
        .all(|field| field_supported(field, records))
}

fn field_supported(field: &FieldModel, records: &BTreeMap<String, RecordModel>) -> bool {
    match &field.ty {
        SemanticType::Bytes | SemanticType::List { .. } if count_field(field).is_none() => false,
        SemanticType::Option { inner } => {
            presence_field(field).is_some() && type_supported(inner, records)
        }
        ty => type_supported(ty, records),
    }
}

fn presence_field(field: &FieldModel) -> Option<String> {
    field.metadata.iter().find_map(|metadata| {
        metadata
            .strip_prefix("presence-field:")
            .map(ToString::to_string)
    })
}

fn type_supported(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. }
        | SemanticType::Enum { .. }
        | SemanticType::Handle { .. }
        | SemanticType::String
        | SemanticType::Bytes => true,
        SemanticType::List { element } => list_element_supported(element, records),
        SemanticType::FixedArray { element, length } => {
            *length <= 1024
                && !matches!(
                    element.as_ref(),
                    SemanticType::Bytes | SemanticType::List { .. }
                )
                && type_supported(element, records)
        }
        SemanticType::Record { name } => records
            .get(name)
            .is_some_and(|record| fields_supported(&record.fields, records)),
        SemanticType::Result { .. }
        | SemanticType::Callback { .. }
        | SemanticType::Pointer { .. }
        | SemanticType::Unknown { .. }
        // An option is only encodable through its field, which carries the
        // presence metadata; `field_supported` handles that case.
        | SemanticType::Option { .. } => false,
    }
}

fn list_element_supported(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. }
        | SemanticType::Enum { .. }
        | SemanticType::Handle { .. }
        | SemanticType::String => true,
        SemanticType::Record { name } => records
            .get(name)
            .is_some_and(|record| fields_supported(&record.fields, records)),
        SemanticType::FixedArray { element, length } => {
            *length <= 1024
                && !matches!(
                    element.as_ref(),
                    SemanticType::Bytes | SemanticType::List { .. }
                )
                && type_supported(element, records)
        }
        _ => false,
    }
}

fn direct_type(ty: &SemanticType) -> bool {
    matches!(
        ty,
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. }
    )
}

fn render_callback(
    module_name: &str,
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
) -> String {
    let callback = callback_name(module_name, &function.name);
    let api_member = native_member(module_name);
    let api_guard = native_guard(module_name);
    let slot_count = plan.direct_params.len().max(plan.direct_results.len());
    let output_index = plan.direct_params.len() - 1;

    let mut encode = String::new();
    let implicit = implicit_count_fields(&function.outputs);
    for field in function
        .outputs
        .iter()
        .filter(|field| !implicit.contains(&field.name))
    {
        encode.push_str(&render_field(
            field,
            &format!("result.{}", field.name),
            "result.",
            records,
            2,
        ));
    }

    // Direct inputs occupy the leading slots; a variable input descriptor, when
    // present, is the slot right after them and the output descriptor is last.
    let mut query_assign = String::new();
    let mut direct_slot = 0usize;
    for field in &function.inputs {
        if render_core_wasm_variable_io_host::direct_type(&field.ty) {
            query_assign.push_str(&format!(
                "    query.{name} = {expr};\n",
                name = field.name,
                expr = query_expr(&field.ty, direct_slot, &format!("query.{}", field.name)),
            ));
            direct_slot += 1;
        } else if render_core_wasm_variable_io_host::variable_type(&field.ty) {
            query_assign.push_str(&render_core_wasm_variable_io_host::render_input_variable(
                field, records,
            ));
        } else {
            query_assign.push_str(&render_core_wasm_variable_io_host::render_wire_read(
                &field.ty,
                &format!("query.{}", field.name),
                records,
                "reader",
                1,
            ));
        }
    }

    let mut input_setup = String::new();
    if variable_input(plan) {
        let (input_bytes, input_alignment) =
            render_core_wasm_variable_io_host::input_descriptor_layout(&function.inputs, records)
                .expect("eligible dynamic-output input descriptor");
        // Read the input descriptor slot before anything can write slots[0],
        // which doubles as the status result.
        input_setup = format!(
            "    const std::uint32_t inputDescriptor = static_cast<std::uint32_t>(slots[{direct_slot}].i32);\n    std::span<const std::uint8_t> inputWire;\n    if (!state->memory.View(inputDescriptor, {input_bytes}u, inputWire)) {{\n        slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds);\n        return nullptr;\n    }}\n    WireReader reader(inputWire);\n"
        );
        query_assign.push_str(&format!(
            "    if (!reader.Finish({input_alignment}u)) {{\n        slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument);\n        return nullptr;\n    }}\n"
        ));
    }

    format!(
        "wasm_trap_t* {callback}(void* environment, wasmtime_caller_t* caller,\n\
             wasmtime_val_raw_t* slots, std::size_t slotCount)\n\
         {{\n\
             auto* state = static_cast<HostState*>(environment);\n\
             if (state == nullptr || state->native == nullptr || {api_guard} ||\n\
                 state->native->{api_member}->{function_name} == nullptr)\n\
                 return Trap(\"{function_name} dynamic-output Core binding is unavailable\");\n\
             if (slots == nullptr || slotCount != {slot_count}u)\n\
                 return Trap(\"{function_name} dynamic-output Core ABI signature mismatch\");\n\n\
             std::string budgetError;\n\
             ImportGuard guard(state, {work}u, budgetError);\n\
             if (!guard.Ok()) return Trap(budgetError);\n\n\
             std::string memoryError;\n\
             if (!EnsureMemory(state, caller, memoryError)) return Trap(memoryError);\n\
         {input_setup}\
             const std::uint32_t descriptorOffset = static_cast<std::uint32_t>(slots[{output_index}].i32);\n\
             std::span<std::uint8_t> descriptor;\n\
             if (!state->memory.MutableView(descriptorOffset, 12u, descriptor)) {{\n\
                 slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds);\n\
                 return nullptr;\n\
             }}\n\
             WireReader control(std::span<const std::uint8_t>(descriptor.data(), descriptor.size()));\n\
             std::uint32_t outputPointer = 0, outputCapacity = 0, ignoredRequired = 0;\n\
             if (!control.U32(outputPointer) || !control.U32(outputCapacity) ||\n\
                 !control.U32(ignoredRequired) || !control.Finish(4)) {{\n\
                 slots[0].i32 = static_cast<std::int32_t>(Status::InvalidArgument);\n\
                 return nullptr;\n\
             }}\n\
             if (!state->memory.Contains(outputPointer, outputCapacity)) {{\n\
                 slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds);\n\
                 return nullptr;\n\
             }}\n\n\
             {query_type} query{{}};\n\
         {query_assign}\
             {result_type} result{{}};\n\
             state->native->{api_member}->{function_name}(&query, &result);\n\
             const std::int32_t errorCode = NativeErrorCode(result.error);\n\
             if (errorCode != 0) {{ slots[0].i32 = errorCode; return nullptr; }}\n\n\
             auto encode = [&](auto& writer) -> bool {{\n\
         {encode}\
                 return writer.Align(8u);\n\
             }};\n\
             DynamicSizeWriter sizer;\n\
             if (!encode(sizer)) {{\n\
                 slots[0].i32 = static_cast<std::int32_t>(Status::OperationFailed);\n\
                 return nullptr;\n\
             }}\n\
             const std::size_t requiredSize = sizer.Offset();\n\
             if (requiredSize > std::numeric_limits<std::uint32_t>::max() ||\n\
                 !CheckResultBytes(state, requiredSize)) {{\n\
                 slots[0].i32 = static_cast<std::int32_t>(Status::BufferOverflow);\n\
                 return nullptr;\n\
             }}\n\
             const std::uint32_t required = static_cast<std::uint32_t>(requiredSize);\n\
             if (!WriteDynamicRequired(descriptor, required))\n\
                 return Trap(\"dynamic Core output descriptor changed unexpectedly\");\n\
             if (outputCapacity < required) {{\n\
                 slots[0].i32 = static_cast<std::int32_t>(Status::BufferOverflow);\n\
                 return nullptr;\n\
             }}\n\
             if (!guard.Charge(requiredSize)) return Trap(budgetError);\n\
             std::span<std::uint8_t> payload;\n\
             if (!state->memory.MutableView(outputPointer, requiredSize, payload))\n\
                 return Trap(\"dynamic Core output range changed unexpectedly\");\n\
             WireWriter writer(payload);\n\
             if (!encode(writer) || writer.Offset() != requiredSize)\n\
                 return Trap(\"dynamic Core output size/write mismatch\");\n\
             slots[0].i32 = 0;\n\
             return nullptr;\n\
         }}\n",
        callback = callback,
        api_guard = api_guard,
        api_member = api_member,
        function_name = function.name,
        slot_count = slot_count,
        work = 1 + plan.direct_params.len(),
        output_index = output_index,
        query_type = function.query,
        input_setup = input_setup,
        query_assign = query_assign,
        result_type = function.result,
        encode = encode,
    )
}

fn render_field(
    field: &FieldModel,
    expr: &str,
    owner_prefix: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match &field.ty {
        SemanticType::Bytes => {
            let count = count_field(field).expect("dynamic bytes count field");
            let count_expr = format!("{owner_prefix}{count}");
            format!(
                "{pad}{{\n{pad}    std::uint32_t coreCount = 0;\n{pad}    if (!NormalizeDynamicCount({count_expr}, coreCount)) return false;\n{pad}    if (coreCount != 0 && {expr} == nullptr) return false;\n{pad}    if (!writer.U32(coreCount)) return false;\n{pad}    if (coreCount != 0 && !writer.Bytes(std::span<const std::uint8_t>(reinterpret_cast<const std::uint8_t*>({expr}), coreCount))) return false;\n{pad}}}\n"
            )
        }
        SemanticType::Option { inner } => {
            let presence = presence_field(field).expect("dynamic option presence field");
            let presence_expr = format!("{owner_prefix}{presence}");
            let nested = render_type(inner, expr, None, records, indent + 1);
            // The dynamic stream is length-driven rather than fixed-stride, so an
            // absent option costs its presence flag and nothing more.
            format!(
                "{pad}if (!writer.U32({presence_expr} ? 1u : 0u)) return false;\n{pad}if ({presence_expr}) {{\n{nested}{pad}}}\n"
            )
        }
        SemanticType::List { element } => {
            let count = count_field(field).expect("dynamic list count field");
            let count_expr = format!("{owner_prefix}{count}");
            let index = format!("coreDynamicIndex{indent}");
            let nested = render_type(
                element,
                &format!("{expr}[{index}]"),
                None,
                records,
                indent + 2,
            );
            format!(
                "{pad}{{\n{pad}    std::uint32_t coreCount = 0;\n{pad}    if (!NormalizeDynamicCount({count_expr}, coreCount)) return false;\n{pad}    if (coreCount != 0 && {expr} == nullptr) return false;\n{pad}    if (!writer.U32(coreCount)) return false;\n{pad}    for (std::uint32_t {index} = 0; {index} < coreCount; ++{index}) {{\n{nested}{pad}    }}\n{pad}}}\n"
            )
        }
        _ => render_type(&field.ty, expr, Some(field), records, indent),
    }
}

fn render_type(
    ty: &SemanticType,
    expr: &str,
    field: Option<&FieldModel>,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => {
            let (method, value) = scalar_writer(name, expr);
            format!("{pad}if (!writer.{method}({value})) return false;\n")
        }
        SemanticType::Enum { .. } => format!(
            "{pad}if (!writer.I32(static_cast<std::int32_t>({expr}))) return false;\n"
        ),
        SemanticType::Handle { .. } => format!(
            "{pad}if (!writer.U64(static_cast<std::uint64_t>({expr}))) return false;\n"
        ),
        SemanticType::String => format!(
            "{pad}{{\n{pad}    const std::string_view coreText = {expr} == nullptr ? std::string_view{{}} : std::string_view({expr});\n{pad}    if (coreText.size() > std::numeric_limits<std::uint32_t>::max()) return false;\n{pad}    if (!writer.U32(static_cast<std::uint32_t>(coreText.size()))) return false;\n{pad}    if (!coreText.empty() && !writer.Bytes(std::span<const std::uint8_t>(reinterpret_cast<const std::uint8_t*>(coreText.data()), coreText.size()))) return false;\n{pad}}}\n"
        ),
        SemanticType::Bytes | SemanticType::List { .. } => {
            let field = field.expect("dynamic bytes/list requires field metadata");
            render_field(field, expr, "", records, indent)
        }
        SemanticType::Record { name } => {
            let record = &records[name];
            let implicit = implicit_count_fields(&record.fields);
            record
                .fields
                .iter()
                .filter(|field| !implicit.contains(&field.name))
                .map(|field| {
                    render_field(
                        field,
                        &format!("{expr}.{}", field.name),
                        &format!("{expr}."),
                        records,
                        indent,
                    )
                })
                .collect()
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreDynamicArrayIndex{indent}");
            let nested = render_type(
                element,
                &format!("{expr}[{index}]"),
                None,
                records,
                indent + 1,
            );
            format!(
                "{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n"
            )
        }
        _ => unreachable!("unsupported dynamic-output type"),
    }
}

fn scalar_writer(name: &str, expr: &str) -> (&'static str, String) {
    match name {
        "bool" => ("Bool", expr.to_owned()),
        "f32" => ("F32", expr.to_owned()),
        "f64" => ("F64", expr.to_owned()),
        "i64" | "isize" => ("I64", format!("static_cast<std::int64_t>({expr})")),
        "u64" | "usize" => ("U64", format!("static_cast<std::uint64_t>({expr})")),
        "i8" | "i16" | "i32" => ("I32", format!("static_cast<std::int32_t>({expr})")),
        _ => ("U32", format!("static_cast<std::uint32_t>({expr})")),
    }
}

fn query_expr(ty: &SemanticType, slot: usize, destination: &str) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!("slots[{slot}].i32 != 0"),
            "f32" => format!("slots[{slot}].f32"),
            "f64" => format!("slots[{slot}].f64"),
            "i64" | "u64" | "isize" | "usize" => {
                native_cast(destination, &format!("slots[{slot}].i64"))
            }
            _ => native_cast(destination, &format!("slots[{slot}].i32")),
        },
        SemanticType::Enum { .. } => native_cast(destination, &format!("slots[{slot}].i32")),
        SemanticType::Handle { .. } => native_cast(destination, &format!("slots[{slot}].i64")),
        _ => unreachable!(),
    }
}

fn native_cast(destination: &str, value: &str) -> String {
    format!(
        "static_cast<std::remove_cv_t<std::remove_reference_t<decltype({destination})>>>({value})"
    )
}

fn count_field(field: &FieldModel) -> Option<String> {
    field.metadata.iter().find_map(|metadata| {
        metadata
            .strip_prefix("count-field:")
            .map(ToString::to_string)
    })
}

fn implicit_count_fields(fields: &[FieldModel]) -> BTreeSet<String> {
    fields.iter().filter_map(count_field).collect()
}

fn render_registration(plan: &FunctionPlan, callback: &str) -> String {
    let params = kind_array("params", &plan.direct_params);
    let results = kind_array("results", &plan.direct_results);
    format!(
        "    {{\n{params}{results}        if (!DefineGeneratedDynamicOutput(linker, \"{module}\", \"{name}\",\n                MakeFuncType(params, {pc}, results, {rc}), {callback}, state, error))\n            return false;\n    }}\n",
        params = params,
        results = results,
        module = plan.import_module,
        name = plan.import_name,
        pc = plan.direct_params.len(),
        rc = plan.direct_results.len(),
        callback = callback,
    )
}

fn kind_array(name: &str, kinds: &[CoreType]) -> String {
    if kinds.is_empty() {
        return format!("        const wasm_valkind_t* {name} = nullptr;\n");
    }
    format!(
        "        const wasm_valkind_t {name}[] = {{{}}};\n",
        kinds
            .iter()
            .map(|kind| match kind {
                CoreType::I32 => "WASM_I32",
                CoreType::I64 => "WASM_I64",
                CoreType::F32 => "WASM_F32",
                CoreType::F64 => "WASM_F64",
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn native_member(module: &str) -> String {
    spring_native_codegen::render_host::core_native_member(module)
        .unwrap_or_else(|| panic!("no NativeInterface member mapped for module {module}"))
}

fn native_guard(module: &str) -> String {
    spring_native_codegen::render_host::core_native_guard(module)
        .unwrap_or_else(|| panic!("no NativeInterface member mapped for module {module}"))
}

fn callback_name(module: &str, function: &str) -> String {
    format!(
        "CoreDynamicOutput_{}_{}",
        module.to_snake_case(),
        function.to_snake_case()
    )
}

fn record_index(model: &ApiModel) -> BTreeMap<String, RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records
                .entry(record.name.clone())
                .or_insert_with(|| record.clone());
        }
    }
    records
}
