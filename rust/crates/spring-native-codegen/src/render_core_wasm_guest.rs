fn executable(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    fixed_executable(plan, inputs, outputs, records)
        || render_core_wasm_option_host::eligible(plan, inputs, outputs, records)
        || render_core_wasm_variable_output_host::eligible(plan, inputs, outputs, records)
        || render_core_wasm_variable_io_host::eligible(plan, inputs, outputs, records)
}

pub(crate) fn fixed_executable(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    if plan.source_status != "automatic"
        || !matches!(
            plan.input_strategy,
            InputStrategy::Direct | InputStrategy::FixedInputBuffer
        )
    {
        return false;
    }
    if inputs
        .iter()
        .any(|field| !direct_type(&field.ty) && !fixed_wire_type(&field.ty, records))
    {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status => true,
        ResultStrategy::Packed32 => {
            outputs.len() == 1
                && matches!(
                    outputs[0].ty,
                    SemanticType::Scalar { .. } | SemanticType::Enum { .. }
                )
        }
        ResultStrategy::FixedOutputBuffer { .. } => outputs
            .iter()
            .all(|field| fixed_wire_type(&field.ty, records)),
        ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported => false,
    }
}

fn direct_wrapper_eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
) -> bool {
    if !matches!(plan.input_strategy, InputStrategy::Direct)
        || !inputs.iter().all(|field| direct_type(&field.ty))
    {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status => outputs.is_empty(),
        ResultStrategy::Packed32 => {
            outputs.len() == 1
                && matches!(
                    outputs[0].ty,
                    SemanticType::Scalar { .. } | SemanticType::Enum { .. }
                )
        }
        _ => false,
    }
}

fn fixed_output_wrapper_eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    matches!(plan.input_strategy, InputStrategy::Direct)
        && inputs.iter().all(|field| direct_type(&field.ty))
        && matches!(
            plan.result_strategy,
            ResultStrategy::FixedOutputBuffer { .. }
        )
        && !outputs.is_empty()
        && outputs
            .iter()
            .all(|field| fixed_wire_type(&field.ty, records))
}

fn fixed_input_wrapper_eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    if plan.source_status != "automatic"
        || !matches!(plan.input_strategy, InputStrategy::FixedInputBuffer)
        || !inputs
            .iter()
            .all(|field| direct_type(&field.ty) || fixed_wire_type(&field.ty, records))
        || fixed_input_layout(inputs, records).is_none()
    {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status => outputs.is_empty(),
        ResultStrategy::Packed32 => {
            outputs.len() == 1
                && matches!(
                    outputs[0].ty,
                    SemanticType::Scalar { .. } | SemanticType::Enum { .. }
                )
        }
        ResultStrategy::FixedOutputBuffer { .. } => {
            !outputs.is_empty()
                && outputs
                    .iter()
                    .all(|field| fixed_wire_type(&field.ty, records))
        }
        ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported => false,
    }
}

fn render_raw_import(
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let fn_ident = format!("core_{}", rust_ident(&function.name.to_snake_case()));
    let params = plan
        .direct_params
        .iter()
        .enumerate()
        .map(|(index, ty)| format!("p{index}: {}", core_rust_type(*ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let result = match plan.direct_results.as_slice() {
        [] => String::new(),
        [ty] => format!(" -> {}", core_rust_type(*ty)),
        _ => return String::new(),
    };
    format!(
        "{pad}#[link(wasm_import_module = \"{module}\")]\n\
         {pad}unsafe extern \"C\" {{\n\
         {pad}    #[link_name = \"{import_name}\"]\n\
         {pad}    pub safe fn {fn_ident}({params}){result};\n\
         {pad}}}\n",
        module = plan.import_module,
        import_name = plan.import_name,
    )
}

fn render_direct_wrapper(
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let fn_ident = rust_ident(&function.name.to_snake_case());
    let raw_ident = format!("core_{fn_ident}");
    let params = render_direct_params(&function.inputs);
    let args = render_direct_args(&function.inputs);
    let arity_lint = too_many_arguments_attribute(function.inputs.len(), indent);

    match plan.result_strategy {
        ResultStrategy::Status => format!(
            "{pad}#[inline]\n\
             {pad}{arity_lint}pub fn {fn_ident}({params}) -> Result<()> {{\n\
             {pad}    #[cfg(target_arch = \"wasm32\")]\n\
             {pad}    {{\n\
             {pad}        let status = raw::{raw_ident}({args});\n\
             {pad}        if status == 0 {{ Ok(()) }} else {{ Err(ApiError::new(status)) }}\n\
             {pad}    }}\n\
             {pad}    #[cfg(not(target_arch = \"wasm32\"))]\n\
             {pad}    {{\n\
             {pad}        let _ = ({unused});\n\
             {pad}        Err(unreachable!())\n\
             {pad}    }}\n\
             {pad}}}\n",
            unused = unused_tuple(&function.inputs),
        ),
        ResultStrategy::Packed32 => {
            let output = &function.outputs[0];
            let return_ty = public_rust_type(&output.ty);
            let decode = decode_packed_value(&output.ty, "packed as u32", &pad);
            format!(
                "{pad}#[inline]\n\
                 {pad}{arity_lint}pub fn {fn_ident}({params}) -> Result<{return_ty}> {{\n\
                 {pad}    #[cfg(target_arch = \"wasm32\")]\n\
                 {pad}    {{\n\
                 {pad}        let packed = raw::{raw_ident}({args}) as u64;\n\
                 {pad}        let status = (packed >> 32) as i32;\n\
                 {pad}        if status != 0 {{\n\
                 {pad}            return Err(ApiError::new(status));\n\
                 {pad}        }}\n\
                 {decode}\n\
                 {pad}    }}\n\
                 {pad}    #[cfg(not(target_arch = \"wasm32\"))]\n\
                 {pad}    {{\n\
                 {pad}        let _ = ({unused});\n\
                 {pad}        Err(unreachable!())\n\
                 {pad}    }}\n\
                 {pad}}}\n",
                unused = unused_tuple(&function.inputs),
            )
        }
        _ => String::new(),
    }
}

fn render_fixed_output_wrapper(
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let ResultStrategy::FixedOutputBuffer { bytes, alignment } = plan.result_strategy else {
        return String::new();
    };
    let pad = " ".repeat(indent);
    let fn_ident = rust_ident(&function.name.to_snake_case());
    let raw_ident = format!("core_{fn_ident}");
    let params = render_direct_params(&function.inputs);
    let direct_args = render_direct_args(&function.inputs);
    let call_args = if direct_args.is_empty() {
        "output_pointer".to_owned()
    } else {
        format!("{direct_args}, output_pointer")
    };
    let return_ty = fixed_output_return_type(&function.outputs, records, &fn_ident);
    let value = render_fixed_output_decode(&function.outputs, records);
    let arity_lint = too_many_arguments_attribute(function.inputs.len(), indent);

    format!(
        "{pad}#[inline]\n\
         {pad}{arity_lint}pub fn {fn_ident}({params}) -> Result<{return_ty}> {{\n\
         {pad}    #[cfg(target_arch = \"wasm32\")]\n\
         {pad}    {{\n\
         {pad}        let mut wire = [0u8; {bytes}];\n\
         {pad}        let output_pointer = crate::wasm_output_ptr(&mut wire)?;\n\
         {pad}        let status = raw::{raw_ident}({call_args});\n\
         {pad}        if status != 0 {{\n\
         {pad}            return Err(ApiError::new(status));\n\
         {pad}        }}\n\
         {pad}        let mut cursor = 0usize;\n\
         {pad}        let value = {value};\n\
         {pad}        if !super::__core_wire::finish(&wire, &mut cursor, {alignment}) {{\n\
         {pad}            return Err(ApiError::new(ErrorCode::Internal as i32));\n\
         {pad}        }}\n\
         {pad}        Ok(value)\n\
         {pad}    }}\n\
         {pad}    #[cfg(not(target_arch = \"wasm32\"))]\n\
         {pad}    {{\n\
         {pad}        let _ = ({unused});\n\
         {pad}        Err(unreachable!())\n\
         {pad}    }}\n\
         {pad}}}\n",
        unused = unused_tuple(&function.inputs),
    )
}

fn render_fixed_input_wrapper(
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let fn_ident = rust_ident(&function.name.to_snake_case());
    let raw_ident = format!("core_{fn_ident}");
    let params = render_fixed_params(&function.inputs, records);
    let direct_args = render_direct_args_only(&function.inputs);
    let (input_bytes, input_alignment) = fixed_input_layout(&function.inputs, records)
        .expect("eligible fixed-input guest wrapper has an input layout");
    let mut encode = String::new();
    for field in function
        .inputs
        .iter()
        .filter(|field| !direct_type(&field.ty))
    {
        encode.push_str(&encode_fixed_value(
            &field.ty,
            &rust_ident(&field.name.to_snake_case()),
            records,
            "input_wire",
            "input_cursor",
            indent + 8,
        ));
    }
    let call_prefix = if direct_args.is_empty() {
        "input_pointer".to_owned()
    } else {
        format!("{direct_args}, input_pointer")
    };
    let arity_lint = too_many_arguments_attribute(function.inputs.len(), indent);

    let (return_ty, call_body) = match plan.result_strategy {
        ResultStrategy::Status => (
            "()".to_owned(),
            format!(
                "{pad}        let status = raw::{raw_ident}({call_prefix});\n\
                 {pad}        if status == 0 {{ Ok(()) }} else {{ Err(ApiError::new(status)) }}\n"
            ),
        ),
        ResultStrategy::Packed32 => {
            let output = &function.outputs[0];
            let return_ty = public_rust_type(&output.ty);
            let decode = decode_packed_value(&output.ty, "packed as u32", &pad);
            (
                return_ty,
                format!(
                    "{pad}        let packed = raw::{raw_ident}({call_prefix}) as u64;\n\
                     {pad}        let status = (packed >> 32) as i32;\n\
                     {pad}        if status != 0 {{\n\
                     {pad}            return Err(ApiError::new(status));\n\
                     {pad}        }}\n\
                     {decode}\n"
                ),
            )
        }
        ResultStrategy::FixedOutputBuffer { bytes, alignment } => {
            let return_ty = fixed_output_return_type(&function.outputs, records, &fn_ident);
            let value = render_fixed_output_decode(&function.outputs, records);
            let call_args = format!("{call_prefix}, output_pointer");
            (
                return_ty,
                format!(
                    "{pad}        let mut output_wire = [0u8; {bytes}];\n\
                     {pad}        let output_pointer = crate::wasm_output_ptr(&mut output_wire)?;\n\
                     {pad}        let status = raw::{raw_ident}({call_args});\n\
                     {pad}        if status != 0 {{\n\
                     {pad}            return Err(ApiError::new(status));\n\
                     {pad}        }}\n\
                     {pad}        let wire = output_wire;\n\
                     {pad}        let mut cursor = 0usize;\n\
                     {pad}        let value = {value};\n\
                     {pad}        if !super::__core_wire::finish(&wire, &mut cursor, {alignment}) {{\n\
                     {pad}            return Err(ApiError::new(ErrorCode::Internal as i32));\n\
                     {pad}        }}\n\
                     {pad}        Ok(value)\n"
                ),
            )
        }
        ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported => return String::new(),
    };

    format!(
        "{pad}#[inline]\n\
         {pad}{arity_lint}pub fn {fn_ident}({params}) -> Result<{return_ty}> {{\n\
         {pad}    #[cfg(target_arch = \"wasm32\")]\n\
         {pad}    {{\n\
         {pad}        let mut input_wire = [0u8; {input_bytes}];\n\
         {pad}        let mut input_cursor = 0usize;\n\
         {encode}\
         {pad}        if !super::__core_wire::finish(&input_wire, &mut input_cursor, {input_alignment}) {{\n\
         {pad}            return Err(ApiError::new(ErrorCode::Internal as i32));\n\
         {pad}        }}\n\
         {pad}        let input_pointer = crate::wasm_output_ptr(&mut input_wire)?;\n\
         {call_body}\
         {pad}    }}\n\
         {pad}    #[cfg(not(target_arch = \"wasm32\"))]\n\
         {pad}    {{\n\
         {pad}        let _ = ({unused});\n\
         {pad}        Err(unreachable!())\n\
         {pad}    }}\n\
         {pad}}}\n",
        unused = unused_tuple(&function.inputs),
    )
}

fn render_direct_params(inputs: &[FieldModel]) -> String {
    inputs
        .iter()
        .map(|field| {
            format!(
                "{}: {}",
                rust_ident(&field.name.to_snake_case()),
                public_rust_type(&field.ty)
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn render_fixed_params(inputs: &[FieldModel], records: &BTreeMap<String, RecordModel>) -> String {
    inputs
        .iter()
        .map(|field| {
            let ty = if direct_type(&field.ty) {
                public_rust_type(&field.ty)
            } else {
                public_fixed_rust_type(&field.ty, records)
            };
            format!("{}: {ty}", rust_ident(&field.name.to_snake_case()))
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn render_direct_args(inputs: &[FieldModel]) -> String {
    inputs
        .iter()
        .map(|field| {
            let name = rust_ident(&field.name.to_snake_case());
            lower_direct_arg(&field.ty, &name)
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn render_direct_args_only(inputs: &[FieldModel]) -> String {
    inputs
        .iter()
        .filter(|field| direct_type(&field.ty))
        .map(|field| {
            let name = rust_ident(&field.name.to_snake_case());
            lower_direct_arg(&field.ty, &name)
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn decode_packed_value(ty: &SemanticType, value: &str, pad: &str) -> String {
    match ty {
        SemanticType::Scalar { name } if name == "bool" => format!(
            "{pad}        match {value} {{\n\
             {pad}            0 => Ok(false),\n\
             {pad}            1 => Ok(true),\n\
             {pad}            _ => Err(ApiError::new(ErrorCode::Internal as i32)),\n\
             {pad}        }}"
        ),
        SemanticType::Scalar { name } if name == "f32" => {
            format!("{pad}        Ok(f32::from_bits({value}))")
        }
        SemanticType::Scalar { name } if matches!(name.as_str(), "i8" | "i16" | "i32") => {
            format!(
                "{pad}        Ok({})",
                cast_wire_value(value.to_owned(), "u32", public_rust_type(ty))
            )
        }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => {
            format!(
                "{pad}        Ok({})",
                cast_wire_value(value.to_owned(), "u32", public_rust_type(ty))
            )
        }
        _ => unreachable!(),
    }
}

fn too_many_arguments_attribute(count: usize, indent: usize) -> String {
    let _ = (count, indent);
    String::new()
}

fn render_fixed_output_decode(
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> String {
    let mut decodes = outputs
        .iter()
        .map(|field| decode_fixed_value(&field.ty, records, "wire", "cursor"))
        .collect::<Vec<_>>();
    if decodes.len() == 1 {
        decodes.remove(0)
    } else {
        format!("({})", decodes.join(", "))
    }
}

fn decode_fixed_value(
    ty: &SemanticType,
    records: &BTreeMap<String, RecordModel>,
    wire: &str,
    cursor: &str,
) -> String {
    let internal = "ApiError::new(ErrorCode::Internal as i32)";
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => {
                format!("super::__core_wire::boolean(&{wire}, &mut {cursor}).ok_or({internal})?")
            }
            "f32" => {
                format!("super::__core_wire::f32(&{wire}, &mut {cursor}).ok_or({internal})?")
            }
            "f64" => {
                format!("super::__core_wire::f64(&{wire}, &mut {cursor}).ok_or({internal})?")
            }
            "i64" | "isize" => {
                let value =
                    format!("super::__core_wire::i64(&{wire}, &mut {cursor}).ok_or({internal})?");
                cast_wire_value(value, "i64", public_rust_type(ty))
            }
            "u64" | "usize" => {
                let value =
                    format!("super::__core_wire::u64(&{wire}, &mut {cursor}).ok_or({internal})?");
                cast_wire_value(value, "u64", public_rust_type(ty))
            }
            "i8" | "i16" | "i32" => {
                let value =
                    format!("super::__core_wire::i32(&{wire}, &mut {cursor}).ok_or({internal})?");
                cast_wire_value(value, "i32", public_rust_type(ty))
            }
            _ => {
                let value =
                    format!("super::__core_wire::u32(&{wire}, &mut {cursor}).ok_or({internal})?");
                cast_wire_value(value, "u32", public_rust_type(ty))
            }
        },
        SemanticType::Enum { .. } => {
            format!("super::__core_wire::i32(&{wire}, &mut {cursor}).ok_or({internal})?")
        }
        SemanticType::Handle { .. } => {
            format!("super::__core_wire::u64(&{wire}, &mut {cursor}).ok_or({internal})?")
        }
        SemanticType::FixedArray { element, length } => {
            let values = (0..*length)
                .map(|_| decode_fixed_value(element, records, wire, cursor))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{values}]")
        }
        SemanticType::Record { name } => {
            let record = &records[name];
            let fields = record
                .fields
                .iter()
                .map(|field| {
                    format!(
                        "{}: {}",
                        rust_ident(&field.name.to_snake_case()),
                        decode_fixed_value(&field.ty, records, wire, cursor)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let (_, alignment) = fixed_wire_layout(ty, records)
                .expect("fixed generated guest record has a wire layout");
            format!(
                "{{ let core_value = {} {{ {fields} }}; super::__core_wire::align(&{wire}, &mut {cursor}, {alignment}).ok_or({internal})?; core_value }}",
                rust_type_ident(name),
            )
        }
        SemanticType::Option { inner } => {
            let present =
                format!("super::__core_wire::boolean(&{wire}, &mut {cursor}).ok_or({internal})?");
            let payload = decode_fixed_value(inner, records, wire, cursor);
            format!(
                "{{ let core_present = {present}; let core_value = {payload}; if core_present {{ Some(core_value) }} else {{ None }} }}"
            )
        }
        _ => unreachable!(),
    }
}

fn cast_wire_value(value: String, wire_type: &str, rust_type: String) -> String {
    if wire_type == rust_type {
        value
    } else {
        format!("{value} as {rust_type}")
    }
}

fn option_temp_ident(value: &str) -> String {
    let mut ident = String::from("__core_option_");
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            ident.push(character);
        } else {
            ident.push('_');
        }
    }
    ident
}

fn encode_fixed_value(
    ty: &SemanticType,
    value: &str,
    records: &BTreeMap<String, RecordModel>,
    wire: &str,
    cursor: &str,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let internal = "ApiError::new(ErrorCode::Internal as i32)";
    match ty {
        SemanticType::Scalar { name } => {
            let (method, wire_type) = match name.as_str() {
                "bool" => ("put_boolean", "bool"),
                "f32" => ("put_f32", "f32"),
                "f64" => ("put_f64", "f64"),
                "i64" | "isize" => ("put_i64", "i64"),
                "u64" | "usize" => ("put_u64", "u64"),
                "i8" | "i16" | "i32" => ("put_i32", "i32"),
                _ => ("put_u32", "u32"),
            };
            let value = cast_wire_value(value.to_owned(), wire_type, public_rust_type(ty));
            format!(
                "{pad}super::__core_wire::{method}(&mut {wire}, &mut {cursor}, {value}).ok_or({internal})?;\n"
            )
        }
        SemanticType::Enum { .. } => format!(
            "{pad}super::__core_wire::put_i32(&mut {wire}, &mut {cursor}, {value}).ok_or({internal})?;\n"
        ),
        SemanticType::Handle { .. } => format!(
            "{pad}super::__core_wire::put_u64(&mut {wire}, &mut {cursor}, {value}).ok_or({internal})?;\n"
        ),
        SemanticType::Option { inner } => {
            let temp = option_temp_ident(value);
            let payload = encode_fixed_value(inner, &temp, records, wire, cursor, indent);
            format!(
                "{pad}let {temp} = {value}.unwrap_or_default();\n{pad}super::__core_wire::put_boolean(&mut {wire}, &mut {cursor}, {value}.is_some()).ok_or({internal})?;\n{payload}"
            )
        }
        SemanticType::FixedArray { element, length } => (0..*length)
            .map(|index| {
                encode_fixed_value(
                    element,
                    &format!("{value}[{index}]"),
                    records,
                    wire,
                    cursor,
                    indent,
                )
            })
            .collect::<String>(),
        SemanticType::Record { name } => {
            let mut output = records[name]
                .fields
                .iter()
                .map(|field| {
                    encode_fixed_value(
                        &field.ty,
                        &format!("{value}.{}", rust_ident(&field.name.to_snake_case())),
                        records,
                        wire,
                        cursor,
                        indent,
                    )
                })
                .collect::<String>();
            let (_, alignment) = fixed_wire_layout(ty, records)
                .expect("fixed generated guest record has a wire layout");
            output.push_str(&format!(
                "{pad}super::__core_wire::align(&{wire}, &mut {cursor}, {alignment}).ok_or({internal})?;\n"
            ));
            output
        }
        _ => unreachable!(),
    }
}

fn fixed_output_return_type(
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
    function_ident: &str,
) -> String {
    if outputs.len() == 1 {
        return public_fixed_rust_type(&outputs[0].ty, records);
    }
    if outputs.len() > 6 {
        return format!("{}Value", rust_type_ident(function_ident));
    }
    format!(
        "({})",
        outputs
            .iter()
            .map(|field| public_fixed_rust_type(&field.ty, records))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn render_output_type_aliases(
    executable: &[(&crate::model::FunctionModel, &FunctionPlan)],
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    executable
        .iter()
        .filter(|(function, plan)| {
            function.outputs.len() > 6
                && (fixed_output_wrapper_eligible(
                    plan,
                    &function.inputs,
                    &function.outputs,
                    records,
                ) || fixed_input_wrapper_eligible(
                    plan,
                    &function.inputs,
                    &function.outputs,
                    records,
                ))
        })
        .map(|(function, _)| {
            let fields = function
                .outputs
                .iter()
                .map(|field| public_fixed_rust_type(&field.ty, records))
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "{pad}pub type {}Value = ({fields});\n",
                rust_type_ident(&function.name)
            )
        })
        .collect::<String>()
}

fn render_fixed_record_types(
    executable: &[(&crate::model::FunctionModel, &FunctionPlan)],
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let mut names = BTreeSet::new();
    for (function, plan) in executable {
        if fixed_output_wrapper_eligible(plan, &function.inputs, &function.outputs, records) {
            for field in &function.outputs {
                collect_record_types(&field.ty, records, &mut names);
            }
        }
        if fixed_input_wrapper_eligible(plan, &function.inputs, &function.outputs, records) {
            for field in &function.inputs {
                if !direct_type(&field.ty) {
                    collect_record_types(&field.ty, records, &mut names);
                }
            }
            if matches!(
                plan.result_strategy,
                ResultStrategy::FixedOutputBuffer { .. }
            ) {
                for field in &function.outputs {
                    collect_record_types(&field.ty, records, &mut names);
                }
            }
        }
    }
    if names.is_empty() {
        return String::new();
    }

    let pad = " ".repeat(indent);
    let field_pad = " ".repeat(indent + 4);
    let mut output = String::new();
    for name in names {
        let record = &records[&name];
        output.push_str(&format!(
            "{pad}#[derive(Debug, Clone, Copy, PartialEq)]\n{pad}pub struct {} {{\n",
            rust_type_ident(&name),
        ));
        for field in &record.fields {
            output.push_str(&format!(
                "{field_pad}pub {}: {},\n",
                rust_ident(&field.name.to_snake_case()),
                public_fixed_rust_type(&field.ty, records),
            ));
        }
        output.push_str(&format!("{pad}}}\n\n"));
    }
    output
}

fn collect_record_types(
    ty: &SemanticType,
    records: &BTreeMap<String, RecordModel>,
    names: &mut BTreeSet<String>,
) {
    match ty {
        SemanticType::Record { name } => {
            if names.insert(name.clone())
                && let Some(record) = records.get(name)
            {
                for field in &record.fields {
                    collect_record_types(&field.ty, records, names);
                }
            }
        }
        SemanticType::FixedArray { element, .. } => collect_record_types(element, records, names),
        SemanticType::Option { inner } => collect_record_types(inner, records, names),
        _ => {}
    }
}

fn lower_direct_arg(ty: &SemanticType, name: &str) -> String {
    match ty {
        SemanticType::Scalar { name: scalar } if scalar == "bool" => {
            format!("if {name} {{ 1 }} else {{ 0 }}")
        }
        SemanticType::Scalar { name: scalar } if scalar == "f32" || scalar == "f64" => {
            name.to_owned()
        }
        SemanticType::Scalar { name: scalar } if scalar == "i64" || scalar == "isize" => {
            name.to_owned()
        }
        SemanticType::Scalar { name: scalar } if matches!(scalar.as_str(), "u64" | "usize") => {
            format!("{name} as i64")
        }
        SemanticType::Scalar { name: scalar } if scalar == "i32" => name.to_owned(),
        SemanticType::Scalar { .. } => format!("{name} as i32"),
        SemanticType::Enum { .. } => name.to_owned(),
        SemanticType::Handle { .. } => format!("{name} as i64"),
        _ => unreachable!(),
    }
}

fn public_rust_type(ty: &SemanticType) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => "bool".to_owned(),
            "char" | "u8" => "u8".to_owned(),
            "i8" => "i8".to_owned(),
            "u16" => "u16".to_owned(),
            "i16" => "i16".to_owned(),
            "u32" => "u32".to_owned(),
            "i32" => "i32".to_owned(),
            "u64" | "usize" => "u64".to_owned(),
            "i64" | "isize" => "i64".to_owned(),
            "f32" => "f32".to_owned(),
            "f64" => "f64".to_owned(),
            other => panic!("unsupported direct Core scalar {other}"),
        },
        SemanticType::Enum { .. } => "i32".to_owned(),
        SemanticType::Handle { .. } => "u64".to_owned(),
        _ => panic!("non-direct type requested for direct Core wrapper"),
    }
}

fn public_fixed_rust_type(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> String {
    match ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. } => {
            public_rust_type(ty)
        }
        SemanticType::FixedArray { element, length } => {
            format!("[{}; {length}]", public_fixed_rust_type(element, records))
        }
        SemanticType::Record { name } => {
            debug_assert!(records.contains_key(name));
            rust_type_ident(name)
        }
        SemanticType::Option { inner } => {
            format!("Option<{}>", public_fixed_rust_type(inner, records))
        }
        _ => panic!("non-fixed type requested for fixed Core wrapper"),
    }
}

fn core_rust_type(ty: CoreType) -> &'static str {
    match ty {
        CoreType::I32 => "i32",
        CoreType::I64 => "i64",
        CoreType::F32 => "f32",
        CoreType::F64 => "f64",
    }
}

fn direct_type(ty: &SemanticType) -> bool {
    matches!(
        ty,
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. }
    )
}

fn fixed_wire_type(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. } => {
            true
        }
        SemanticType::FixedArray { element, length } => {
            *length <= 64 && fixed_wire_type(element, records)
        }
        SemanticType::Record { name } => records.get(name).is_some_and(|record| {
            record
                .fields
                .iter()
                .all(|field| fixed_wire_type(&field.ty, records))
        }),
        SemanticType::Option { inner } => fixed_wire_type(inner, records),
        _ => false,
    }
}

fn fixed_wire_layout(
    ty: &SemanticType,
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "i64" | "u64" | "isize" | "usize" | "f64" => Some((8, 8)),
            _ => Some((4, 4)),
        },
        SemanticType::Enum { .. } => Some((4, 4)),
        SemanticType::Handle { .. } => Some((8, 8)),
        SemanticType::FixedArray { element, length } => {
            let (bytes, alignment) = fixed_wire_layout(element, records)?;
            Some((bytes.checked_mul(u32::try_from(*length).ok()?)?, alignment))
        }
        SemanticType::Record { name } => {
            let record = records.get(name)?;
            layout_fields(&record.fields, records)
        }
        SemanticType::Option { inner } => {
            let (bytes, alignment) = fixed_wire_layout(inner, records)?;
            Some((bytes.checked_add(4)?, alignment.max(4)))
        }
        _ => None,
    }
}

fn fixed_input_layout(
    fields: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    let fixed = fields
        .iter()
        .filter(|field| !direct_type(&field.ty))
        .cloned()
        .collect::<Vec<_>>();
    if fixed.is_empty() {
        None
    } else {
        layout_fields(&fixed, records)
    }
}

fn layout_fields(
    fields: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> Option<(u32, u32)> {
    let mut bytes = 0u32;
    let mut alignment = 1u32;
    for field in fields {
        let (field_bytes, field_alignment) = fixed_wire_layout(&field.ty, records)?;
        bytes = align_up(bytes, field_alignment).checked_add(field_bytes)?;
        alignment = alignment.max(field_alignment);
    }
    Some((align_up(bytes, alignment), alignment))
}

fn align_up(value: u32, alignment: u32) -> u32 {
    debug_assert!(alignment.is_power_of_two());
    (value + alignment - 1) & !(alignment - 1)
}

fn unused_tuple(inputs: &[FieldModel]) -> String {
    if inputs.is_empty() {
        "()".to_owned()
    } else {
        let names = inputs
            .iter()
            .map(|field| rust_ident(&field.name.to_snake_case()))
            .collect::<Vec<_>>()
            .join(", ");
        if inputs.len() == 1 {
            format!("{names},")
        } else {
            names
        }
    }
}

fn rust_ident(value: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
        "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do",
        "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
    ];
    if KEYWORDS.contains(&value) {
        format!("{value}_")
    } else {
        value.to_owned()
    }
}

fn rust_type_ident(value: &str) -> String {
    rust_ident(&value.to_upper_camel_case())
}

fn record_index(model: &ApiModel) -> BTreeMap<String, RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records
                .entry(record.name.clone())
                .or_insert_with(|| record.clone());
        }
    }
    records
}
