//! Generate the Rust guest-facing Core ABI layer. The generated raw surface
//! mirrors only imports accepted by the production fast-path registry; known
//! allocation-heavy variable-input scaffolding is intentionally excluded.

use heck::ToSnakeCase;
use std::collections::BTreeMap;

use crate::model::{ApiModel, FieldModel, RecordModel, SemanticType};
use crate::render_core_wasm::{self, CoreType, FunctionPlan, InputStrategy, ResultStrategy};
use crate::render_core_wasm_option_host;
use crate::render_core_wasm_variable_output_host;

pub fn render(model: &ApiModel) -> String {
    let records = record_index(model);
    let plans = render_core_wasm::plan(model)
        .functions
        .into_iter()
        .map(|plan| ((plan.module.clone(), plan.function.clone()), plan))
        .collect::<BTreeMap<_, _>>();

    let mut output = String::from(
        "// @generated by spring-api-codegen; do not edit.\n\n\
         // This module is included by spring-wasm-core. Raw imports are public\n\
         // for advanced use; ordinary guest code should use safe generated or\n\
         // specialized crate APIs. Only production-fast imports appear here.\n\n",
    );

    for module in &model.modules {
        let executable = module
            .functions
            .iter()
            .filter_map(|function| {
                let plan = plans.get(&(module.name.clone(), function.name.clone()))?;
                executable(plan, &function.inputs, &function.outputs, &records)
                    .then_some((function, plan))
            })
            .collect::<Vec<_>>();
        if executable.is_empty() {
            continue;
        }

        let module_ident = rust_ident(&module.name.to_snake_case());
        output.push_str(&format!("pub mod {module_ident} {{\n"));
        output.push_str("    use crate::{ApiError, ErrorCode, Result};\n\n");
        output.push_str("    #[cfg(target_arch = \"wasm32\")]\n    pub mod raw {\n");
        for (function, plan) in &executable {
            output.push_str(&render_raw_import(function, plan, 8));
        }
        output.push_str("    }\n\n");

        for (function, plan) in &executable {
            if direct_wrapper_eligible(plan, &function.inputs, &function.outputs) {
                output.push_str(&render_direct_wrapper(function, plan, 4));
                output.push('\n');
            }
        }
        output.push_str("}\n\n");
    }

    output
}

fn executable(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    fixed_executable(plan, inputs, outputs, records)
        || render_core_wasm_option_host::eligible(plan, inputs, outputs, records)
        || render_core_wasm_variable_output_host::eligible(plan, inputs, outputs, records)
}

fn fixed_executable(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    if plan.source_status != "automatic"
        || !matches!(
            plan.input_strategy,
            InputStrategy::Direct | InputStrategy::FixedInputBuffer
        )
    {
        return false;
    }
    if inputs
        .iter()
        .any(|field| !direct_type(&field.ty) && !fixed_wire_type(&field.ty, records))
    {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status => true,
        ResultStrategy::Packed32 => {
            outputs.len() == 1
                && matches!(outputs[0].ty, SemanticType::Scalar { .. } | SemanticType::Enum { .. })
        }
        ResultStrategy::FixedOutputBuffer { .. } => {
            outputs.iter().all(|field| fixed_wire_type(&field.ty, records))
        }
        ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported => false,
    }
}

fn direct_wrapper_eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
) -> bool {
    if !matches!(plan.input_strategy, InputStrategy::Direct)
        || !inputs.iter().all(|field| direct_type(&field.ty))
    {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status => outputs.is_empty(),
        ResultStrategy::Packed32 => {
            outputs.len() == 1
                && matches!(outputs[0].ty, SemanticType::Scalar { .. } | SemanticType::Enum { .. })
        }
        _ => false,
    }
}

fn render_raw_import(
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let fn_ident = format!("core_{}", rust_ident(&function.name.to_snake_case()));
    let params = plan
        .direct_params
        .iter()
        .enumerate()
        .map(|(index, ty)| format!("p{index}: {}", core_rust_type(*ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let result = match plan.direct_results.as_slice() {
        [] => String::new(),
        [ty] => format!(" -> {}", core_rust_type(*ty)),
        _ => return String::new(),
    };
    format!(
        "{pad}#[link(wasm_import_module = \"{module}\")]\n\
         {pad}extern \"C\" {{\n\
         {pad}    #[link_name = \"{import_name}\"]\n\
         {pad}    pub fn {fn_ident}({params}){result};\n\
         {pad}}}\n",
        module = plan.import_module,
        import_name = plan.import_name,
    )
}

fn render_direct_wrapper(
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let fn_ident = rust_ident(&function.name.to_snake_case());
    let raw_ident = format!("core_{fn_ident}");
    let params = function
        .inputs
        .iter()
        .map(|field| {
            format!(
                "{}: {}",
                rust_ident(&field.name.to_snake_case()),
                public_rust_type(&field.ty)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let args = function
        .inputs
        .iter()
        .map(|field| {
            let name = rust_ident(&field.name.to_snake_case());
            lower_direct_arg(&field.ty, &name)
        })
        .collect::<Vec<_>>()
        .join(", ");

    match plan.result_strategy {
        ResultStrategy::Status => format!(
            "{pad}#[inline]\n\
             {pad}pub fn {fn_ident}({params}) -> Result<()> {{\n\
             {pad}    #[cfg(target_arch = \"wasm32\")]\n\
             {pad}    {{\n\
             {pad}        // SAFETY: generated scalar-only Core signature.\n\
             {pad}        let status = unsafe {{ raw::{raw_ident}({args}) }};\n\
             {pad}        return if status == 0 {{ Ok(()) }} else {{ Err(ApiError::new(status)) }};\n\
             {pad}    }}\n\
             {pad}    #[cfg(not(target_arch = \"wasm32\"))]\n\
             {pad}    {{\n\
             {pad}        let _ = ({unused});\n\
             {pad}        Err(ApiError::new(ErrorCode::UnsupportedHostTarget as i32))\n\
             {pad}    }}\n\
             {pad}}}\n",
            unused = unused_tuple(&function.inputs),
        ),
        ResultStrategy::Packed32 => {
            let output = &function.outputs[0];
            let return_ty = public_rust_type(&output.ty);
            let decode = decode_packed_value(&output.ty, "packed as u32", &pad);
            format!(
                "{pad}#[inline]\n\
                 {pad}pub fn {fn_ident}({params}) -> Result<{return_ty}> {{\n\
                 {pad}    #[cfg(target_arch = \"wasm32\")]\n\
                 {pad}    {{\n\
                 {pad}        // SAFETY: generated scalar-only Core signature.\n\
                 {pad}        let packed = unsafe {{ raw::{raw_ident}({args}) }} as u64;\n\
                 {pad}        let status = (packed >> 32) as u32 as i32;\n\
                 {pad}        if status != 0 {{\n\
                 {pad}            return Err(ApiError::new(status));\n\
                 {pad}        }}\n\
                 {decode}\n\
                 {pad}    }}\n\
                 {pad}    #[cfg(not(target_arch = \"wasm32\"))]\n\
                 {pad}    {{\n\
                 {pad}        let _ = ({unused});\n\
                 {pad}        Err(ApiError::new(ErrorCode::UnsupportedHostTarget as i32))\n\
                 {pad}    }}\n\
                 {pad}}}\n",
                unused = unused_tuple(&function.inputs),
            )
        }
        _ => String::new(),
    }
}

fn decode_packed_value(ty: &SemanticType, value: &str, pad: &str) -> String {
    match ty {
        SemanticType::Scalar { name } if name == "bool" => format!(
            "{pad}        return match {value} {{\n\
             {pad}            0 => Ok(false),\n\
             {pad}            1 => Ok(true),\n\
             {pad}            _ => Err(ApiError::new(ErrorCode::Internal as i32)),\n\
             {pad}        }};"
        ),
        SemanticType::Scalar { name } if name == "f32" => {
            format!("{pad}        return Ok(f32::from_bits({value}));")
        }
        SemanticType::Scalar { name }
            if matches!(name.as_str(), "i8" | "i16" | "i32") => {
                let rust = public_rust_type(ty);
                format!("{pad}        return Ok(({value} as i32) as {rust});")
            }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => {
            let rust = public_rust_type(ty);
            format!("{pad}        return Ok(({value}) as {rust});")
        }
        _ => unreachable!(),
    }
}

fn lower_direct_arg(ty: &SemanticType, name: &str) -> String {
    match ty {
        SemanticType::Scalar { name: scalar } if scalar == "bool" => {
            format!("if {name} {{ 1 }} else {{ 0 }}")
        }
        SemanticType::Scalar { name: scalar } if scalar == "f32" || scalar == "f64" => {
            name.to_owned()
        }
        SemanticType::Scalar { name: scalar }
            if matches!(scalar.as_str(), "i64" | "u64" | "isize" | "usize") => {
                format!("{name} as i64")
            }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => format!("{name} as i32"),
        SemanticType::Handle { .. } => format!("{name} as i64"),
        _ => unreachable!(),
    }
}

fn public_rust_type(ty: &SemanticType) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => "bool".to_owned(),
            "char" | "u8" => "u8".to_owned(),
            "i8" => "i8".to_owned(),
            "u16" => "u16".to_owned(),
            "i16" => "i16".to_owned(),
            "u32" => "u32".to_owned(),
            "i32" => "i32".to_owned(),
            "u64" | "usize" => "u64".to_owned(),
            "i64" | "isize" => "i64".to_owned(),
            "f32" => "f32".to_owned(),
            "f64" => "f64".to_owned(),
            other => panic!("unsupported direct Core scalar {other}"),
        },
        SemanticType::Enum { .. } => "i32".to_owned(),
        SemanticType::Handle { .. } => "u64".to_owned(),
        _ => panic!("non-direct type requested for direct Core wrapper"),
    }
}

fn core_rust_type(ty: CoreType) -> &'static str {
    match ty {
        CoreType::I32 => "i32",
        CoreType::I64 => "i64",
        CoreType::F32 => "f32",
        CoreType::F64 => "f64",
    }
}

fn direct_type(ty: &SemanticType) -> bool {
    matches!(
        ty,
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. }
    )
}

fn fixed_wire_type(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } | SemanticType::Handle { .. } => true,
        SemanticType::FixedArray { element, length } => {
            *length <= 64 && fixed_wire_type(element, records)
        }
        SemanticType::Record { name } => records
            .get(name)
            .is_some_and(|record| record.fields.iter().all(|field| fixed_wire_type(&field.ty, records))),
        _ => false,
    }
}

fn unused_tuple(inputs: &[FieldModel]) -> String {
    if inputs.is_empty() {
        "()".to_owned()
    } else {
        let names = inputs
            .iter()
            .map(|field| rust_ident(&field.name.to_snake_case()))
            .collect::<Vec<_>>()
            .join(", ");
        if inputs.len() == 1 {
            format!("{names},")
        } else {
            names
        }
    }
}

fn rust_ident(value: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false",
        "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
        "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true",
        "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract",
        "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized",
        "virtual", "yield", "try",
    ];
    if KEYWORDS.contains(&value) {
        format!("{value}_")
    } else {
        value.to_owned()
    }
}

fn record_index(model: &ApiModel) -> BTreeMap<String, RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records.entry(record.name.clone()).or_insert_with(|| record.clone());
        }
    }
    records
}
