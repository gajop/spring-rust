//! Generate allocation-free Wasmtime/Core host callbacks for the conservative
//! automatic subset of the semantic API.

use heck::ToSnakeCase;
use std::collections::BTreeMap;

use crate::model::{ApiModel, FieldModel, RecordModel, SemanticType};
use crate::render_core_wasm::{self, CoreType, FunctionPlan, InputStrategy, ResultStrategy};

pub fn render_header() -> String {
    r#"/* @generated by spring-api-codegen; do not edit. */
#pragma once

#include <string>

#include "WasmInterface/core/bindings/WasmCoreBindings.h"

namespace recoil::wasm::core::generated {

// Register every callout for which the generator can prove a fixed Core ABI.
// Handwritten/specialized imports may be registered separately before this.
bool RegisterGeneratedImports(wasmtime_linker_t* linker, HostState* state, std::string& error);

} // namespace recoil::wasm::core::generated
"#
    .to_owned()
}

pub fn render_cpp(model: &ApiModel) -> String {
    let declarations = model
        .modules
        .iter()
        .map(|module| {
            format!(
                "bool RegisterGeneratedImports_{}(wasmtime_linker_t*, HostState*, std::string&);",
                module_registration_name(&module.name)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let registrations = model
        .modules
        .iter()
        .map(|module| {
            format!(
                "    if (!RegisterGeneratedImports_{}(linker, state, error))\n        return false;",
                module_registration_name(&module.name)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */

#include "wasm/generated/WasmCoreGeneratedBindings.h"

namespace recoil::wasm::core::generated {{

{declarations}

bool RegisterGeneratedImports(wasmtime_linker_t* linker, HostState* state, std::string& error)
{{
    if (linker == nullptr || state == nullptr || state->native == nullptr) {{
        error = "cannot register generated Core Wasm imports without linker/host/native API";
        return false;
    }}
{registrations}
    return true;
}}

}} // namespace recoil::wasm::core::generated
"#,
        declarations = declarations,
        registrations = registrations,
    )
}

pub fn render_module_cpp(model: &ApiModel, module_name: &str) -> String {
    let records = record_index(model);
    let plans = render_core_wasm::plan(model)
        .functions
        .into_iter()
        .map(|plan| ((plan.module.clone(), plan.function.clone()), plan))
        .collect::<BTreeMap<_, _>>();
    let module = model
        .modules
        .iter()
        .find(|module| module.name == module_name)
        .unwrap_or_else(|| panic!("unknown Core generated module {module_name}"));
    let mut callbacks = String::new();
    let mut registrations = String::new();
    let mut generated_count = 0usize;
    for function in &module.functions {
        let Some(plan) = plans.get(&(module.name.clone(), function.name.clone())) else {
            continue;
        };
        if !eligible(plan, &function.inputs, &function.outputs, &records) {
            continue;
        }
        generated_count += 1;
        callbacks.push_str(&render_callback(&module.name, function, plan, &records));
        callbacks.push('\n');
        registrations.push_str(&render_registration(
            plan,
            &callback_name(&module.name, &function.name),
        ));
    }
    format_module_cpp(module_name, callbacks, registrations, generated_count)
}

