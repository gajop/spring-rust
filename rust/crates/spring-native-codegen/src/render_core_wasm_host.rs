//! Generate allocation-free Wasmtime/Core host callbacks for the conservative
//! automatic subset of the semantic API.

use heck::{ToLowerCamelCase, ToSnakeCase};
use std::collections::BTreeMap;

use crate::model::{ApiModel, FieldModel, RecordModel, SemanticType};
use crate::render_core_wasm::{self, CoreType, FunctionPlan, InputStrategy, ResultStrategy};

pub fn render_header() -> String {
    r#"/* @generated by spring-api-codegen; do not edit. */
#pragma once

#include <string>

#include "WasmInterface/WasmCoreBindings.h"

namespace recoil::wasm::core::generated {

// Register every callout for which the generator can prove a fixed Core ABI.
// Handwritten/specialized imports may be registered separately before this.
bool RegisterGeneratedImports(wasmtime_linker_t* linker, HostState* state, std::string& error);

} // namespace recoil::wasm::core::generated
"#
    .to_owned()
}

pub fn render_cpp(model: &ApiModel) -> String {
    let records = record_index(model);
    let plans = render_core_wasm::plan(model)
        .functions
        .into_iter()
        .map(|plan| ((plan.module.clone(), plan.function.clone()), plan))
        .collect::<BTreeMap<_, _>>();

    let mut callbacks = String::new();
    let mut registrations = String::new();
    let mut generated_count = 0usize;

    for module in &model.modules {
        for function in &module.functions {
            let Some(plan) = plans.get(&(module.name.clone(), function.name.clone())) else {
                continue;
            };
            if !eligible(plan, &function.inputs, &function.outputs, &records) {
                continue;
            }
            generated_count += 1;
            callbacks.push_str(&render_callback(
                &module.name,
                function,
                plan,
                &records,
            ));
            callbacks.push('\n');
            registrations.push_str(&render_registration(plan, &callback_name(&module.name, &function.name)));
        }
    }

    format!(
        r#"/* @generated by spring-api-codegen; do not edit. */

#include "wasm/generated/WasmCoreGeneratedBindings.h"

#include <array>
#include <bit>
#include <cstdint>
#include <span>
#include <string_view>

#include "NativeInterface/NativeInterface.h"
#include "WasmInterface/WasmCoreAbi.h"
#include "WasmInterface/WasmCoreGeneratedSupport.h"
#include "WasmInterface/WasmCoreWire.h"

namespace recoil::wasm::core::generated {{
namespace {{

bool DefineGenerated(wasmtime_linker_t* linker, const char* moduleName,
    const char* functionName, wasm_functype_t* type,
    wasmtime_func_unchecked_callback_t callback, HostState* state, std::string& error)
{{
    wasmtime_error_t* defineError = wasmtime_linker_define_func_unchecked(
        linker,
        moduleName, std::char_traits<char>::length(moduleName),
        functionName, std::char_traits<char>::length(functionName),
        type, callback, state, nullptr);
    wasm_functype_delete(type);
    if (defineError == nullptr)
        return true;
    error = ErrorMessage(defineError);
    return false;
}}

{callbacks}
}} // namespace

bool RegisterGeneratedImports(wasmtime_linker_t* linker, HostState* state, std::string& error)
{{
    if (linker == nullptr || state == nullptr || state->native == nullptr) {{
        error = "cannot register generated Core Wasm imports without linker/host/native API";
        return false;
    }}
{registrations}
    return true;
}}

static_assert({generated_count} >= 0, "generated Core Wasm callback count");

}} // namespace recoil::wasm::core::generated
"#,
        callbacks = callbacks,
        registrations = registrations,
        generated_count = generated_count,
    )
}

fn eligible(
    plan: &FunctionPlan,
    inputs: &[FieldModel],
    outputs: &[FieldModel],
    records: &BTreeMap<String, RecordModel>,
) -> bool {
    if plan.source_status != "automatic" || !matches!(plan.input_strategy, InputStrategy::Direct) {
        return false;
    }
    if inputs.iter().any(|field| !direct_query_type(&field.ty)) {
        return false;
    }
    match plan.result_strategy {
        ResultStrategy::Status | ResultStrategy::Packed32 => true,
        ResultStrategy::FixedOutputBuffer { .. } => {
            outputs.iter().all(|field| wire_type(&field.ty, records))
        }
        ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported => false,
    }
}

fn direct_query_type(ty: &SemanticType) -> bool {
    matches!(
        ty,
        SemanticType::Scalar { .. } | SemanticType::Enum { .. }
    )
}

fn wire_type(ty: &SemanticType, records: &BTreeMap<String, RecordModel>) -> bool {
    match ty {
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => true,
        SemanticType::FixedArray { element, length } => *length <= 64 && wire_type(element, records),
        SemanticType::Record { name } => records
            .get(name)
            .is_some_and(|record| record.fields.iter().all(|field| wire_type(&field.ty, records))),
        _ => false,
    }
}

fn render_callback(
    module_name: &str,
    function: &crate::model::FunctionModel,
    plan: &FunctionPlan,
    records: &BTreeMap<String, RecordModel>,
) -> String {
    let callback = callback_name(module_name, &function.name);
    let api_member = native_member(module_name);
    let slot_count = plan.direct_params.len().max(plan.direct_results.len());
    let work = 1 + plan.direct_params.len() as u64;
    let mut body = String::new();

    body.push_str(&format!(
        "wasm_trap_t* {callback}(void* environment, wasmtime_caller_t* caller,\n    wasmtime_val_raw_t* slots, std::size_t slotCount)\n{{\n    auto* state = static_cast<HostState*>(environment);\n    if (state == nullptr || state->native == nullptr || state->native->{api_member} == nullptr ||\n        state->native->{api_member}->{function_name} == nullptr)\n        return Trap(\"{function_name} generated Core binding is unavailable\");\n    if ({slot_count} != 0 && (slots == nullptr || slotCount != {slot_count}))\n        return Trap(\"{function_name} generated Core ABI signature mismatch\");\n    if ({slot_count} == 0 && slotCount != 0)\n        return Trap(\"{function_name} generated Core ABI signature mismatch\");\n\n    std::string budgetError;\n    ImportGuard guard(state, {work}u, budgetError);\n    if (!guard.Ok())\n        return Trap(budgetError);\n",
        callback = callback,
        api_member = api_member,
        function_name = function.name,
        slot_count = slot_count,
        work = work,
    ));

    if let ResultStrategy::FixedOutputBuffer { bytes, .. } = plan.result_strategy {
        let output_index = function.inputs.len();
        body.push_str(&format!(
            "\n    std::string memoryError;\n    if (!EnsureMemory(state, caller, memoryError))\n        return Trap(memoryError);\n    const std::uint32_t output = static_cast<std::uint32_t>(slots[{output_index}].i32);\n    if (!state->memory.Contains(output, {bytes}u)) {{\n        slots[0].i32 = static_cast<std::int32_t>(Status::OutOfBounds);\n        return nullptr;\n    }}\n",
            output_index = output_index,
            bytes = bytes,
        ));
    }

    body.push_str(&format!("\n    {} query{{}};\n", function.query));
    for (index, field) in function.inputs.iter().enumerate() {
        body.push_str(&format!(
            "    query.{field} = {expr};\n",
            field = field.name,
            expr = query_expr(&field.ty, index, &format!("query.{}", field.name)),
        ));
    }
    body.push_str(&format!(
        "    {} result{{}};\n    state->native->{api_member}->{function_name}(&query, &result);\n    const std::int32_t errorCode = NativeErrorCode(result.error);\n",
        function.result,
        api_member = api_member,
        function_name = function.name,
    ));

    match plan.result_strategy {
        ResultStrategy::Status => {
            body.push_str("    slots[0].i32 = errorCode;\n    return nullptr;\n");
        }
        ResultStrategy::Packed32 => {
            let field = &function.outputs[0];
            let value = packed32_expr(&field.ty, &format!("result.{}", field.name));
            body.push_str(&format!(
                "    slots[0].i64 = static_cast<std::int64_t>(PackU32({value}, errorCode));\n    return nullptr;\n",
                value = value,
            ));
        }
        ResultStrategy::FixedOutputBuffer { bytes, alignment } => {
            body.push_str(
                "    if (errorCode != 0) {\n        slots[0].i32 = errorCode;\n        return nullptr;\n    }\n",
            );
            body.push_str(&format!(
                "    std::array<std::uint8_t, {bytes}> wire{{}};\n    WireWriter writer(wire);\n",
                bytes = bytes,
            ));
            for field in &function.outputs {
                body.push_str(&render_wire_write(
                    &field.ty,
                    &format!("result.{}", field.name),
                    records,
                    1,
                ));
            }
            body.push_str(&format!(
                "    if (!writer.Finish({alignment}u))\n        return Trap(\"generated Core wire layout mismatch for {function_name}\");\n    if (!state->memory.Write(output, wire.data(), wire.size()))\n        return Trap(\"generated Core output range changed unexpectedly\");\n    slots[0].i32 = 0;\n    return nullptr;\n",
                alignment = alignment,
                function_name = function.name,
            ));
        }
        ResultStrategy::VariableOutputBuffer | ResultStrategy::Unsupported => unreachable!(),
    }
    body.push_str("}\n");
    body
}

fn query_expr(ty: &SemanticType, slot: usize, destination: &str) -> String {
    match ty {
        SemanticType::Scalar { name } => match name.as_str() {
            "bool" => format!("slots[{slot}].i32 != 0"),
            "f32" => format!("slots[{slot}].f32"),
            "f64" => format!("slots[{slot}].f64"),
            "i64" | "u64" | "isize" | "usize" => {
                format!("static_cast<decltype({destination})>(slots[{slot}].i64)")
            }
            _ => format!("static_cast<decltype({destination})>(slots[{slot}].i32)"),
        },
        SemanticType::Enum { .. } => {
            format!("static_cast<decltype({destination})>(slots[{slot}].i32)")
        }
        _ => unreachable!(),
    }
}

fn packed32_expr(ty: &SemanticType, value: &str) -> String {
    match ty {
        SemanticType::Scalar { name } if name == "f32" => {
            format!("std::bit_cast<std::uint32_t>({value})")
        }
        SemanticType::Scalar { name } if name == "bool" => {
            format!("static_cast<std::uint32_t>({value} ? 1u : 0u)")
        }
        SemanticType::Scalar { .. } | SemanticType::Enum { .. } => {
            format!("static_cast<std::uint32_t>({value})")
        }
        _ => unreachable!(),
    }
}

fn render_wire_write(
    ty: &SemanticType,
    value: &str,
    records: &BTreeMap<String, RecordModel>,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    match ty {
        SemanticType::Scalar { name } => {
            let method = match name.as_str() {
                "bool" => "Bool",
                "f32" => "F32",
                "f64" => "F64",
                "i64" => "I64",
                "u64" | "usize" => "U64",
                "i8" | "i16" | "i32" | "isize" => "I32",
                _ => "U32",
            };
            format!(
                "{pad}if (!writer.{method}({value})) return Trap(\"generated Core wire overflow\");\n"
            )
        }
        SemanticType::Enum { .. } => format!(
            "{pad}if (!writer.I32(static_cast<std::int32_t>({value}))) return Trap(\"generated Core wire overflow\");\n"
        ),
        SemanticType::Record { name } => {
            let record = &records[name];
            record
                .fields
                .iter()
                .map(|field| {
                    render_wire_write(
                        &field.ty,
                        &format!("{value}.{}", field.name),
                        records,
                        indent,
                    )
                })
                .collect::<String>()
        }
        SemanticType::FixedArray { element, length } => {
            let index = format!("coreIndex{}", indent);
            let nested = render_wire_write(element, &format!("{value}[{index}]"), records, indent + 1);
            format!(
                "{pad}for (std::size_t {index} = 0; {index} < {length}u; ++{index}) {{\n{nested}{pad}}}\n"
            )
        }
        _ => unreachable!(),
    }
}

fn render_registration(plan: &FunctionPlan, callback: &str) -> String {
    let params = kind_array("params", &plan.direct_params);
    let results = kind_array("results", &plan.direct_results);
    format!(
        "    {{\n{params}{results}        if (!DefineGenerated(linker, \"{module}\", \"{name}\",\n                MakeFuncType(params, {param_count}, results, {result_count}), {callback}, state, error))\n            return false;\n    }}\n",
        params = params,
        results = results,
        module = plan.import_module,
        name = plan.import_name,
        param_count = plan.direct_params.len(),
        result_count = plan.direct_results.len(),
        callback = callback,
    )
}

fn kind_array(name: &str, kinds: &[CoreType]) -> String {
    if kinds.is_empty() {
        return format!("        const wasm_valkind_t* {name} = nullptr;\n");
    }
    format!(
        "        const wasm_valkind_t {name}[] = {{{}}};\n",
        kinds
            .iter()
            .map(|kind| match kind {
                CoreType::I32 => "WASM_I32",
                CoreType::I64 => "WASM_I64",
                CoreType::F32 => "WASM_F32",
                CoreType::F64 => "WASM_F64",
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn native_member(module: &str) -> String {
    match module {
        "camera" => "cameraApi".to_owned(),
        "sound" => "soundApi".to_owned(),
        other => other.to_lower_camel_case(),
    }
}

fn callback_name(module: &str, function: &str) -> String {
    format!(
        "Core_{}_{}",
        module.to_snake_case(),
        function.to_snake_case()
    )
}

fn record_index(model: &ApiModel) -> BTreeMap<String, RecordModel> {
    let mut records = BTreeMap::new();
    for module in &model.modules {
        for record in &module.records {
            records.entry(record.name.clone()).or_insert_with(|| record.clone());
        }
    }
    records
}
